'use strict';

/**
 * Очистка названий из внешних источников.
 *
 * ── Зачем ─────────────────────────────────────────────────────────────────
 * Парсеры внешних площадок приносят название вместе с украшением:
 * «🌐 АО "СЕГЕЖСКИЙ ЦБК"», «🔥 Тендер дня». Эмодзи доезжали до карточек,
 * писем и ТКП — а в клиентском документе и в интерфейсе допустим только
 * русский текст (правило проекта, verify-gate).
 *
 * Дополнительно убираем невидимые символы (zero-width, BOM) и «мусорные»
 * пробелы: они ломают сравнение названий и дедупликацию контрагентов.
 *
 * Функция идемпотентна: корректная строка возвращается без изменений.
 */

// Эмодзи и пиктограммы: основные блоки + вариационные селекторы + ZWJ.
const EMOJI = /[\u{1F300}-\u{1FAFF}\u{1F000}-\u{1F2FF}\u{2600}-\u{27BF}\u{2B00}-\u{2BFF}\u{FE00}-\u{FE0F}\u{200D}\u{20E3}]/gu;
// Невидимое и управляющее.
const INVISIBLE = /[\u0000-\u0008\u000B\u000C\u000E-\u001F\u007F\u200B-\u200F\u202A-\u202E\u2060-\u2064\uFEFF]/g;

/**
 * Чистит название от эмодзи и невидимых символов.
 *
 * @param {*} value
 * @returns {string}
 */
function cleanName(value) {
  if (value == null) return '';
  let s = String(value);
  s = s.replace(EMOJI, '');
  s = s.replace(INVISIBLE, '');
  // Схлопываем пробелы, включая неразрывные.
  s = s.replace(/[\s\u00A0]+/g, ' ');
  return s.trim();
}

/**
 * Есть ли в строке эмодзи (для валидации и логов).
 *
 * @param {*} value
 * @returns {boolean}
 */
function hasEmoji(value) {
  if (value == null) return false;
  EMOJI.lastIndex = 0;
  return EMOJI.test(String(value));
}

module.exports = { cleanName, hasEmoji };
