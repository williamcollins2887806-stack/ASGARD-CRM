'use strict';
/**
 * ASGARD CRM — извлечение НАСЕЛЁННОГО ПУНКТА (города) из адресной строки.
 *
 * Зачем: в `employees.city` исторически попадал полный адрес («Ростовская обл.,
 * р-н Зерноградский, г. Зерноград, ул. им. Шукшина, д. 92, кв. 23»), потому что
 * поле заполнялось свободным текстом из четырёх источников (v2-карточка,
 * vanilla-карточка, Field-PWA, импорт). UI рисует `city` в «Дружине» и в табеле —
 * там нужен только город.
 *
 * Разведение понятий (V389):
 *   city                 — ТОЛЬКО населённый пункт (Москва, Зерноград, пгт Красногорский)
 *   address              — фактический адрес проживания (полный)
 *   registration_address — адрес регистрации (полный)
 *
 * Ловушки, которые здесь учтены (проверены на 610 реальных записях прода):
 *   • «д. 54» / «д.54» — ДОМ (число), а «д. Зеленинские Дворики» — ДЕРЕВНЯ;
 *   • адреса без запятых: «Саратовская область город Пугачев улица переулок татарский дом 12»;
 *   • «Москва(Московская область)» — город в скобках уточняется регионом;
 *   • регион/район («Волгоградская обл», «р-н Зерноградский») городом НЕ считается;
 *   • обрезанный адрес («ул Пролетарская, д. 15» без города) — отдаём с флагом
 *     `low`, чтобы человек проверил, а не молча записали мусор.
 *
 * Чистая функция, без БД и зависимостей: используется и бэкендом (миграция
 * данных), и тестами. Не бросает исключений.
 */

const RE_HOUSE = /^д\.?\s*\d/i;

/** Маркеры улицы/дома: с них начинается «хвост» адреса, который нам не нужен. */
const RE_STREET_TOK =
  /(?:^|[\s,.])(?:улица|ул\.|переулок|пер\.|проспект|просп\.|пр-т|шоссе|микрорайон|мкр\.|квартал|бульвар|бул\.|б-р|набережная|наб\.|площадь|пл\.|проезд|аллея|территория|тер\.|корпус|корп\.|строение|стр\.|дом|здание|литера|гск|тсж|жск|днп|снт|кв\.|квартира)\b/i;

/** Сегмент заканчивается на регион/район — это не населённый пункт. */
const RE_REGION_TAIL =
  /(?:обл\.?|область|край|респ\.?|республика|ао|округ|р-н\.?|р-он\.?|район|г\.?о\.?|городской округ)\s*$/i;

const RE_INDEX = /^\d{5,6}$/;
const RE_PLACEHOLDER = /^(?:-+|—+|нет|н\/д|не указан|не указано|неизвестно)$/i;

/**
 * Маркер ГОРОДСКОГО уровня («г. Москва», «город Тюмень») — самый надёжный.
 * Приоритетнее поселкового: в «г. Москва, пос. Сосенское, п. Коммунарка» город = Москва,
 * а не Коммунарка (реальный кейс #28 на проде).
 */
const RE_CITY = /(?:^|[\s,.])(?:г(?:ор)?\.?\s+|\s?город\s+)([А-ЯЁ][А-ЯЁа-яё0-9.\-]*(?:\s+[А-ЯЁ][А-ЯЁа-яё0-9.\-]*)*)/i;

/** Обратная форма городского маркера: «Ханты-Мансийск г», «Москва гор». */
const RE_CITY_TAIL = /(?:^|[\s,.])([А-ЯЁ][А-ЯЁа-яё0-9.\-]*(?:\s+[А-ЯЁ][А-ЯЁа-яё0-9.\-]*)*)\s+(?:г\.?|гор\.?|город)\.?(?=[\s,;.]|$)/i;

/**
 * Маркеры поселкового уровня: пгт / рп / посёлок / село / станица / деревня / аул / хутор.
 * «д.»/«дер.» — деревня И «д. 54» = дом: число отсекается проверкой RE_HOUSE выше.
 * Одиночные «с»/«ст»/«д» в ОБРАТНОЙ форме НЕ используются — иначе
 * «ул. Советская д. 6» даёт город «Советская» (реальный баг, найден на проде #101).
 */
const RE_SETTLE =
  /(?:^|[\s,.])(?:пгт\.?\s*|рп\.?\s*|п\.\s+|пос\.?\s+|посёлок\s+|село\s+|с\.\s+|станица\s+|ст-ца\s*|ст\.\s+|деревня\s+|дер\.\s+|д\.\s+|аул\s+|хутор\s+|слобода\s+|сл\.\s*)([А-ЯЁ][А-ЯЁа-яё0-9.\-]*(?:\s+[А-ЯЁ][А-ЯЁа-яё0-9.\-]*)*)/i;

/** Обратная форма поселкового маркера (узкий список — см. выше). */
const RE_SETTLE_TAIL =
  /(?:^|[\s,.])([А-ЯЁ][А-ЯЁа-яё0-9.\-]*(?:\s+[А-ЯЁ][А-ЯЁа-яё0-9.\-]*)*)\s+(?:пгт\.?|рп\.?|пос\.?|посёлок|село|станица|деревня|аул|хутор|слобода)\.?(?=[\s,;.]|$)/i;

const clean = (s) =>
  String(s == null ? '' : s)
    .replace(/\s+/g, ' ')
    .replace(/^[\s,;.]+|[\s,;.]+$/g, '')
    .replace(/["«»]/g, '')
    .trim();

const stripPrefix = (s) =>
  clean(s)
    .replace(
      /^(?:г(?:ор)?\.?|пгт\.?|рп\.?|п\.|пос\.?|посёлок|село|с\.|ст\.|ст-ца|дер\.?|д\.|деревня|аул|хутор|слобода|сл\.)\s+/i,
      ''
    )
    // «Москва(Московская область)» → «Москва»: уточнение региона в скобках.
    .replace(/\s*\([^)]*\)\s*$/, '')
    // «Бийск Алтайский край» → «Бийск»: прилагательное региона + маркер региона.
    // \b здесь НЕЛЬЗЯ — в JS он ASCII-ориентированный и не видит границу после «край».
    .replace(
      /\s+[А-ЯЁ][а-яё]*(?:ск|цк|ий|ая|ое|ый|ой)\s+(?:обл\.?|область|край|респ\.?|республика|автономн\w*|округ|ао)(?=\s|$|[.,;])/i,
      ''
    )
    // «Бийск край», «Москва обл.» — маркер региона с хвостом.
    .replace(/\s+(?:обл\.?|область|край|респ\.?|республика|автономн\w*|округ|ао)(?=\s|$|[.,;]).*$/i, '')
    // «Пугачев улица переулок татарский дом» → «Пугачев»: обрезаем хвост улицы,
    // который не удалось отделить запятой (адрес без запятых).
    .replace(
      /\s+(?:улица|ул\.?|переулок|пер\.?|проспект|просп\.?|пр-кт|шоссе|микрорайон|мкр\.?|бульвар|бул\.?|б-р|набережная|наб\.?|площадь|пл\.?|проезд|аллея|территория|тер\.?|корпус|корп\.?|строение|стр\.?|дом|здание|литера|гск|тсж|жск|днп|снт|кв\.?|квартира)(?=\s|$|[.,;]).*$/i,
      ''
    )
    // Висячие одиночные маркеры: «Зеленинские Дворики д» → «Зеленинские Дворики».
    .replace(/\s+(?:г|п|д|с|ст)\.?$/i, '')
    .replace(/^(?:г|п|д|с|ст)\.$/i, '')
    .trim();

const looksRegion = (t) => RE_REGION_TAIL.test(t) || RE_INDEX.test(t) || /^(?:россия|рф)$/i.test(t);
// \b не работает после «ул.» (точка не word-символ) — StreetStart закрывает дыру.
const looksStreet = (t) =>
  RE_STREET_TOK.test(' ' + t + ' ') || RE_HOUSE.test(t) || RE_STREET_START.test(t) || RE_DISTRICT_START.test(t);
const isPlaceholder = (t) => RE_PLACEHOLDER.test(clean(t));

/**
 * Режет адрес на сегменты: по запятой И по «бесзапятым» маркерам улиц.
 * @param {string} addr
 * @returns {string[]}
 */
function splitAddress(addr) {
  let s = clean(addr);
  if (!s || isPlaceholder(s)) return [];
  s = s.replace(/\s+(\d{5,6})(?=[\s,])/g, ' '); // почтовый индекс
  s = s.replace(
    /\s+(?=(?:улица|переулок|проспект|пр-кт|шоссе|микрорайон|бульвар|набережная|площадь|проезд|аллея|территория|корпус|строение|здание|литера)\b)/gi,
    ', '
  );
  s = s.replace(/\s*,?\s*(?:кв\.?|квартира)\s*\d+[а-я]?\.?$/gi, '');
  return s.split(',').map(clean).filter(Boolean);
}

/**
 * Извлекает населённый пункт из адресной строки.
 *
 * @param {string} raw — адрес (или уже готовое значение city)
 * @returns {{city: string, low: boolean}|null}
 *   city — населённый пункт; low=true → адрес обрезан, нужна ручная проверка.
 *   null — распознать нечего.
 */
function extractCity(raw) {
  const rawClean = clean(raw == null ? '' : raw);
  if (!rawClean || isPlaceholder(rawClean)) return null;

  // «Москва(Московская область)» — город с уточнением региона в скобках.
  // Разбираем до нарезки: иначе правило «последнего живого сегмента» пометит
  // результат как low и город не будет записан (реальные #10169/10170/10179).
  const paren = rawClean.match(/^([^(]+?)\s*\(([^)]*)\)$/);
  if (paren) {
    const head = clean(paren[1]);
    const inner = clean(paren[2]);
    // В скобках регион («Московская область») — город снаружи. Если наоборот
    // («Красногорский (Москва)»), берём то, что выглядит населённым пунктом.
    if (head && !looksRegion(head) && !RE_STREET_TOK.test(' ' + head + ' ') && !/\d/.test(head)) {
      return { city: stripPrefix(head), low: false };
    }
    if (inner) {
      const fromInner = extractCity(inner.replace(/\([^)]*\)/g, ''));
      if (fromInner && !fromInner.low) return fromInner;
    }
  }

  const segs = splitAddress(rawClean);
  if (!segs.length) return null;

  // Собираем ВСЕ маркеры населённых пунктов и берём самый «старший» уровень:
  //   город («г. Москва», «город Пугачев») важнее посёлка/села («п. Коммунарка») — реальный #28.
  // Между одинаковыми уровнями выигрывает ПОСЛЕДНИЙ (ближайший к улице).
  let cityLevel = null;
  let settleLevel = null;
  for (const seg of segs) {
    let m;
    // Городской маркер однозначен («город Пугачев») — ищем даже в смешанном
    // сегменте без запятых: «Саратовская область город Пугачев улица переулок...».
    const reCity = new RegExp(RE_CITY.source, 'gi');
    while ((m = reCity.exec(seg)) !== null) cityLevel = clean(m[1]);
    // Поселковый маркер не ищем в сегменте, начинающемся с улицы (иначе
    // «ул. Советская д. 6» даёт город «Советская» — реальный баг, найден на проде).
    if (seg === segs[0] || !looksStreet(seg)) {
      const reSet = new RegExp(RE_SETTLE.source, 'gi');
      while ((m = reSet.exec(seg)) !== null) settleLevel = clean(m[1]);
    }
  }
  if (cityLevel) return { city: stripPrefix(cityLevel), low: false };
  if (settleLevel) return { city: stripPrefix(settleLevel), low: false };

  // 1b) Обратная форма: «Ханты-Мансийск г», «Бийск Гор», «пос. Крестцы».
  for (const seg of segs) {
    const mc = seg.match(RE_CITY_TAIL);
    if (mc) {
      const cand = stripPrefix(mc[1]).replace(/\s+(?:обл\.?|область|край|респ\.?|республика|округ)\s*$/i, '').trim();
      if (cand && !looksRegion(cand) && !looksStreet(cand)) return { city: cand, low: false };
    }
  }
  for (const seg of segs) {
    const ms = seg.match(RE_SETTLE_TAIL);
    if (!ms) continue;
    const cand = stripPrefix(ms[1]).replace(/\s+(?:обл\.?|область|край|респ\.?|республика|округ)\s*$/i, '').trim();
    if (cand && !looksRegion(cand) && !looksStreet(cand)) return { city: cand, low: false };
  }

  // 2) Без маркера — последний «живой» сегмент (не регион/район/улица/индекс).
  for (let i = segs.length - 1; i >= 0; i--) {
    const t = clean(segs[i]);
    if (!t || looksRegion(t) || looksStreet(t) || /\d/.test(t) || !/[А-ЯЁа-яё]/.test(t)) continue;
    // «Бийск, Алтайская область»: город ведёт строку одним словом — уверенно.
    // Остальные случаи помечаем low: адрес обрезан, нужна проверка человеком.
    const confident = i === 0 && /^[А-ЯЁ][а-яё\-]+$/.test(t);
    return { city: stripPrefix(t), low: !confident };
  }

  // 3) Адрес обрезан (нет ни города, ни улицы-хвоста) — отдаём остаток как low,
  //    чтобы это ушло человеку, а не в поле «Город» молча.
  const stripped = segs
    .map((x) => x.replace(RE_SETTLE, '$1').replace(RE_CITY, '$1'))
    .filter((x) => !looksRegion(x) && !looksStreet(x) && !/^\d+$/.test(x))
    .join(', ');
  if (stripped && /[А-ЯЁа-яё]/.test(stripped)) return { city: clean(stripped), low: true };

  // 4) Одно слово — вероятно, уже готовое значение city.
  const whole = clean(String(raw == null ? '' : raw).replace(/\(\s*[^)]*\s*\)\s*$/, ''));
  if (/^[А-ЯЁ][а-яё\-]+(?:[-\s][А-ЯЁ][а-яё\-]+)?$/.test(whole)) return { city: whole, low: false };
  return null;
}

/**
 * Обёртка: только город или null (без флага).
 * @param {string} raw
 * @returns {string|null}
 */
function extractCityName(raw) {
  const r = extractCity(raw);
  return r && r.city ? r.city : null;
}

/**
 * Начинается ли строка с маркера улицы/дома. Отдельная функция, потому что
 * RE_STREET_TOK опирается на префикс «(?:^|[\s,.])» + \b, а \b в JS не видит
 * границу после «ул.» (точка не является word-символом) — проверено на проде.
 */
const RE_STREET_START =
  /^\s*(?:улица|ул\.?|переулок|пер\.?|проспект|просп\.?|пр-т|шоссе|ш\.|микрорайон|мкр\.?|квартал|бульвар|бул\.?|б-р|набережная|наб\.?|площадь|пл\.?|проезд|аллея|территория|тер\.?|корпус|корп\.?|строение|стр\.?|дом|здание|литера|гск|тсж|жск|днп|снт|кв\.?|квартира)(?=[\s.]|$)/i;

/** Сегмент начинается с «р-н …» / «район …» — это район, не город. */
const RE_DISTRICT_START = /^\s*(?:р-н\.?|р-он\.?|район)\b/i;

/** Значение — это только маркер без названия («г», «ул», «П», «обл»). */
const RE_MARKER_ONLY =
  /^(?:г|гор|город|ул|улица|пер|переулок|пр-кт|проспект|д|дом|с|село|ст|станица|п|пос|посёлок|рп|пгт|кв|квартира|обл|область|край|респ|республика|р-н|р-он|район|округ|ао)\s*\.?$/i;

/** Похоже ли значение на адрес/регион, а не на город.
 * Используется валидацией на записи: не дать снова положить адрес в `city`.
 * @param {string} value
 * @returns {boolean}
 */
function looksLikeAddress(value) {
  const t = clean(value);
  if (!t) return false;
  if (t.length > 60) return true;
  if (/\d/.test(t)) return true;
  if (RE_STREET_TOK.test(' ' + t + ' ')) return true;
  if (RE_STREET_START.test(t)) return true;
  if (RE_DISTRICT_START.test(t)) return true;
  if (RE_MARKER_ONLY.test(t)) return true;
  if (RE_REGION_TAIL.test(t)) return true;
  if (/\(/.test(t)) return true;
  return splitAddress(t).length > 1;
}

/**
 * Годится ли строка в `city` как населённый пункт. Контракт для записи:
 * маркеры, регионы, улицы, цифры и «low»-остатки — НЕ годятся.
 * @param {string} value
 * @returns {boolean}
 */
function isAcceptableCity(value) {
  const t = clean(value);
  if (!t) return false;
  if (t.length < 3) return false;          // «П», «г», «ул», «д»
  if (looksLikeAddress(t)) return false;
  if (!/[А-ЯЁа-яё]/.test(t)) return false; // чистая латиница/цифры
  const r = extractCity(t);
  return !!r && r.low === false;
}

module.exports = {
  extractCity,
  extractCityName,
  looksLikeAddress,
  isAcceptableCity,
  splitAddress,
  clean,
  // экспорт для тестов
  _re: {
    RE_HOUSE, RE_STREET_TOK, RE_STREET_START, RE_DISTRICT_START, RE_MARKER_ONLY,
    RE_REGION_TAIL, RE_INDEX, RE_PLACEHOLDER,
    RE_CITY, RE_CITY_TAIL, RE_SETTLE, RE_SETTLE_TAIL
  }
};
