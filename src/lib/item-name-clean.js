'use strict';

/**
 * Очистка наименований номенклатуры (заказчик 19.10.2026).
 * ═══════════════════════════════════════════════════════════════════════════
 * Проблема: OCR/скан склеивает наименование с габаритами, ГОСТ и фасовкой:
 *   «Мат из минеральной ваты прошивной МП (СТ)-100 - 2000.1200.60
 *    ГОСТ 21880-2022 36 руп. (5,184 м3)»
 * Из-за этого поиск по товару в номенклатуре не находит позицию: человек ищет
 * «мат из минваты», а в базе строка начинается так же, но при точном
 * сопоставлении/сортировке хвост мешает.
 *
 * Решение: РАЗДЕЛИТЬ строку на читаемое имя и «хвост» (габариты/ГОСТ/фасовку).
 * Хвост НЕ выбрасываем — переносим в `article`, чтобы данные не терялись
 * (по нему тоже ищут: артикул, ГОСТ, размер).
 *
 * ГЛАВНЫЙ ПРИНЦИП: ничего не ломать. Функция чистая (без БД, без сети),
 * при сомнении возвращает исходную строку без изменений. Отрезает хвост
 * ТОЛЬКО когда он явно похож на технические данные и стоит не в начале
 * названия.
 * ═══════════════════════════════════════════════════════════════════════════
 */

// Маркеры начала «технического хвоста».
// ВАЖНО: даты (12.10.2026 / 12.10.26) НЕ трогаем — они часто часть услуги
// («Проживание ТРУХИН А. С. 12.10.2026»), без даты позиция нечитаема.
const TAIL_MARKERS = [
  // ГОСТ / ТУ / ОСТ — однозначно норматив, не часть названия товара
  /\s*[-–—,]?\s*\b(ГОСТ|ГОСТ\s*Р|ТУ|ОСТ)\s*[\d\-–—.]/i,
  // Габариты ТРОЙКОЙ через разделитель: 2000.1200.60, 1200x600x50.
  // Двойка «3х2,5» и даты «12.10.2026» сюда НЕ попадают (это часть названия/услуги).
  /\s*[-–—,]?\s*\d{2,}\s*[.,xх×]\s*\d{2,}\s*[.,xх×]\s*\d{2,}/i,
  // Фасовка/количество с единицей: «36 руп.» (единицы, которые бывают только у фасовки)
  /\s*[-–—,]?\s*\b\d{1,4}\s*(руп|рул|упак|пач)\b\.?/i,
  // Фасовка в скобках: «(5,184 м3)», «(25кг)», «(27 кг)»
  /\s*\(\s*\d+[.,]?\d*\s*(м3|м2|кг|л|мл|г|шт)\s*\)/i
];

// Единицы, которые сами по себе НЕ признак хвоста (часто это и есть товар:
// «Кабель 3х2,5», «Труба Ду50»). Защита ниже по длине префикса.
const MIN_NAME_LEN = 18;   // если до маркера меньше — это не хвост, а название («Кабель 3х2,5»)

/**
 * Разделить наименование на имя и технический хвост.
 * @param {string} raw — исходная строка из счёта/OCR/ИИ
 * @returns {{name:string, tail:string|null, changed:boolean}}
 */
function splitItemName(raw) {
  const src = String(raw == null ? '' : raw).replace(/\s+/g, ' ').trim();
  if (!src) return { name: '', tail: null, changed: false };
  // Слишком короткое — не трогаем (нечего делить).
  if (src.length < MIN_NAME_LEN + 6) return { name: src, tail: null, changed: false };

  let cutAt = -1;
  for (const re of TAIL_MARKERS) {
    const m = src.match(re);
    if (m && m.index != null) {
      // Хвост должен стоять ПОСЛЕ осмысленного имени — иначе это часть названия
      // («Кабель 3х2,5»: маркер в начале, резать нельзя).
      if (m.index < MIN_NAME_LEN) continue;
      // ДАТА НЕ ХВОСТ: если фрагмент — именно дата (ДД.ММ.ГГГГ / ДД.ММ.ГГ),
      // оставляем её в имени («Проживание ТРУХИН А. С. 12.10.2026»).
      // ВАЖНО: проверяем структуру ДАТЫ, а не просто «20xx» — иначе ГОСТ 21880-2022
      // ошибочно принимается за дату и не отрезается.
      if (/\b\d{1,2}[.\-/]\d{1,2}[.\-/]\d{2,4}\b/.test(m[0])) continue;
      cutAt = m.index;
      break;
    }
  }
  if (cutAt < 0) return { name: src, tail: null, changed: false };

  const name = src.slice(0, cutAt).replace(/[\s\-–—,.;:]+$/, '').trim();
  const tail = src.slice(cutAt).replace(/^[\s\-–—,.;:]+/, '').trim();
  // Защита от вырождения: имя должно остаться осмысленным.
  if (name.length < MIN_NAME_LEN || !tail) return { name: src, tail: null, changed: false };
  return { name, tail, changed: true };
}

/**
 * Нормализовать название контрагента: привести кавычки в порядок после OCR.
 * Дефект (заказчик 19.10.2026): `ООО "ТД "БАШПРОМТОРГ` — открыта внешняя кавычка,
 * внутри ещё одна, закрывающей нет. Нужно `ООО "ТД БАШПРОМТОРГ"`.
 * Организацию НЕ переименовываем — только балансируем кавычки.
 *
 * Принцип «не ломать»: если строка уже корректна (чётное число кавычек или их нет),
 * возвращаем её БЕЗ изменений (кроме типа кавычек).
 * @param {string} raw
 * @returns {string}
 */
function tidyOrgName(raw) {
  const orig = String(raw == null ? '' : raw).replace(/\s+/g, ' ').trim();
  if (!orig) return orig;
  // Единый тип кавычек: «ёлочки» и типографские → прямые.
  let s = orig.replace(/[«»]/g, '"').replace(/[“”]/g, '"').replace(/\s+/g, ' ').trim();

  const count = (s.match(/"/g) || []).length;
  // Хвост из двух закрывающих подряд (`..."БАШПРОМТОРГ""`) — OCR-артефакт.
  // Снимаем ДО проверки чётности, иначе такая строка считается «валидной».
  s = s.replace(/"{2,}\s*$/, '"').trim();
  // После снятия дубля парность могла нарушиться — нормализуем вложенную пару.
  // Форма: `ООО "ТД "БАШПРОМТОРГ"` (3 кавычки: внешняя открыта, внутренняя пара,
  // закрывающей внешней нет). Схлопываем внутреннюю пару в пробел.
  if ((s.match(/"/g) || []).length % 2 === 1) {
    // `ООО "A "B"` → `ООО "A B"`
    const nested = s.match(/^([^"]{2,40}?)\s+"([^"]{1,60}?)\s+"([^"]{1,120}?)"?$/);
    if (nested) {
      return `${nested[1].trim()} "${nested[2].trim()} ${nested[3].trim()}"`.replace(/\s+/g, ' ').trim();
    }
  }
  if ((s.match(/"/g) || []).length % 2 === 0) return s;

  // Нечётное → одна лишняя/незакрытая. Единственный безопасный случай, который
  // чиним: незакрытая ВНЕШНЯЯ кавычка (`ООО "ТД "БАШПРОМТОРГ`).
  // Всё остальное возвращаем как есть — лучше кривая кавычка, чем потеря текста.
  const m = s.match(/^(.{2,40}?)\s+"([^"]*?)\s+"\s*([^"]{1,120})$/);
  if (m) {
    const head = m[1].trim();
    const inner = m[2].trim();
    const name = m[3].trim();
    return `${head} "${inner} ${name}"`.replace(/\s+/g, ' ').trim();
  }
  // Просто не хватает закрывающей в конце — добавляем.
  return (s + '"').replace(/\s+/g, ' ').trim();
}

module.exports = { splitItemName, tidyOrgName, MIN_NAME_LEN };
