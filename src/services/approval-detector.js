'use strict';

/**
 * V398 (Часть II): детект согласия директора («Добро») по телу письма.
 * ═══════════════════════════════════════════════════════════════════════════
 * Требование заказчика: директор отвечает словом («Добро»), не кнопкой.
 *
 * ПРИНЦИП (переписан 17.10.2026 после 3-го круга верификатора):
 * blacklist негативов НЕ РАБОТАЕТ — «не платите / не перечисляйте / заморозьте /
 * приостановите / однако не» бесконечны, и каждый обход согласовывал счёт.
 * Теперь — WHITELIST (fail-closed): согласием считается ТОЛЬКО тело, целиком
 * состоящее из разрешённых токенов (короткое и однозначное). Любое иное слово
 * → `needs_manual` (ручное подтверждение кнопкой в CRM, что и так есть).
 *
 * Это осознанно строго: директор, пишущий «Добро» (как в требовании), проходит;
 * директор, пишущий развёрнутый текст с условиями, — подтверждает в CRM.
 */

// Токены, допустимые в теле согласия (после нормализации).
const APPROVE_TOKENS = new Set([
  'добро', 'да', 'ага', 'ок', 'окей', 'okay', 'ok',
  'согласовано', 'согласен', 'согласна', 'согласны',
  'утверждаю', 'утверждено', 'утверждаем', 'утвердить',
  'одобряю', 'одобрено', 'одобряем', 'одобрить',
  'подтверждаю', 'подтверждено', 'подтверждаем', 'подтвердить',
  'разрешаю', 'разрешено', 'разрешаем', 'разрешить',
  'оплачивайте', 'оплачиваем', 'оплачивать', 'оплачивай', 'оплати', 'оплатить', 'оплатим',
  'платите', 'платим', 'платить', 'плати',
  'перечислить', 'переведите', 'переведи', 'перечислите',
  'можно', 'разрешение', 'даю', 'даем', 'даём', 'принято', 'принял', 'принять', 'хорошо', 'понял'
]);
// Нейтральные слова, не меняющие смысла (не считать «неизвестными»).
const FILLER_TOKENS = new Set([
  'спасибо', 'пожалуйста', 'и', 'это', 'всё', 'все', 'уважением', 'с', 'коллеги', 'коллега',
  'на', 'за', 'оплату', 'счёт', 'счет', 'по', 'от', 'в', 'к'
]);
// Платёжные слова: если встречаются ПОСЛЕ подписи/разделителя — это скрытая
// инструкция («Добро\n--\nНе оплачивайте») → отказ.
const PAY_WORDS_RE = /(оплач|оплат|плат|перечисл|перевед|перевод|деньг|счёт|счет|заморо|приостанов)/i;
// Ловушки-ложные согласия.
// D-277: раньше регекспы были БЕЗ границ слова — «добро» матчилось внутри
// «доброе утро» и «доброжелательный», поэтому любое тело с приветствием
// помечалось falsePositive и «Добро» директора отвергалось. Границы обязательны.
const C = '(?:^|[^а-яёa-z])';
const E = '(?:[^а-яёa-z]|$)';
const FALSE_APPROVE = [
  new RegExp(`${C}добро\\s+пожаловать${E}`, 'i'),
  new RegExp(`${C}добр(?:ое|ый|ой|ого)\\s+(?:утро|день|вечер|время|ночи|дня)${E}`, 'i'),
  new RegExp(`${C}доброжелательн`, 'i'),
  new RegExp(`${C}добросовестн`, 'i'),
  new RegExp(`${C}добротн`, 'i')
];

/** Убрать цитаты прежней переписки (чужие письма). Подпись НЕ режем здесь. */
function stripQuotes(text) {
  let s = String(text || '');
  const cutMarkers = [
    /\n\s*-{2,}\s*(исходное|первоначальное)\s+сообщение\s*-{2,}/i,
    /\n\s*_{3,}/,
    /\n\s*>{1,}/,
    /\n\s*От:\s.*\n\s*(Кому|Отправлено):/i,
    /\n\s*От кого:\s/i,
    /\n\s*Отправлено:\s/i,
    /\n\s*(Пересылаю|Пересланное сообщение|Перенаправлено)/i,
    /\n\s*From:\s.*\n\s*(Sent|To):/i,
    /\n\s*On .{0,80}wrote:/i,
    /\n\s*письмо\s+от\s+/i,
    // D-277 (прод 19.10.2026): Яндекс.Почта / Mail.ru. Реальное письмо #4889
    // («Добро» директора) НЕ обрезалось: маркера «в 11:10, Виктория Тумаева
    // <office@…> написал(а):» в списке не было. Цитата оставалась в теле, и
    // «доброе утро!» внутри неё ложно срабатывало как falsePositive —
    // согласие директора терялось. Две формы: с датой и без.
    /\n\s*\d{1,2}\s+[а-яё.]+\s+\d{4}\s*(?:г\.)?\s*,?\s*в\s*\d{1,2}:\d{2}/i,
    /\n\s*.*(?:написал\(а\)|написала|написал|wrote)\s*:/i,
    /\n\s*[^\n]{0,120}<[^>\s]+@[^>]+>\s*(?:написал|пишет)/i
  ];
  for (const re of cutMarkers) {
    const m = s.split(re);
    if (m.length > 1) s = m[0];
  }
  return s.trim();
}

/**
 * Убрать подпись мобильного клиента.
 * D-277: «Добро» + автоподпись iPhone приходят СКЛЕЕННЫМИ в один токен —
 * «ДоброОтправлено с iPhone» (перенос строки в теле письма не сохраняется).
 * После разборки на токены это давало unknown_tokens → согласие терялось.
 * Вырезаем подпись как подстроку ДО токенизации: «ДоброОтправлено с iPhone»
 * → «Добро».
 */
function stripSignature(text) {
  return String(text || '')
    .replace(/(?:отправлено|отправлен[оа]|переслано|переслан[оа]|отправлено\s+из|sent|forwarded)\s+(?:с|со|из|from)\s+(?:my\s+|моего\s+|мобильного\s+)?(?:iphone|ipad|ipod|android|samsung|galaxy|xperia|huawei|honor|мобильного|мобильной|мобильного\s+устройства|почты|mail)[^\n]*/gi, ' ')
    .replace(/^\s*--\s*$/gm, '\n')
    .trim();
}

/** Нормализовать токен: убрать пунктуацию/эмодзи/кавычки. */
function normToken(w) {
  return String(w || '')
    .toLowerCase()
    .replace(/[^\u0430-\u044f\u0451a-z0-9]/gi, '')   // кириллица/латиница/цифры
    .trim();
}

/**
 * Защита от юникод-гомоглифов: смешение кириллицы и латиницы в одном слове
 * («добpо» с латинской «p») — верный признак подделки, не согласие.
 */
function hasMixedScript(w) {
  const s = String(w || '');
  const cyr = /[\u0430-\u044f\u0451]/i.test(s);
  const lat = /[a-z]/i.test(s);
  return cyr && lat;
}

/**
 * Есть ли утвердительное согласие в теле (СТРОГИЙ whitelist).
 * @param {string} body
 * @returns {{approve:boolean, word?:string, reason?:string}}
 */
function detectApproval(body) {
  const whole = String(body || '');

  const cut = stripQuotes(whole);
  if (!cut) return { approve: false };
  // Вопрос — не согласие («Оплачиваем?», «Согласовать?»).
  if (/[?？]/.test(cut)) return { approve: false, reason: 'question' };

  // Защита от скрытой инструкции в подписи/после разделителя: берём всё, что
  // идёт после первой строки из дефисов/подчёркиваний, и если там есть
  // платёжные слова — это не чистое согласие.
  // ВАЖНО (живой тест 18.10.2026): Яндекс/Мейл-агенты добавляют ПОД разделителем
  // служебный блок «Кому: … Тема: … счёт от WILDBERRIES … > цитата». Слово «счёт»
  // из ТЕМЫ цитаты ложно считалось «скрытой инструкцией», и настоящее «Добро!»
  // отвергалось. Теперь: (1) служебную шапку перед цитатой отрезаем ДО проверки;
  // (2) платёжные слова ищем только в строках, которые НЕ являются цитатой;
  // (3) ищем именно ИНСТРУКЦИЮ (оплачивайте/не оплачивайте/перечислите/заморозьте),
  //     а не любое упоминание слова «счёт».
  const parts = cut.split(/\n\s*[-_=]{2,}\s*\n?/);
  if (parts.length > 1) {
    // Отрезаем служебную шапку пересылки и цитаты («Кому:», «Тема:», «> …»).
    const tailLines = parts.slice(1).join('\n')
      .split('\n')
      .filter((l) => {
        const t = l.trim();
        if (!t) return false;
        if (/^(кому|от|отправлено|тема|дата|from|to|sent|subject|date)\s*:/i.test(t)) return false;
        if (/^>/.test(t)) return false;                       // строка-цитата
        if (/^\d{2}\.\d{2}\.\d{4}/.test(t)) return false;     // дата-строка пересылки
        return true;
      });
    const instruction = tailLines.join('\n');
    const INSTRUCTION_RE = /(не\s+оплач|не\s+перечисл|не\s+плат|оплач|оплат|плат|перечисл|перевед|перевод|заморо|приостанов|подожд|отлож|после\s+поставк|после\s+получен)/i;
    if (INSTRUCTION_RE.test(instruction)) {
      return { approve: false, reason: 'instruction_after_separator' };
    }
  }

  // Тело до разделителя подписи.
  const head = parts[0];

  // D-277: подпись мобильного клиента режем ДО токенизации («ДоброОтправлено
  // с iPhone» → «Добро»).
  const cleaned = stripSignature(head);

  // Ловушки-ложные согласия проверяем на СОБСТВЕННОМ тексте директора, уже
  // без цитаты и подписи. Раньше проверяли `whole` (всё тело): приветствие
  // из ЦИТАТЫ («Коллеги, доброе утро!») глушило настоящее «Добро» — D-277.
  for (const trap of FALSE_APPROVE) { if (trap.test(cleaned)) return { approve: false, falsePositive: true }; }

  // Разбиваем на токены, отбрасывая пустые.
  const tokens = cleaned.split(/\s+/).map(normToken).filter(Boolean);
  if (!tokens.length) return { approve: false };
  // Длинное тело — не однозначное согласие (fail-closed → ручное подтверждение).
  if (tokens.length > 6) return { approve: false, reason: 'too_long' };

  const unknown = tokens.filter((t) => !APPROVE_TOKENS.has(t) && !FILLER_TOKENS.has(t));
  if (unknown.length) return { approve: false, reason: 'unknown_tokens', unknown: unknown.slice(0, 4) };
  // Гомоглифы (кириллица+латиница в слове) — подделка.
  if (cleaned.split(/\s+/).some(hasMixedScript)) return { approve: false, reason: 'mixed_script' };

  const hit = tokens.find((t) => APPROVE_TOKENS.has(t));
  return hit ? { approve: true, word: hit } : { approve: false, reason: 'no_approve_token' };
}

/** Явный отказ (для отдельного класса). */
function detectRejection(body) {
  const s = String(body || '').toLowerCase();
  const rej = ['отклоняю', 'отклонено', 'отклоняем', 'отказано', 'не согласовано', 'на доработку',
    'верни на', 'вернуть', 'аннулиру', 'пересмотр', 'отменяю', 'отмена'];
  const hit = rej.find((w) => s.includes(w));
  return hit ? { reject: true, word: hit } : { reject: false };
}

module.exports = { stripQuotes, detectApproval, detectRejection, APPROVE_TOKENS, FILLER_TOKENS };
