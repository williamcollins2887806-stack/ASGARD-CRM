/**
 * Классифицировать предмет закупки.
 *
 * Возвращает каркас и тип (товар/услуга). Если ничего не совпало — каркас
 * `production` (самый нейтральный) и тип по эвристике «услуга/поставка».
 *
 * @param {string[]} items — наименования позиций
 * @param {string} [comment] — назначение платежа / комментарий, если есть
 * @returns {{scaffold:string, type:'goods'|'service', matched:string|null, confidence:number}}
 */
function classify(items, comment) {
  const hay = [...(items || []), comment || ''].join(' \n ');
  if (!hay.trim()) {
    return { scaffold: 'production', type: 'goods', matched: null, confidence: 0 };
  }
  for (const r of RULES) {
    if (r.re.test(hay)) {
      return {
        scaffold: r.scaffold,
        type: r.type,
        matched: (hay.match(r.re) || [])[0] || null,
        // Совпадение по ключевому слову — это уверенность «выше средней»,
        // но не абсолют: позиция может быть описана нестандартно.
        confidence: 0.7,
      };
    }
  }
  // Пусто: если в тексте есть «услуг» — это услуга, иначе поставка.
  const isService = /услуг|работ[аы]|обслуживан|выполнени/i.test(hay);
  return { scaffold: 'production', type: isService ? 'service' : 'goods', matched: null, confidence: 0.3 };
}

