/** Подставить значения в шаблон-образец. */
function fill(tpl, vars) {
  return String(tpl || '').replace(/\{(\w+)\}/g, (m, k) => {
    const v = vars[k];
    return v == null || v === '' ? '' : String(v);
  }).replace(/\s+/g, ' ').trim();
}

/**
 * Фолбэк без ИИ: собрать блоки из образцов.
 * @returns {{gist:string, why:string, source:'fallback'}}
 */
function buildFallback(cls, vars) {
  const set = (EXAMPLES[cls.scaffold] || EXAMPLES.production)[cls.type]
    || (EXAMPLES[cls.scaffold] || EXAMPLES.production).goods;
  return {
    gist: fill(set.gist, vars),
    why: fill(set.why, vars),
    source: 'fallback',
  };
}

/** Список позиций строкой через запятую — как в эталонах Дмитрия (без маркеров). */
function itemsInline(items) {
  const list = (items || []).map((s) => String(s || '').trim()).filter(Boolean);
  if (!list.length) return '';
  return list.join(', ');
}

