/** Разобрать ответ модели в JSON. */
function parseJson(text) {
  const raw = String(text || '').trim();
  if (!raw) return null;
  // Модель иногда оборачивает в ```json ... ```
  const fenced = raw.match(/```(?:json)?\s*([\s\S]*?)```/i);
  const body = fenced ? fenced[1] : raw;
  const start = body.indexOf('{');
  const end = body.lastIndexOf('}');
  if (start < 0 || end <= start) return null;
  try {
    const o = JSON.parse(body.slice(start, end + 1));
    const gist = String(o.gist || '').trim();
    const why = String(o.why || '').trim();
    if (gist.length < 40 || why.length < 40) return null;
    return { gist, why };
  } catch (_) { return null; }
}

/**
 * Сгенерировать блоки письма.
 *
 * @param {object} input
 * @param {string[]} input.items — позиции счёта
 * @param {string} [input.comment] — назначение/комментарий
 * @param {string} input.counterparty
 * @param {string} input.company
 * @param {string} input.invoiceNo
 * @param {string} [input.invoiceDate]
 * @param {string} [input.contractLabel]
 * @param {number} [input.amount]
 * @param {object} [opts] — { ai: require('../services/ai-provider') | null, timeoutMs }
 * @returns {Promise<{gist,why,scaffold,type,source,matched}>}
 */
async function generate(input, opts = {}) {
  const d = input || {};
  const items = Array.isArray(d.items) ? d.items.filter(Boolean) : [];
  const cls = classify(items, d.comment);

  const vars = {
    company: d.company || 'ООО «Асгард-Сервис»',
    counterparty: d.counterparty || 'поставщик',
    items: itemsInline(items) || 'поставки по счёту',
    invoice_no: d.invoiceNo || 'б/н',
    invoice_date: d.invoiceDate || '',
    contract_label: d.contractLabel || '',
    amount: d.amount != null
      ? Number(d.amount).toLocaleString('ru-RU', { minimumFractionDigits: 2, maximumFractionDigits: 2 })
      : '',
  };

  // Без ИИ — сразу фолбэк (он детерминированный и не врёт).
  const ai = opts.ai === undefined ? require('./ai-provider') : opts.ai;
  if (!ai || typeof ai.completeFast !== 'function') {
    const fb = buildFallback(cls, vars);
    return { ...fb, scaffold: cls.scaffold, type: cls.type, matched: cls.matched };
  }

  try {
    const prompt = buildPrompt(cls, vars);
    const res = await ai.completeFast({
      messages: [{ role: 'user', content: prompt }],
      maxTokens: 900,
      temperature: 0.3,
    });
    const text = (res && (res.text || res.content)) || '';
    const parsed = parseJson(text);
    if (parsed) {
      return {
        gist: parsed.gist,
        why: parsed.why,
        scaffold: cls.scaffold,
        type: cls.type,
        matched: cls.matched,
        source: 'ai',
      };
    }
    console.warn('[obs-letter-ai] модель вернула не-JSON или слишком короткий текст — фолбэк');
  } catch (e) {
    console.warn('[obs-letter-ai] ИИ недоступен, фолбэк: ' + (e && e.message));
  }

  const fb = buildFallback(cls, vars);
  return { ...fb, scaffold: cls.scaffold, type: cls.type, matched: cls.matched };
}

