'use strict';
/**
 * D-336: категоризация общехозяйственных (офисных) расходов по контрагенту и описанию.
 *
 * Зачем: импорт исторических счетов складывал всё в одну категорию 'consumables',
 * которой нет в справочнике UI — расходы физически были, но в реестре офисных
 * расходов не отображались и директор не видел картину по компании.
 *
 * Категории совпадают с CATEGORIES в public/assets/js/office_expenses.js.
 * Порядок правил важен: первое совпадение выигрывает (от частного к общему).
 */

const RULES = [
  // Аренда помещений
  { cat: 'rent', re: /(гужва|аренд\w* (офис|помещен)|сдач\w* помещен|пентин)/i },
  // Коммунальные
  { cat: 'utilities', re: /(энергосбыт|водоканал|теплосет|газпром межрегион|коммунал|энерго|ресурсоснабж)/i },
  // Связь и интернет
  { cat: 'communication', re: /(мтс|билайн|мегафон|теле2|ростелеком|тинькофф ?мобайл|связь|интернет|телеком)/i },
  // Транспорт / такси / логистика / каршеринг / АЗС
  { cat: 'transport', re: /(яндекс\.?\s?такси|такси|деловые линии|сдэк|пэк\b|груз ?авто|тэк\b|рустранс|якуттранс|транспорт|логист|перевозк|каршеринг|ситидрайв|карлосон|элит-?кар|заправк|топлив|азс|мойка)/i },
  // Оборудование офиса (техника, IT-интеграторы, монтаж)
  { cat: 'office_equipment', re: /(ситилинк|днс\b|мвидео|эльдорадо|компьютер|ноутбук|монитор|принтер|мфу|картридж|техник|тривио|тензор|кондиционер|видеонаблюден)/i },
  // ПО и подписки
  { cat: 'software', re: /(битрикс|1с[-\s]?|яндекс ?облако|контур|сбис|антивирус|kaspersky|лиценз|подписк|софт|программ|microsoft|google|айдиэнлаб)/i },
  // Канцелярия и офисные товары (в т.ч. маркетплейсы)
  { cat: 'office_supplies', re: /(канцеляр|бумага|ручк|папк|скоросшиват|офисн\w* принадлежност|пресс ?бюро|комус|офисмаг|рвб\b|wildberries|ундервуд)/i },
  // Хозтовары
  { cat: 'household', re: /(хозтовар|чистящ|моющ|бытов\w* хими|мыло|салфетк|мусорн|хозмаг|удачный выбор)/i },
  // Инструменты / СИЗ
  { cat: 'tools', re: /(спецодежд|сиз\b|каск|перчатк|инструмент|всеинструменты|эрис|акваматика|овэлтрейд|подш\w*|крепеж)/i },
  // Представительские
  { cat: 'representation', re: /(ресторан|кафе|банкет|подарк|представител|catering|кофе|ресто-?маркет)/i },
  // Командировки/отели/билеты/обучение/страхование — общехозяйственное
  { cat: 'other', re: /(вайт ?тревел|хотэл|отель|гостиниц|авиакомпани|ржд\b|билет|командиров|медицин|учебн\w* комбинат|обучени|аттестац|охрана труда|страхов|вск)/i }
];

// Если контрагент не опознан — пробуем по тексту описания.
const DESC_RULES = [
  { cat: 'rent', re: /(аренд|наём|найм помещен)/i },
  { cat: 'utilities', re: /(электроэнерг|отоплен|водоснабж|водоотвед|коммунал)/i },
  { cat: 'communication', re: /(мобильн\w* связ|доступ в интернет|интернет)/i },
  { cat: 'transport', re: /(такси|перевозк|доставк|проезд|билет|топлив|мойка кузова)/i },
  { cat: 'office_supplies', re: /(канцеляр|бумаг)/i },
  { cat: 'household', re: /(хозтовар|уборк|чистящ)/i },
  { cat: 'tools', re: /(спецодежд|сиз\b|инструмент)/i },
  { cat: 'software', re: /(подписк|лиценз|программ)/i },
  { cat: 'office_equipment', re: /(ноутбук|монитор|принтер|картридж|компьютер|кондиционер)/i }
];

const VALID_CATEGORIES = new Set([
  'rent', 'utilities', 'office_supplies', 'communication', 'transport', 'household',
  'office_equipment', 'software', 'representation', 'project_expense', 'tools', 'other'
]);

/**
 * Категория офисного расхода.
 * @param {{counterparty?:string, description?:string}} doc
 * @returns {string} одна из VALID_CATEGORIES
 */
function classifyOfficeCategory(doc = {}) {
  const cp = String(doc.counterparty || '');
  const ds = String(doc.description || '');
  if (cp) {
    for (const r of RULES) if (r.re.test(cp)) return r.cat;
  }
  if (ds) {
    for (const r of DESC_RULES) if (r.re.test(ds)) return r.cat;
    for (const r of RULES) if (r.re.test(ds)) return r.cat;
  }
  return 'other';
}

module.exports = { classifyOfficeCategory, VALID_CATEGORIES, RULES, DESC_RULES };
