/**
 * Структурный счёт строк таблицы — по сетке ячеек, а не по тексту.
 *
 * ── Зачем это отдельный модуль ────────────────────────────────────────────
 * Тринадцать проходов верификатора показали: оценивать число позиций ВОР по
 * склеенному тексту нельзя. Форматы бесконечны, и каждый ломает счётчик:
 *
 *   • считали строки с единицами — ломались «м», «компл», «Гкал», шапки
 *     «Объём, т», где единица вынесена в заголовок;
 *   • считали нумерацию 1..N — ломались разделы с перезапуском (3×100 давало
 *     40), один пропущенный номер резал 300 до 150, а колонка «Кол-во»
 *     с числами 101..400 добавляла фантомные позиции (300 → 400);
 *   • текстовая нарезка после docx (ячейка = отдельная строка) и csv
 *     (запятые) давала вообще 0, то есть детектор молча выключался.
 *
 * Причина одна: текст теряет структуру. После рендера в строку невозможно
 * отличить номер позиции от объёма, единицу от названия, шапку от данных.
 *
 * Здесь структура не теряется: считаем по готовой сетке ячеек, которую отдаёт
 * сам парсер (ExcelJS / mammoth-таблица / CSV), до превращения в текст.
 * Никаких эвристик на строках — только ячейки.
 *
 * ── Что считается позицией ────────────────────────────────────────────────
 * Строка таблицы, в которой есть:
 *   • непустое НАЗВАНИЕ (текст длиннее 3 символов, не шапка), и
 *   • числовое КОЛИЧЕСТВО, и
 *   • единица измерения — либо в отдельной ячейке, либо в шапке колонки.
 *
 * Порядок колонок не важен (в реальных ведомостях «Кол-во» и «Ед.изм.»
 * стоят в любом порядке). Заголовки разделов, подстроки «в т.ч.», «Итого»
 * отсекаются по признакам, которые в сетке видны однозначно.
 */

/** Каноничные единицы измерения (в нормализованном виде). */
const UNITS = new Set([  'м', 'м2', 'м3', 'м²', 'м³', 'км', 'см', 'мм',
  'пог.м', 'погм', 'п.м', 'пм', 'м.п', 'мп',
  'куб.м', 'кубм', 'м.куб', 'мкуб', 'кв.м', 'квм',
  'т', 'тн', 'тонн', 'тонна', 'тонны', 'кг', 'г', 'грамм',
  'шт', 'шт.', 'штук', 'штука', 'ед', 'ед.', 'единиц',
  'компл', 'компл.', 'комплект', 'комплектов',
  'л', 'литр', 'литров', 'мл',
  'гкал', 'ккал', 'квт', 'квт.ч', 'квтч', 'мвт',
  'усл.ед', 'у.е', 'уе', 'балл', 'час', 'ч', 'сут', 'сутки', 'смена', 'чел.час',
  'апп', 'аппарат', 'аппаратов', 'труб', 'трубка', 'трубок', 'трубки',
  'секц', 'секция', 'секций', 'узел', 'узлов', 'элемент', 'элементов'
]);

/**
 * Находит ПОЛНЫЕ повторы блоков подряд — копии таблицы внутри листа.
 *
 * Ищем позицию i, после которой последовательность подписей в точности
 * повторяет предыдущий блок: sig[a..b] === sig[b+1..c]. Возвращает диапазоны
 * повторяющихся копий.
 *
 * Требования к блоку: не меньше 8 строк (мелкие совпадения не считаем
 * копией) и хотя бы 90 % подписей непустые.
 *
 * @param {string[]} sigs
 * @returns {Array<{from: number, to: number}>}
 */
function findRepeatedBlocks(sigs) {
  const out = [];
  const n = sigs.length;
  let i = 0;
  while (i < n) {
    let found = false;
    // Перебираем от МАЛЕНЬКОГО блока к большому и берём первый (минимальный),
    // который повторяется. Обратный порядок ошибался: при 4 копиях по 100
    // блок 200 (две копии скопом) принимался за один, и оставалось 200
    // позиций вместо 100.
    for (let len = MIN_BLOCK; i + len * 2 <= n; len += 1) {
      const first = sigs.slice(i, i + len);
      const meaningful = first.filter(Boolean).length;
      if (meaningful / len < 0.9) continue;

      // Сколько раз блок повторяется подряд.
      let copies = 1;
      let at = i + len;
      while (at + len <= n) {
        const next = sigs.slice(at, at + len);
        let same = true;
        for (let k = 0; k < len; k += 1) {
          if (first[k] !== next[k]) { same = false; break; }
        }
        if (!same) break;
        copies += 1;
        at += len;
      }
      if (copies < 2) continue;

      // Все копии после первой — дубли.
      out.push({ from: i + len, to: i + len * copies, len });
      i = at;
      found = true;
      break;
    }
    if (!found) i += 1;
  }
  return out;
}

/**
 * Подпись строки позиции — для схлопывания дублей внутри листа.
 *
 * Берём название (самую длинную текстовую ячейку) и все числа строки.
 * Одинаковая подпись означает ту же самую позицию: «Очистка 5 | м3 | 340»
 * дважды — дубль. Разные позиции с похожим названием разойдутся по объёму.
 *
 * @param {{cells: string[], nums: number[]}} c
 * @returns {string} подпись или '' если подписывать нечего
 */
function rowSignature(c) {
  if (!c || !Array.isArray(c.cells)) return '';
  const name = c.cells
    .filter((s) => s && /[а-яёa-z]{3}/i.test(s) && !/^\d+$/.test(s))
    .sort((a, b) => b.length - a.length)[0] || '';
  if (name.length < 4) return '';
  const nums = (Array.isArray(c.nums) ? c.nums : []).join(',');
  return name.slice(0, 120) + '|' + nums;
}

/**
 * Строка шапки таблицы.
 *
 * Нужна потому, что шапка С числами (годы, нумерация колонок) проходит
 * проверку «есть число» и давала фантомную позицию (+1 к любому итогу):
 * «Наименование | Объём, м3 | 2025 | 2026» → 301 вместо 300.
 *
 * ── Почему список слов минимальный ────────────────────────────────────────
 * В первой версии здесь были «объём», «сумма», «стоимость». Это глушило
 * СТРОКИ ДАННЫХ: названия «Замер объёма отложений», «Определение объёма
 * осадка», «Стоимость работ», «Сумма затрат» — обычные работы на реальных
 * ведомостях зачистки ёмкостей. Замер: 217 позиций из 300, причём молча —
 * РП видел «разбор полный» и не знал о 83 пропущенных строках.
 *
 * Поэтому здесь только слова, которые в названии работы не встречаются
 * в начале: обозначения колонок и «№».
 *
 * @param {string[]} nonEmpty — непустые ячейки строки
 * @returns {boolean}
 */
function isHeaderRow(nonEmpty) {
  const joined = nonEmpty.join(' ');
  // Шапка — это когда НЕСКОЛЬКО ячеек являются обозначениями колонок,
  // а не когда одно слово встретилось где угодно.
  //
  // Раньше требовалось «слово колонки в ЛЮБОЙ ячейке» — и колонка
  // «Примечание» со значением «акт № 5» делала шапкой каждую строку
  // данных: 0 из 300 на реальной ведомости (найдено верификатором).
  // Теперь нужно минимум ДВА обозначения колонок в одной строке:
  // «№ | Наименование | Ед. изм. | Кол-во» — да, «Очистка | м3 | 340 | акт № 5» — нет.
  //
  // ВАЖНО: только ОБЩИЕ обозначения, которые встречаются в любой ведомости.
  // Здесь нельзя перечислять колонки конкретного заказчика («код_метода»,
  // «метод_очистки»…) — на другом тендере их не будет, и правило не сработает.
  // Ведомости с незнакомыми колонками ловятся СТРУКТУРНО: см. блок ниже.
  const columnWords = [
    /^(№|п\/п|номер)$/i,
    /^(наименование|наименование работ|виды работ|вид работ|работы)$/i,
    /^(ед\.?\s*изм\.?|единица|единицы)$/i,
    /^(кол-?во|количество)(\s*[,;(].*)?$/i,
    /^(объ[её]м|объ[её]мы)(\s+работ\w*)?(\s*[,;(].*)?$/i,
    /^(цена|сумма|стоимость)(\s*[,;(].*)?$/i
  ];
  let hits = 0;
  for (const c of nonEmpty) {
    if (columnWords.some((re) => re.test(c))) hits += 1;
  }
  if (hits >= 2) {
    // У шапки все ячейки короткие: она не описывает работу.
    const longest = nonEmpty.reduce((a, s) => (s.length > a.length ? s : a), '');
    return longest.length <= 30;
  }

  // ── Структурный признак шапки (без словарей) ─────────────────────────────
  // Ведомость заказчика может называть колонки как угодно: «Код_метода»,
  // «Характер_отложений», «Объем_емкости_м3». Перечислять такие слова
  // нельзя — на другом тендере их не будет.
  //
  // Поэтому шапку узнаём ПО СТРУКТУРЕ: строка, где
  //   • нет ни одного числа (в данных числа есть почти всегда),
  //   • все ячейки короткие (заголовки, а не описания работ),
  //   • минимум две ячейки содержат единицу измерения в своём имени
  //     («Площадь_м2», «Осадок_т», «Объем_емкости_м3»).
  // Два последних условия вместе дают: это перечень КОЛОНОК с величинами.
  const noNumbers = !nonEmpty.some((c) => numCell(c) !== null);
  if (!noNumbers) return false;
  const longestCell = nonEmpty.reduce((a, s) => (s.length > a.length ? s : a), '');
  if (longestCell.length > 40) return false;
  if (nonEmpty.length < 3) return false;
  const unitNames = nonEmpty.filter((c) => unitFromHeaderName(c) !== null).length;
  return unitNames >= 2;
}

/**
 * Приводит ячейку к нормализованной строке: нижний регистр, без пробелов
 * по краям, схлопнутые внутренние пробелы, единая точка.
 */
/** Минимальная длина блока-копии. Короче — обычное совпадение строк. */
const MIN_BLOCK = 8;

/**
 * Сколько РАЗНЫХ подписей должно быть в блоке, чтобы считать его копией.
 *
 * Копия таблицы содержит разные позиции. Блок из одинаковых строк
 * («Замена лампы | шт | 1» × 60) — это данные, а не копия, и схлопывать его
 * нельзя: иначе 60 позиций превратятся в 12 и недобор не будет виден.
 */
const MIN_DISTINCT_IN_BLOCK = 3;

function normCell(v) {
  return String(v == null ? '' : v)
    .toLowerCase()
    .replace(/\u00a0/g, ' ')
    .replace(/\s+/g, ' ')
    .trim();
}

/** Единица измерения или нет. */
function isUnitCell(v) {
  const s = normCell(v);
  if (!s || s.length > 20) return false;
  if (UNITS.has(s)) return true;
  // «м3», «м³», «куб. м», «пог. м» с любыми разделителями.
  const compact = s.replace(/[\s.]/g, '');
  if (UNITS.has(compact)) return true;
  // Доменные единицы ТЭЦ и энергетики: «Гкал/час», «кВт·ч», «тыс. м3»,
  // «чел/час», «1000 м3». Без них ведомости тепловых нагрузок давали 0
  // позиций — детектор молча выключался (найдено верификатором).
  if (/^(гкал|ккал|квт|мвт|кгс)([\/·\s.]*(ч|час|ч\.|кг|м2|м3))*$/i.test(compact)) return true;
  if (/^(тыс\.?|1000)\s*(м3|м2|м|т|шт|гкал|квт)/i.test(s)) return true;
  if (/^(чел\.?|человеко)\s*[\/·-]?\s*(час|ч|дн|сут|смен)/i.test(s)) return true;
  // Единица ВНУТРИ ячейки с числом: «340 м3», «12,5 т». Это единый формат
  // выгрузок, где колонка единицы слилась с количеством. Без этого вся
  // такая ведомость давала 0 позиций (найдено верификатором).
  if (/^\d+(?:[.,]\d+)?\s*(м2|м3|м²|м³|куб|кв|пог|п\.?м|м\.?п|шт|кг|т|тн|тонн|компл|гкал|ккал|квт|мвт|литр|л|км|м|апп|труб|секц|узел|элемент)$/i.test(s)) return true;
  return /^(м|м2|м3|м²|м³|км|см|мм|т|тн|кг|г|шт|ед|компл|л|мл|гкал|ккал|квт|квтч|мвт|апп|труб|секц|узел|элемент|челчас|услед)$/.test(compact);
}

/**
 * Единица измерения внутри ИМЕНИ КОЛОНКИ.
 *
 * Реальная ведомость заказчика (Дефектная ведомость RUNEV-11842, 673 позиции)
 * называет колонки так: «Площадь_м2», «Объем_емкости_м3», «Осадок_т»,
 * «Длина_трубки_мм», «Кол_во_трубок_шт». Единица стоит ВНУТРИ имени, через
 * подчёркивание, а в данных — только число.
 *
 * Без этого вся ведомость давала 0 позиций: детектор молча выключался на
 * настоящем документе заказчика (проверено на реальном файле).
 *
 * @param {string} header — текст заголовка колонки
 * @returns {string|null} единица или null
 */
function unitFromHeaderName(header) {
  const s = normCell(header);
  if (!s) return null;
  // Вся ячейка — уже единица («м3») или обозначение колонки («Ед. изм.»).
  // Обозначение колонки единицей НЕ является: там единица стоит в данных.
  if (/^(ед\.?\s*изм\.?|единица|единицы)$/i.test(s)) return null;
  // Последний сегмент после подчёркивания/пробела/точки: «Объем_емкости_м3» → «м3».
  const parts = s.split(/[_\s]+/).filter(Boolean);
  for (let i = parts.length - 1; i >= 0; i -= 1) {
    const tail = parts[i].replace(/[.,;:]+$/, '');
    // Сегмент «ед»/«шт» сам по себе не годится: он входит в «Ед. изм.».
    if (/^(ед|единиц|единица)$/i.test(tail)) continue;
    if (isUnitCell(tail)) return tail;
    const compact = tail.replace(/\^/g, '');
    if (isUnitCell(compact)) return compact;
  }
  return null;
}

/** Числовое количество: 340, 12,5, 1 234,5, «340 м3», «24м3». */
function numCell(v) {
  const s = normCell(v).replace(/\s/g, '').replace(',', '.');
  if (!s) return null;
  // Чистое число.
  if (/^-?\d+(?:\.\d+)?$/.test(s)) {
    const n = Number(s);
    return Number.isFinite(n) ? n : null;
  }
  // Число с единицей в ОДНОЙ ячейке: «340м3», «12.5т», «250п.м».
  // Частый формат в выгрузках, где колонка единицы потерялась.
  // Найдено верификатором: такие строки давали 0 позиций.
  const m = /^(-?\d+(?:\.\d+)?)(м2|м3|м²|м³|куб|кв|пог|п\.?м|м\.?п|шт|кг|т|тн|тонн|компл|гкал|ккал|квт|мвт|литр|л|км|м|апп|труб|секц|узел|элемент)$/i.exec(s);
  if (m) {
    const n = Number(m[1]);
    return Number.isFinite(n) ? n : null;
  }
  return null;
}

/**
 * Текст названия: есть буквы, длина больше 3.
 *
 * ── Почему здесь НЕТ списка заголовков ────────────────────────────────────
 * Раньше функция отбрасывала «шапку» по совпадению с названием колонки:
 * «работы», «объём», «всего», «итого». Это давало два класса ошибок, оба
 * найдены верификатором:
 *   • «Работы по очистке резервуара Р-1» — префиксное совпадение, счёт падал
 *     вдвое на ведомости, где все названия так начинаются;
 *   • «Работы» (название ровно одним словом) и «Всего отходов вывезти,
 *     партия N» — отбрасывались как шапка, счёт 0 и 100 из 120.
 *
 * Причина в том, что по ОДНОЙ ячейке «шапка или данные» неразрешимо: в
 * заголовке таблицы стоит «Работы», и в данных тоже «Работы».
 *
 * Решается это контекстом строки, а не словарём: строка шапки не содержит
 * чисел, поэтому она и так не попадёт в кандидаты (там требуется хотя бы одно
 * число). Значит список заголовков здесь не нужен вовсе — убираем источник
 * ложных срабатываний.
 */
function isNameCell(v) {
  const s = normCell(v);
  // Названия из 3 букв — норма: «ТЭН», «Люк», «Шов», «Бак», «Вал», «Кран».
  // Раньше порог был 4 символа, и такие позиции терялись (0 из 300 —
  // найдено верификатором). Но 1–2 символа отсекаем: это коды и «№».
  if (s.length < 3) return false;
  // Должны быть буквы (кириллица или латиница) — иначе это код или число.
  if (!/[а-яёa-z]/i.test(s)) return false;

  // Подстрока-продолжение: «в т.ч.», «в том числе» — не отдельная позиция.
  // Маркеры списка (•, -, —, ·) и двоеточие снимаются ПЕРЕД проверкой:
  // «• в т.ч. ППР» и «в том числе: ППР» иначе проходили и удваивали счёт
  // (найдено верификатором: 600 вместо 300).
  const noBullet = s.replace(/^[\s•·\-—–*•()0-9.)\]]+/, '');
  if (/^(в\s*т\.?\s*ч\.?|в\s*том\s+числе)(\s|\.|:|$)/i.test(noBullet)) return false;

  // Служебные строки итогов: только когда это ВСЯ ячейка («Итого»,
  // «Всего»), а не начало названия работы.
  if (/^(итог|всего|итого)$/i.test(s)) return false;

  return true;
}

/** Ячейка похожа на номер позиции: 1..9999 без дробной части. */
function isSeqCell(v) {
  const s = normCell(v);
  return /^\d{1,4}$/.test(s) && Number(s) >= 0 && Number(s) <= 9999;
}

/**
 * Считает позиции в сетке одной таблицы.
 *
 * @param {Array<Array<any>>} rows — строки, каждая строка — массив значений ячеек
 * @returns {{positions: number, headerUnit: string|null, hasSeq: boolean}}
 */
function countTableRows(rows) {
  const grid = Array.isArray(rows) ? rows : [];

  // ── 1. Шапка колонки единиц ─────────────────────────────────────────────
  // В реальных ведомостях единицу пишут в заголовке: «Объём, м3», «Ед. изм.».
  // В данных строк тогда только число. Ищем единицу в шапке и запоминаем её
  // индекс колонки, чтобы строки считались по наличию названия и количества.
  let headerUnit = null;
  let headerUnitCol = -1;
  // Строка, где найдена шапка. Строки ВЫШЕ неё — заголовки отчёта, а не
  // данные: они не должны считаться позициями по объявленной ниже шапке.
  let headerRowIndex = -1;
  // Колонка количества: нужна, чтобы понять, что строка относится к таблице
  // с объявленной единицей (а не к графику работ ниже, где её нет).
  let quantityCol = -1;
  // Единица для каждой шапки: строка → единица. Нужна потому, что ведомость
  // может повторять шапку на каждый раздел, и каждая секция должна знать
  // свою единицу, а не только первая.
  const headerUnits = new Map();
  // Первая шапка: строки выше неё — заголовки отчёта.
  let firstHeaderRow = -1;
  for (let r = 0; r < grid.length; r += 1) {
    const row = grid[r] || [];
    for (let c = 0; c < row.length; c += 1) {
      const s = normCell(row[c]);
      if (!s) continue;
      // НЕ пропускаем колонку повторно: ведомость может повторять шапку
      // на каждый раздел, и каждая такая строка должна попасть в карту
      // единиц. Пропуск по индексу колонки оставлял только первую шапку.

      // «Объём, м3» / «Кол-во, т» — единица внутри заголовка после запятой.
      // Берём последнюю часть после разделителя и проверяем, единица ли это.
      if (/(объ[её]м|количеств|кол-?во)/i.test(s)) {
        quantityCol = c;
        const tail = s.split(/[,;()]/).map((x) => x.trim()).filter(Boolean).pop() || '';
        if (isUnitCell(tail)) {
          headerUnit = tail;
          headerUnitCol = c;
          headerRowIndex = r;
          headerUnits.set(r, tail);
          if (firstHeaderRow < 0) firstHeaderRow = r;
          continue;
        }
      }
      // «Объём м3» без запятой: последнее слово в заголовке — единица.
      const words = s.split(' ');
      const last = words[words.length - 1];
      if (isUnitCell(last) && /(объ[её]м|количеств|кол-?во)/i.test(s)) {
        headerUnit = last;
        headerUnitCol = c;
        headerRowIndex = r;
        headerUnits.set(r, last);
        if (firstHeaderRow < 0) firstHeaderRow = r;
        continue;
      }
      // Двухстрочная шапка: «Наименование | Объём», ниже «| м3».
      // Единица стоит в следующей строке в той же колонке.
      if (/(объ[её]м|количеств|кол-?во)/i.test(s)) {
        const nextRow = grid[r + 1] || [];
        const below = normCell(nextRow[c]);
        if (isUnitCell(below)) {
          headerUnit = below;
          headerUnitCol = c;
          headerRowIndex = r + 1;
          headerUnits.set(r + 1, below);
          if (firstHeaderRow < 0) firstHeaderRow = r + 1;
          continue;
        }
      }
      // Отдельная колонка «Ед. изм.» без значения — единица будет в строках,
      // но саму колонку запомним, чтобы не спутать с количеством.
      if (/^(ед\.?\s*изм|единица)$/i.test(s)) {
        headerUnitCol = c;
      }
      // Единица ВНУТРИ имени колонки: «Площадь_м2», «Объем_емкости_м3»,
      // «Осадок_т». Так устроена реальная ведомость заказчика (673 позиции
      // в файле Дефектная_ведомость_RUNEV-11842). Без этого вся ведомость
      // давала 0 — детектор молча выключался на настоящем документе.
      //
      // ВАЖНО: только если вся строка выглядит как шапка — иначе строка
      // сводки «Сводка объёмов за май | м3 | 12345» объявит себя шапкой
      // и сдвинет границу данных.
      if (isHeaderRow(grid[r].map((v) => normCell(v)).filter(Boolean))) {
        const unitInName = unitFromHeaderName(s);
        if (unitInName) {
          headerUnit = unitInName;
          headerUnitCol = c;
          headerRowIndex = r;
          headerUnits.set(r, unitInName);
          if (firstHeaderRow < 0) firstHeaderRow = r;
        }
      }
    }
  }

  // ── 2. Строки данных ────────────────────────────────────────────────────
  // Сначала собираем кандидатов, потом решаем: колонка с возрастающими
  // подряд числами (1,2,3,…) — это нумерация, а не объём. Различать нужно
  // постфактум: по одной строке номер позиции и количество неотличимы.
  let hasSeq = false;

  // ── 1. Сбор строк-кандидатов ───────────────────────────────────────────
  // Ничего не решаем на первом проходе: наличие единиц в таблице выясняется
  // по всем строкам, а не по текущей. Иначе смешанная ведомость (часть строк
  // с единицей, часть без) теряла половину позиций — 150 из 300.
  const collected = [];
  let afterHeader = false;
  for (let rowIdx = 0; rowIdx < grid.length; rowIdx += 1) {
    const row = grid[rowIdx];
    if (!Array.isArray(row) || !row.length) continue;

    const cells = row.map((v) => normCell(v));
    const nonEmpty = cells.filter(Boolean);
    if (!nonEmpty.length) continue;

    // Шапка таблицы: обозначения колонок, а не работа.
    if (isHeaderRow(nonEmpty)) {
      // Шапка задаёт границу данных даже без объявленной единицы
      // («№ | Наименование | Ед. изм. | Кол-во»). Раньше firstHeaderRow
      // выставлялся только при «Объём, м3», и строки сводки над таблицей
      // считались позициями: 202 вместо 200 (найдено верификатором).
      if (firstHeaderRow < 0) firstHeaderRow = rowIdx;
      // Единица может быть объявлена В ЭТОЙ строке или В СЛЕДУЮЩЕЙ
      // (двухстрочная шапка: «Объём» сверху, «м3» снизу). Если ни там,
      // ни там её нет — наследуем от предыдущей таблицы: раздел с новой
      // шапкой остаётся частью той же ведомости, и его единица та же.
      // Сбрасываем только для шапки ДРУГОЙ таблицы (график: этап/срок).
      const ownUnit = headerUnits.get(rowIdx) || headerUnits.get(rowIdx + 1) || null;
      const isScheduleHeader = nonEmpty.filter((c) => /^(этап\w*|срок\w*|дней|дни|период|дата|месяц\w*|недел\w*|год)$/i.test(c)).length >= 1;
      const inherited = ownUnit || (isScheduleHeader ? null : headerUnit);
      if (isScheduleHeader) {
        headerUnit = null;
        headerUnitCol = -1;
        quantityCol = -1;
      }
      collected.push({ kind: 'break', rowIdx, unit: inherited });
      continue;
    }

    // Строка-продолжение двухстрочной шапки: только единица в той же
    // колонке, где объявлен объём. Граница таблицы, не позиция и не данные.
    if (headerUnits.has(rowIdx) && nonEmpty.length === 1 && isUnitCell(nonEmpty[0])) {
      continue;
    }
    // Настоящая шапка с объявленным количеством: после неё пустой объём
    // означает незаполненную позицию, а не заголовок.
    if (rowIdx <= headerRowIndex) { /* до шапки — отчёт */ }

    // Подстрока-продолжение предыдущей позиции отсекается в isNameCell:
    // там же обрабатываются маркеры списка и двоеточие.

    // Итоговая строка — служебная, не название работы.
    // Признак: название НАЧИНАЕТСЯ с итогового слова, а не равно ему.
    // Раньше лимит был «не больше 3 непустых ячеек», и сметная форма
    // «Итого по разделу | м3 | 1234 | 99999» проходила как позиция:
    // +10 к счёту (найдено верификатором).
    // Итоговая строка — служебная, а не название работы.
    //
    // Различаем два похожих случая:
    //   • «Итого по разделу 1», «Всего по ведомости», «Итого» — служебные;
    //   • «Всего отходов вывезти, партия N» — это НАЗВАНИЕ работы.
    // Признак итога: после итогового слова идёт «по», «за», двоеточие или
    // конец строки. Название работы продолжается значащим словом.
    if (nonEmpty.some((c) => /^(итог|всего|итого)(\s*$|\s+(по|за|на|с|из)(\s|$)|[:.,—]|\s+(работ|объ[её]м|затрат|стоимост|сумм))/i.test(c))) continue;

    const names = nonEmpty.filter((c) => isNameCell(c));
    if (!names.length) continue;

    // Строка из одной непустой ячейки БЕЗ числа — обычно заголовок раздела
    // («Раздел 2», «Отчёт за период»). Но точно так же выглядит позиция
    // с незаполненной колонкой количества в ведомости без колонки №.
    //
    // Структурно эти случаи неразличимы. Выбираем в пользу ПОЗИЦИИ:
    // потеря 30 позиций из 300 (10 %) искажает ожидание сильнее, чем
    // три лишних заголовка раздела (1 %). Заголовки в итоге ограничены:
    // их число равно числу разделов, а не строк.

    const unitCells = nonEmpty.filter((c) => isUnitCell(c));
    const seqCells = nonEmpty.filter((c) => isSeqCell(c));
    const nums = nonEmpty.map((c) => numCell(c)).filter((n) => n !== null && n >= 0);

    // Новая шапка в середине листа — началась другая таблица.
    // Новая ШАПКА в середине листа — началась другая таблица.
    //
    // КОРЕНЬ (найдено верификатором): условие было слишком широким —
    // «две непустые ячейки без чисел, обе короткие». Под него попадала
    // обычная строка данных с незаполненным объёмом: ['Р-7', '-'].
    // Единица обнулялась, и весь хвост ведомости (150 из 301) выпадал
    // молча. То же с заголовком раздела во второй ячейке и с повторной
    // шапкой без единицы.
    //
    // Теперь требуем, чтобы это была именно ШАПКА: минимум два обозначения
    // колонок («наименование», «кол-во», «ед. изм.») либо одна ячейка
    // с объёмом и вторая с единицей. Строка данных эти условия не выполняет.
    const looksLikeColumnHeader = !nums.length && nonEmpty.length >= 2
      && !seqCells.length
      && nonEmpty.every((c) => c.length <= 30)
      && (
        nonEmpty.filter((c) => /^(№|п\/п|номер|наименование|вид\w*\s+работ\w*|работы|ед\.?\s*изм\.?|единиц\w*|кол-?во|количество|объ[её]м\w*|цена|сумма|стоимость|этап\w*|срок\w*|дней|дни|период|дата|месяц\w*|недел\w*|год)(\s*[,;(].*)?$/i.test(c)).length >= 2
        || (/(объ[её]м|количеств|кол-?во)/i.test(nonEmpty.join(' ')) && nonEmpty.some((c) => isUnitCell(c)))
      );    if (looksLikeColumnHeader && rowIdx > headerRowIndex) {
      // Шапка без объявленной единицы: если у неё ЕСТЬ колонка объёма
      // (пусть без единицы), единицу наследуем от предыдущей таблицы —
      // это продолжение той же ведомости (раздел с новой шапкой).
      // Сбрасываем только когда шапка явно описывает ДРУГУЮ таблицу
      // (график: этап/срок/дней). Если у ЭТОЙ шапки есть своя единица
      // (карта headerUnits), берём её — иначе после графика вторая ВОР
      // оставалась без единицы и теряла все позиции.
      const isScheduleHeader = nonEmpty.filter((c) => /^(этап\w*|срок\w*|дней|дни|период|дата|месяц\w*|недел\w*|год)$/i.test(c)).length >= 1;
      const ownUnit = headerUnits.get(rowIdx) || headerUnits.get(rowIdx + 1) || null;
      if (isScheduleHeader && !ownUnit) {
        headerUnit = null;
        headerUnitCol = -1;
        quantityCol = -1;
      } else if (ownUnit) {
        headerUnit = ownUnit;
      }
      collected.push({ kind: 'break', rowIdx, unit: headerUnit || ownUnit || null });
      continue;
    }

    collected.push({
      rowIdx,
      cells,
      names,
      unitHere: unitCells.length > 0,
      seqCells,
      nums,
      hasDash: nonEmpty.some((c) => /^(-|—|–|н\/д|х|нет)$/i.test(c)),
      nonEmptyLen: nonEmpty.length,
      afterHeader
    });
  }

  // ── 2. Есть ли в таблице единицы вообще ─────────────────────────────────
  // Если хоть где-то есть единица измерения, эта таблица — ведомость, и
  // строки без единицы в ней тоже позиции (заказчик не заполнил колонку).
  // Так же работает объявленная шапка «Объём, м3».
  let tableHasUnits = !!headerUnit;
  for (const item of collected) {
    if (item.kind === 'break') continue;
    if (item.unitHere) { tableHasUnits = true; break; }
  }

  // ── 2б. Разбиение на секции по шапкам ───────────────────────────────────
  // Заголовок новой таблицы (или раздела) закрывает предыдущую секцию.
  // Каждая секция решает про единицы самостоятельно: у ведомости они есть,
  // у графика работ — нет. Так заголовок раздела внутри ВОР не ломает
  // подсчёт хвоста, а график ниже ВОР не считается ведомостью.
  const sections = [];
  let current = { items: [], hasHeaderUnit: false, unit: null };
  for (const item of collected) {
    if (item.kind === 'break') {
      if (current.items.length) sections.push(current);
      // Секция после шапки наследует единицу ЭТОЙ шапки, а не первой.
      current = { items: [], hasHeaderUnit: !!item.unit, unit: item.unit || null };
      continue;
    }
    if (item.unitHere) current.hasHeaderUnit = true;
    current.items.push(item);
  }
  if (current.items.length) sections.push(current);

  // ── 2в. Отбор позиций по секциям ────────────────────────────────────────
  const candidates = [];
  // Строки-границы (заголовки разделов). Дубль таблицы не должен
  // схлопываться через них — это разные разделы, а не копия.
  const sectionBreaks = [];
  for (let sIdx = 0; sIdx < sections.length; sIdx += 1) {
    const section = sections[sIdx];
    // Единицы секции: в её строках ИЛИ в ЕЁ шапке. Раньше брали только
    // первую секцию, и при повторе шапки на каждый раздел считался лишь
    // первый: 100 из 300 (найдено верификатором).
    const headerApplies = !!section.unit || (!!headerUnit && sIdx === 0);
    const sectionHasUnits = section.hasHeaderUnit || headerApplies;
    // Единиц нет ни в строках, ни в шапке — ведомостью не считаем.
    //
    // ПОЧЕМУ НЕ ПЫТАЕМСЯ УГАДАТЬ: таблица «№ | Наименование | Кол-во» без
    // единиц структурно НЕОТЛИЧИМА от графика работ «№ | Этап | Дней» и от
    // оглавления «№ | Раздел | Стр.». Везде два числа и сквозная нумерация.
    // Попытка считать такие таблицы ведомостями давала 140 позиций на
    // графике и 200 на оглавлении — а это ЛОЖНАЯ ТРЕВОГА на полном разборе.
    //
    // Цена выбора: ведомость без единиц детектором не считается (порог 0 —
    // анализ идёт как раньше). Это ЧЕСТНО: детектор молчит, а не врёт.
    // Молчаливый недобор (показать «полный разбор» при потере половины)
    // недопустим, а ложная тревога недопустима тоже — оба хуже нуля.
    if (!sectionHasUnits) continue;

    for (const item of section.items) {
      // Строки ВЫШЕ ПЕРВОЙ шапки — заголовки отчёта, а не данные.
      // Используем первую найденную шапку, а не последнюю: при повторной
      // шапке на каждый раздел последняя отсекла бы все предыдущие секции.
      if (firstHeaderRow >= 0 && item.rowIdx < firstHeaderRow) continue;

      // Заголовок раздела: одна непустая ячейка — «Раздел 2. Прочие
      // работы», «Часть 1», «Этап 3». Число внутри названия не мешает:
      // это нумерация раздела, а не количество. Позицией не является,
      // но помечает границу таблицы.
      //
      // ВАЖНО: признак — только служебное слово в начале («Раздел 2»,
      // «Часть 1»). Раньше сюда же попадала любая строка из ОДНОЙ ячейки
      // без чисел, и позиция с незаполненным объёмом считалась заголовком
      // раздела: 150 пустых из 300 давали ровно 150 (потеря половины,
      // найдено верификатором). Пустая ячейка — не заголовок.
      // Заголовок раздела: служебное слово + НОМЕР раздела и НЕТ данных.
      //
      // Два условия обязательны вместе:
      //   • номер («Раздел 2», «1. Цех 1», «1.1. Подготовительные работы») —
      //     без номера это может быть название работы;
      //   • в строке нет количества и единицы — у настоящей позиции они есть.
      //
      // КОРЕНЬ (найдено верификатором): условие было по одному слову, и
      // названия работ «Блок питания», «Секция трубопровода», «Часть
      // футеровки», «Этап зачистки» считались заголовками: 0 из 100.
      // Плюс нумерованные заголовки «1. Цех 1» не распознавались вовсе,
      // и три раздела схлопывались как копия (100 из 300).
      const firstCell = (item.cells.find(Boolean) || '');
      const numberedTitle = /^(\d+(?:\.\d+)*\.?\s+)?(раздел|часть|этап|глава|подраздел|секция|блок|цех|участок)(\s|\.|$)/i.test(firstCell);
      const hasSectionNumber = /^\d/.test(firstCell) || /\s\d/.test(firstCell) || /\s(и|v|vi|vii|viii|ix|x)\b/i.test(firstCell);
      const noDataCells = !item.nums.length && !item.unitHere;
      const looksLikeSectionTitle = numberedTitle && hasSectionNumber && noDataCells;
      if (looksLikeSectionTitle) {
        sectionBreaks.push(item.rowIdx);
        continue;
      }

      // Подпись внизу ведомости: «Составил | Иванов», «Проверил | Петров»,
      // «Главный инженер | Сидоров». Две-три короткие ячейки-слова без
      // единиц и чисел. Позицией не является, но и раздел не открывает.
      // Раньше такая строка считалась позицией с пустым объёмом: 151 из 150.
      const wordCells = item.nonEmptyLen;
      const allShortWords = item.cells.filter(Boolean).every((c) => c.length <= 30 && /^[а-яёa-z\s.]+$/i.test(c));
      if (!item.nums.length && !item.unitHere && wordCells <= 3 && allShortWords
        && /^(составил|проверил|согласовал|утвердил|главный инженер|начальник|мастер|подпись)(\s|$)/i.test(firstCell)) {
        continue;
      }

      const hasNumber = item.nums.length > 0;
      const filledBySeq = item.seqCells.length > 0;
      const emptyQty = !hasNumber && (filledBySeq || headerApplies);

      if (!(hasNumber || filledBySeq || item.hasDash || emptyQty)) continue;

      if (item.seqCells.length) hasSeq = true;
      candidates.push({
        rowIdx: item.rowIdx,
        cells: item.cells,
        nums: item.nums,
        numIdx: item.cells.map((s, i) => (numCell(s) !== null ? i : -1)).filter((i) => i >= 0),
        unitHere: item.unitHere,
        hasDash: item.hasDash,
        hasSeqCell: filledBySeq,
        emptyQty
      });
    }
  }

  // ── 2г. Схлопывание дублей внутри листа ─────────────────────────────────
  // Один и тот же перечень иногда вставляют в лист дважды (скопировали
  // таблицу целиком). Тогда счёт удваивается.
  //
  // ── ПОЧЕМУ ЗДЕСЬ МАКСИМАЛЬНАЯ ОСТОРОЖНОСТЬ ───────────────────────────────
  // Схлопывание уменьшает счёт. Если оно ошибётся, получится МОЛЧАЛИВЫЙ
  // НЕДОБОР: детектор покажет «разбор полный», а половина ведомости
  // потеряна. Это хуже завышения — завышение хотя бы видно как тревога.
  //
  // Найдено верификатором на реальных данных: спецификации часто состоят из
  // ОДИНАКОВЫХ строк («Замена лампы | шт | 1» × 60 — примечание с помещением
  // в другой колонке). Наивная дедупликация объявляла их копией таблицы и
  // оставляла 12 позиций из 60.
  //
  // Поэтому копией считаем ТОЛЬКО блок, который:
  //   • повторяется целиком и подряд (≥ MIN_BLOCK строк);
  //   • НЕОДНОРОДЕН — внутри блока хотя бы 3 разных подписи. Однородный
  //     блок из одинаковых строк — это данные, а не копия таблицы;
  //   • не разделён шапкой или заголовком раздела.
  const rowSignatures = candidates.map(rowSignature);
  const duplicateRanges = [];
  for (const range of findRepeatedBlocks(rowSignatures)) {
    const len = range.len || Math.floor((range.to - range.from) / 2);
    const firstStart = candidates[range.from - len];
    const secondStart = candidates[range.from];
    if (!firstStart || !secondStart) continue;

    // Неоднородность блока: копия таблицы содержит разные позиции.
    // Одинаковые строки подряд — это повторяющиеся работы, а не копия.
    const blockSigs = new Set(rowSignatures.slice(range.from - len, range.from));
    if (blockSigs.size < MIN_DISTINCT_IN_BLOCK) continue;

    const headerRows = collected.filter((it) => it.kind === 'break').map((it) => it.rowIdx);
    const hasBreak = headerRows.some((row) => row >= firstStart.rowIdx && row <= secondStart.rowIdx)
      || sectionBreaks.some((row) => row >= firstStart.rowIdx && row <= secondStart.rowIdx);
    if (hasBreak) continue;
    duplicateRanges.push(range);
  }
  const isDuplicate = new Set();
  for (const range of duplicateRanges) {
    for (let i = range.from; i < range.to; i += 1) isDuplicate.add(i);
  }
  const uniqueCandidates = candidates.filter((_, i) => !isDuplicate.has(i));
  const duplicatedRows = isDuplicate.size;

  // ── 3. Отсев колонки-нумерации ──────────────────────────────────────────
  // Колонка, где значения идут 1,2,3,… подряд почти без пропусков, — это
  // номера позиций. Её числа не могут быть объёмом: иначе каждая строка
  // «| 1 | Очистка | 1 |» давала бы двойной счёт.
  //
  // ВАЖНО: объёмы тоже бывают последовательными (101, 102, 103…), а иногда
  // и ровно 1,2,3…N. Поэтому отсев применяется, ТОЛЬКО если после него
  // остаётся хотя бы одно другое число: у настоящей нумерации всегда есть
  // отдельная колонка объёма. Если объём — единственное число в строке,
  // отсекать его нельзя, иначе ведомость «1, 2, 3…» обнулится.
  const seqCandidates = [];
  const width = uniqueCandidates.reduce((w, c) => Math.max(w, c.cells.length), 0);
  for (let col = 0; col < width; col += 1) {
    const seq = [];
    for (const c of uniqueCandidates) {
      const n = numCell(c.cells[col]);
      if (n !== null && Number.isInteger(n) && n >= 0 && n <= 9999) seq.push(n);
    }
    if (seq.length < 8) continue;
    // Покрытие: почти каждая строка-кандидат имеет число в этой колонке.
    if (seq.length / uniqueCandidates.length < 0.85) continue;
    // Начинается с 1 (допускаем 0 — редкая нумерация с нуля).
    if (seq[0] > 1) continue;
    // Доля шагов «+1» в возрастающей последовательности.
    let steps = 0;
    let good = 0;
    for (let i = 1; i < seq.length; i += 1) {
      if (seq[i] === seq[i - 1]) continue;
      steps += 1;
      if (seq[i] === seq[i - 1] + 1) good += 1;
    }
    if (steps >= 5 && good / steps >= 0.9) seqCandidates.push(col);
  }

  // Отсекаем ТОЛЬКО ОДНУ колонку — лучшего кандидата в нумерацию.
  //
  // Раньше отсекались все подходящие колонки. Если объёмы тоже шли подряд
  // с 1 (штуки, комплекты) или перезапускались по разделам, снимались обе
  // колонки, и счёт обнулялся: 300 позиций → 0. У ведомости нумерация одна,
  // поэтому и снимать надо одну — ту, что начинается с 1 и идёт ровнее всех.
  let seqCol = -1;
  if (seqCandidates.length) {
    // Приоритет: колонка, начинающаяся с 1, затем с наибольшим покрытием.
    let bestScore = -1;
    for (const col of seqCandidates) {
      const vals = uniqueCandidates.map((c) => numCell(c.cells[col]));
      const filled = vals.filter((v) => v !== null);
      if (!filled.length) continue;
      const startsAtOne = filled[0] === 1 || filled[0] === 0 ? 1 : 0;
      const score = startsAtOne * 1000 + filled.length;
      if (score > bestScore) { bestScore = score; seqCol = col; }
    }
    // Проверяем, можно ли снять колонку-нумерацию.
    //
    // Два случая, и они ОБА законны:
    //   • в строках есть другое число (объём) — снимаем нумерацию, объём
    //     остаётся признаком позиции;
    //   • других чисел нет вовсе — тогда снимать нельзя, колонка и есть
    //     объём (ведомость «1, 2, 3…» без колонки №).
    //
    // Раньше порог 0.5 не различал эти случаи и вёл себя скачком: при 60
    // заполненных объёмах из 120 (доля 0.5) нумерация снималась, при 59
    // отменялась — счёт прыгал 120 ↔ 59 на одном прочерке (найдено
    // верификатором). Теперь решаем по наличию хотя бы одного другого
    // числа, а не по доле.
    if (seqCol >= 0) {
      const anyOther = uniqueCandidates.some((c) => c.numIdx.filter((i) => i !== seqCol).length > 0);
      // Если других чисел нет — единственная колонка и есть объём, снимать
      // нельзя. Это ведомость «объёмы 1, 2, 3…» без колонки №.
      //
      // Обратный случай — таблица из одних номеров при пустой колонке
      // объёма — структурно НЕОТЛИЧИМ от неё: там тоже одна числовая
      // колонка с 1,2,3… Поэтому выбираем безопасное: не снимаем.
      // Завышение здесь невозможно (числа реально есть в каждой строке),
      // а ошибочное обнуление выключило бы детектор на настоящей ведомости.
      if (!anyOther) seqCol = -1;
    }
  }
  const seqCols = new Set(seqCol >= 0 ? [seqCol] : []);

  // ── 4. Итог ─────────────────────────────────────────────────────────────
  let positions = 0;
  for (const c of uniqueCandidates) {
    // Числа за вычетом колонки-нумерации.
    const quantityNums = c.numIdx
      .filter((i) => !seqCols.has(i))
      .map((i) => numCell(c.cells[i]))
      .filter((n) => n !== null);

    if (quantityNums.length) {
      positions += 1;
      continue;
    }

    // Чисел не осталось. Это может быть:
    //   • строка оглавления (только номер, объёма нет) — не позиция;
    //   • позиция с ПРОЧЕРКОМ вместо объёма — позиция.
    // Различаем по наличию единицы измерения или прочерка: у оглавления
    // нет ни того, ни другого.
    if (c.hasDash || c.unitHere || c.hasSeqCell || c.emptyQty) {
      positions += 1;
    }
  }

  return { positions, headerUnit, hasSeq: hasSeq || seqCols.size > 0 };
}

/**
 * Извлекает сетки из .xlsx буфера через ExcelJS.
 * Возвращает массив таблиц: по одной на лист.
 *
 * @param {Buffer} buf
 * @returns {Promise<Array<{name: string, rows: Array<Array<any>>}>>}
 */
async function gridFromXlsx(buf) {
  const ExcelJS = require('exceljs');
  const wb = new ExcelJS.Workbook();
  await wb.xlsx.load(buf);
  const sheets = [];
  wb.eachSheet((sheet) => {
    const rows = [];
    sheet.eachRow({ includeEmpty: false }, (row) => {
      const vals = [];
      row.eachCell({ includeEmpty: true }, (cell) => {
        const v = cell.value;
        if (v == null) { vals.push(''); return; }
        if (typeof v === 'object' && v.text) { vals.push(String(v.text)); return; }
        if (typeof v === 'object' && v.result != null) { vals.push(String(v.result)); return; }
        if (typeof v === 'object' && v.error) { vals.push(''); return; }
        if (typeof v !== 'object') { vals.push(String(v)); return; }
        vals.push('');
      });
      rows.push(vals);
    });
    if (rows.length) sheets.push({ name: sheet.name, rows });
  });
  return sheets;
}

/**
 * Извлекает сетки из .xls/.csv через SheetJS.
 *
 * Для .csv нужна отдельная обработка: SheetJS читает CSV как текст, и без
 * указания кодировки UTF-8 без BOM превращается в мусор — все строки
 * отбрасываются, счёт = 0. Верификатор это поймал: UTF-8 без BOM и cp1251
 * (кодировка русского Excel по умолчанию) давали 0 при 300 реальных позициях.
 *
 * @param {Buffer} buf
 * @param {string} [originalName]
 * @returns {Array<{name: string, rows: Array<Array<any>>}>}
 */
function gridFromSheetJs(buf, originalName) {
  const XLSX = require('xlsx');
  const ext = String(require('path').extname(originalName || '')).toLowerCase();
  let wb;
  if (ext === '.csv') {
    wb = readCsvWorkbook(XLSX, buf);
  } else {
    wb = XLSX.read(buf, { type: 'buffer', cellDates: false, cellText: true });
  }
  const sheets = [];
  for (const name of wb.SheetNames) {
    const sheet = wb.Sheets[name];
    if (!sheet) continue;
    const aoa = XLSX.utils.sheet_to_json(sheet, { header: 1, blankrows: false, defval: '' });
    if (aoa && aoa.length) sheets.push({ name, rows: aoa });
  }
  return sheets;
}

/**
 * Читает CSV с правильной кодировкой.
 *
 * Порядок: UTF-8 с BOM → UTF-8 без BOM → cp1251 (русский Excel).
 * Определяем по наличию «кракозябр»: если после декодирования в UTF-8
 * получаются символы замены, значит файл не UTF-8.
 */
function readCsvWorkbook(XLSX, buf) {
  const raw = Buffer.isBuffer(buf) ? buf : Buffer.from(String(buf || ''));

  // 1. UTF-8 с BOM — самый надёжный вариант.
  if (raw.length >= 3 && raw[0] === 0xEF && raw[1] === 0xBB && raw[2] === 0xBF) {
    return XLSX.read(raw.slice(3).toString('utf8'), { type: 'string', raw: true });
  }

  // 2. UTF-8 без BOM: декодируем и проверяем, не появилось ли символов замены.
  const asUtf8 = raw.toString('utf8');
  if (!asUtf8.includes('\uFFFD')) {
    return XLSX.read(asUtf8, { type: 'string', raw: true });
  }

  // 3. cp1251 — кодировка русского Excel. Декодируем вручную: встроенного
  //    декодера в Node нет, а iconv может отсутствовать.
  return XLSX.read(decodeCp1251(raw), { type: 'string', raw: true });
}

/** Декодирует cp1251 → строка. Таблица соответствия для кириллицы. */
function decodeCp1251(buf) {
  const raw = Buffer.isBuffer(buf) ? buf : Buffer.from(String(buf || ''));
  const map = [];
  // 0xC0..0xFF в cp1251 — это А..я по порядку (кроме Ё/ё отдельно).
  const upper = 'АБВГДЕЖЗИЙКЛМНОПРСТУФХЦЧШЩЪЫЬЭЮЯ';
  const lower = 'абвгдежзийклмнопрстуфхцчшщъыьэюя';
  for (let i = 0; i < 32; i += 1) map[0xC0 + i] = upper[i] || '';
  for (let i = 0; i < 32; i += 1) map[0xE0 + i] = lower[i] || '';
  map[0xA8] = 'Ё';
  map[0xB8] = 'ё';
  map[0xB9] = '№';

  let out = '';
  for (let i = 0; i < raw.length; i += 1) {
    const b = raw[i];
    if (b < 0x80) out += String.fromCharCode(b);
    else out += map[b] != null ? map[b] : '';
  }
  return out;
}

/**
 * Считает позиции по всем листам файла.
 *
 * Берём СУММУ по листам, за вычетом дублей.
 *
 * История: сначала стоял максимум по листам — защита от одного перечня,
 * продублированного на двух листах («ВОР» и «Расчёт»). Но ведомости часто
 * разбиты на части: «Часть 1/2/3» или «Раздел 1/2/3» по 100 позиций. На таком
 * файле максимум давал 100 вместо 300, и разбор из 100 помечался полным —
 * то есть детектор снова слеп, ровно на том классе, который чинили.
 *
 * Поэтому: складываем все листы, но считаем копией только тот лист, который
 * почти полностью повторяет другой (совпадает и число позиций, и первые
 * названия). Части раздела повторяют друг друга редко, копии — почти всегда.
 *
 * @param {Array<{name: string, rows: Array<Array<any>>}>} sheets
 * @returns {{positions: number, perSheet: Array<{name: string, positions: number}>, source: string}}
 */
function countPositionsInSheets(sheets) {
  const list = Array.isArray(sheets) ? sheets : [];
  const perSheet = [];
  const signatures = [];

  for (const sh of list) {
    const r = countTableRows(sh.rows);
    perSheet.push({ name: sh.name, positions: r.positions });
    // Подпись — все названия листа: сравнение по первым N ломается при
    // другой сортировке строк (копия не распознаётся, счёт удваивается).
    signatures.push({ positions: r.positions, names: firstNameCells(sh.rows, Infinity) });
  }

  let total = 0;
  const kept = [];
  for (let i = 0; i < perSheet.length; i += 1) {
    if (perSheet[i].positions <= 0) continue;
    // Копия — лист, который совпадает с УЖЕ ПРИНЯТЫМ: те же названия и
    // БЛИЗКОЕ число позиций. Сравниваем только с принятыми, иначе два
    // одинаковых листа считали бы копией друг друга и оба выпадали.
    //
    // Требовать РАВНОГО числа нельзя: копия с одним прочерком вместо объёма
    // даёт 299 против 300 и не распознавалась (599 вместо 300). Допускаем
    // расхождение до 5 % — это копия с правкой, а не другой перечень.
    const isCopy = kept.some((k) => {
      const diff = Math.abs(k.positions - perSheet[i].positions);
      const bigger = Math.max(k.positions, perSheet[i].positions);
      return diff <= Math.max(2, bigger * 0.05) && sameNames(k.names, signatures[i].names);
    });
    if (isCopy) continue;
    kept.push({ positions: perSheet[i].positions, names: signatures[i].names });
    total += perSheet[i].positions;
  }

  return { positions: total, perSheet, source: 'grid' };
}

/**
 * Названия позиций листа — подпись для поиска копий.
 *
 * Берём названия из строк, где есть ЧИСЛО: это строки данных, а не заголовки
 * отчёта. Раньше бралось первое подходящее название в строке, и заголовок
 * «Ведомость объёмов работ за период» над шапкой сдвигал подпись — копия
 * не распознавалась, счёт удваивался (600 вместо 300).
 *
 * @param {Array<Array<any>>} rows
 * @param {number} n — сколько названий набрать
 * @returns {string[]}
 */
function firstNameCells(rows, n) {
  const out = [];
  for (const row of (Array.isArray(rows) ? rows : [])) {
    if (!Array.isArray(row)) continue;
    const cells = row.map((v) => normCell(v));
    // Только строки данных: в них есть число.
    if (!cells.some((s) => numCell(s) !== null)) continue;
    const name = cells.find((s) => s && isNameCell(s));
    if (!name) continue;
    // В подпись входят и ЧИСЛА строки: у трёх цехов с одинаковым составом
    // работ объёмы РАЗНЫЕ, и без чисел такие листы схлопывались как копия —
    // 100 из 300 (найдено верификатором).
    const nums = cells.map((s) => numCell(s)).filter((v) => v !== null && v >= 0).join(',');
    out.push(name + '|' + nums);
    if (out.length >= n) break;
  }
  return out;
}

/**
 * Один лист — копия другого?
 *
 * Раньше сравнивались первые 5 названий по порядку. Это ломалось в обе
 * стороны (найдено верификатором):
 *   • заголовок отчёта над шапкой сдвигал список → копия не распознана,
 *     счёт 600 вместо 300;
 *   • сортировка по-другому → то же самое;
 *   • два РАЗНЫХ листа с одинаковыми первыми названиями → ложная
 *     дедупликация, счёт 300 вместо 600.
 *
 * Теперь сравниваем ПЕРЕСЕЧЕНИЕ множеств названий: копии совпадают почти
 * полностью (≥85 %), разные перечни — нет. Порядок не важен, заголовки
 * отчёта отфильтрованы.
 *
 * @param {string[]} a
 * @param {string[]} b
 * @returns {boolean}
 */
function sameNames(a, b) {
  if (!a.length || !b.length) return false;
  const setA = new Set(a);
  const setB = new Set(b);
  let common = 0;
  for (const s of setA) if (setB.has(s)) common += 1;
  const minSize = Math.min(setA.size, setB.size);
  if (!minSize) return false;
  // Копия — это когда меньший набор ПОЧТИ ЦЕЛИКОМ содержится в большем.
  //
  // Порог 0.9 (а не 0.5): при 0.5 две части перечня с 60 общими названиями
  // из 100 считались копией, и счёт падал вдвое (200 → 100). Найдено
  // верификатором.
  //
  // Но при копии с одним прочерком вместо объёма наборы почти совпадают,
  // поэтому 0.9 срабатывает. Дополнительно сверяем размер: у копии число
  // позиций совпадает или отличается незначительно.
  return common / minSize >= 0.9;
}

/**
 * Извлекает таблицы из .docx через mammoth в HTML-режиме.
 *
 * ── Почему HTML, а не текст ───────────────────────────────────────────────
 * `mammoth.extractRawText` отдаёт ПЛОСКИЙ текст: каждая ячейка становится
 * отдельной строкой, и структура строки теряется. Считать по такому тексту
 * нельзя — 13 проходов верификатора это доказали.
 *
 * `mammoth.convertToHtml` сохраняет `<table><tr><td>`, поэтому ячейки можно
 * разложить обратно в сетку и посчитать тем же структурным счётчиком, что
 * и xlsx. Это закрывает формат, на котором детектор работал вслепую.
 *
 * @param {Buffer} buf
 * @returns {Promise<Array<{name: string, rows: Array<Array<string>>}>>}
 */
async function gridFromDocx(buf) {
  const mammoth = require('mammoth');
  const res = await mammoth.convertToHtml({ buffer: buf });
  const html = String((res && res.value) || '');
  if (!/<table/i.test(html)) return [];

  // Разбор без внешних зависимостей: таблицы → строки → ячейки.
  // mammoth экранирует содержимое, поэтому вложенных таблиц в ячейках нет.
  const tables = [];
  const tableRe = /<table\b[^>]*>([\s\S]*?)<\/table>/gi;
  let tm;
  let idx = 0;
  while ((tm = tableRe.exec(html)) !== null) {
    idx += 1;
    const rows = [];
    const trRe = /<tr\b[^>]*>([\s\S]*?)<\/tr>/gi;
    let rm;
    while ((rm = trRe.exec(tm[1])) !== null) {
      const cells = [];
      const tdRe = /<t[dh]\b[^>]*>([\s\S]*?)<\/t[dh]>/gi;
      let cm;
      while ((cm = tdRe.exec(rm[1])) !== null) {
        cells.push(htmlCellText(cm[1]));
      }
      if (cells.length) rows.push(cells);
    }
    if (rows.length) tables.push({ name: 'таблица ' + idx, rows });
  }
  return tables;
}

/** Текст ячейки HTML без тегов, с раскрытыми сущностями. */
function htmlCellText(fragment) {
  return String(fragment || '')
    .replace(/<br\s*\/?>/gi, ' ')
    .replace(/<\/(p|div)>/gi, ' ')
    .replace(/<[^>]+>/g, '')
    .replace(/&nbsp;/gi, ' ')
    .replace(/&amp;/gi, '&')
    .replace(/&lt;/gi, '<')
    .replace(/&gt;/gi, '>')
    .replace(/&quot;/gi, '"')
    .replace(/&#39;/gi, "'")
    .replace(/\s+/g, ' ')
    .trim();
}

/**
 * Конвертирует старый .doc/.xls в современный формат через LibreOffice,
 * чтобы структурный счётчик мог прочитать сетку ячеек.
 *
 * Зачем: `.doc` (OLE2) и старый `.xls` не читаются ни ExcelJS, ни mammoth
 * напрямую — для них есть только текстовый путь, а по тексту считать нельзя.
 * LibreOffice в системе уже используется для извлечения текста, поэтому
 * конвертация ничего нового не требует.
 *
 * @param {Buffer} buf
 * @param {string} originalName
 * @param {string} targetExt — '.docx' или '.xlsx'
 * @returns {Buffer|null}
 */
function convertViaLibreOffice(buf, originalName, targetExt) {
  const { spawnSync } = require('child_process');
  const os = require('os');
  const srcExt = String(require('path').extname(originalName || '') || '.doc').toLowerCase();
  let tmpDir = null;
  try {
    tmpDir = fs.mkdtempSync(path.join(os.tmpdir(), 'gridconv-'));
    const src = path.join(tmpDir, 'in' + srcExt);
    fs.writeFileSync(src, buf);

    const bins = [
      'soffice', 'libreoffice', '/usr/bin/soffice', '/usr/bin/libreoffice',
      'C:\\Program Files\\LibreOffice\\program\\soffice.exe'
    ];
    const filter = targetExt === '.xlsx' ? 'xlsx' : 'docx';
    for (const bin of bins) {
      const profile = path.join(tmpDir, 'prof');
      try { fs.mkdirSync(profile, { recursive: true }); } catch (_) {}
      const r = spawnSync(bin, [
        '--headless', '--norestore', '--nolockcheck',
        `-env:UserInstallation=file://${profile.replace(/\\/g, '/')}`,
        '--convert-to', filter,
        '--outdir', tmpDir, src
      ], { timeout: 90000, encoding: 'utf8' });
      if (r.error || r.status !== 0) continue;
      const made = fs.readdirSync(tmpDir).find((f) => f.toLowerCase().endsWith(targetExt));
      if (!made) continue;
      return fs.readFileSync(path.join(tmpDir, made));
    }
    return null;
  } catch (_) {
    return null;
  } finally {
    if (tmpDir) { try { fs.rmSync(tmpDir, { recursive: true, force: true }); } catch (_) {} }
  }
}

/**
 * Публичная точка: считает позиции по буферу файла.
 *
 * Возвращает `positions: 0`, если формат не табличный или посчитать не удалось
 * — вызывающий код в этом случае работает без порога (не блокирует разбор).
 *
 * @param {{buf: Buffer, originalName: string}} p
 * @returns {Promise<{positions: number, perSheet: Array, source: string}>}
 */
async function countPositionsFromBuffer({ buf, originalName }) {
  const ext = String(require('path').extname(originalName || '')).toLowerCase();
  try {
    if (ext === '.xlsx') {
      const sheets = await gridFromXlsx(buf);
      return countPositionsInSheets(sheets);
    }
    if (ext === '.xls' || ext === '.csv') {
      const sheets = gridFromSheetJs(buf, originalName);
      return countPositionsInSheets(sheets);
    }
    if (ext === '.docx') {
      // Таблицы Word: структура сохраняется в HTML, поэтому считаем по сетке.
      const sheets = await gridFromDocx(buf);
      return countPositionsInSheets(sheets);
    }
    // Старые форматы: конвертируем в современный и считаем уже по нему.
    // Без этого .doc и .xls оставались бы на текстовом резерве.
    if (ext === '.doc') {
      const docx = convertViaLibreOffice(buf, originalName, '.docx');
      if (docx) {
        const sheets = await gridFromDocx(docx);
        return countPositionsInSheets(sheets);
      }
    }
    if (ext === '.xls') {
      const xlsx = convertViaLibreOffice(buf, originalName, '.xlsx');
      if (xlsx) {
        const sheets = await gridFromXlsx(xlsx);
        return countPositionsInSheets(sheets);
      }
    }
  } catch (_) {
    // Не смогли разобрать структуру — пусть вызывающий работает без порога.
  }
  return { positions: 0, perSheet: [], source: 'none' };
}

