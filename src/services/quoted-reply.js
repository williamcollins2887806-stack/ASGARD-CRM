/**
 * D-345 (заказчик 22.10.2026): «Письмо-ответ без вложений не должно создавать
 * заявку по цитате. Если в треде есть письмо с настоящим PDF — брать его.
 * Если нет — только строка "требует ручной проверки", без заявки на оплату».
 * ═══════════════════════════════════════════════════════════════════════════
 * ЧТО СЛУЧИЛОСЬ НА ПРОДЕ (заявка #27 «Комус», 34 313,65 ₽):
 *   1. Офис АГПЗ (agpz@) отправил счёт с PDF — письмо #4992.
 *   2. Настоящий PDF не разобрался: OCR вернул 0 символов → `not_invoice:other`.
 *   3. Пришёл ответ Сторожева (#4999) БЕЗ вложений — «Счёт подтверждаю, прошу
 *      оплатить», и в теле была ПРОЦИТИРОВАНА переписка со словом «Счёт на оплату».
 *   4. Классификатор увидел маркер `Счёт на оплату` в ЦИТАТЕ → `is_invoice=true`,
 *      регулярки вытащили номер и сумму оттуда → создалась заявка.
 *   Итог: документ без файла и без позиций, инициатор — не тот, кто прислал счёт.
 *
 * ПРАВИЛО, которое здесь реализовано:
 *
 *   A. Если у письма НЕТ своих вложений-счетов, то текст, состоящий в основном
 *      из цитаты, счётом не считается. Такой документ создаётся ТОЛЬКО как
 *      «требует ручной проверки» — без заявки на оплату.
 *
 *   B. Если в треде/цепочке есть письмо с настоящим счётом (PDF/картинка) —
 *      источником берётся ОНО, а не текст ответа. Тот же файл и позиции.
 *
 * Эвристика цитаты простая и предсказуемая (без ИИ):
 *   • доля «цитатных» строк (> «, «Кому:», «Тема:», «От:», дата-заголовок) выше 30%;
 *   • ИЛИ длина собственного текста (до первой цитаты) меньше 40% всего тела;
 *   • ИЛИ в собственном тексте нет ни одного реквизита счёта (суммы, ИНН, счёта).
 */

/** Отрезать цитатную часть — тот же набор маркеров, что в approval-detector. */
function stripQuoted(body) {
  // ВАЖНО: в БД многие письма лежат ОДНОЙ строкой — переносы не сохранились
  // (Яндекс/Мейл-агенты склеивают). Тогда маркеры «Кому:», «Тема:», «---»
  // оказываются внутри строки и ни один `\n...` regex не срабатывает.
  // Расставляем переносы перед типовыми маркерами цитаты — это делает разбор
  // устойчивым к склейке и НЕ портит текст, где таких маркеров нет.
  const s = String(body || '')
    .replace(/\s*Кому\s*:/gi, '\nКому:')
    .replace(/\s*Тема\s*:/gi, '\nТема:')
    .replace(/\s*Копия\s*:/gi, '\nКопия:')
    .replace(/\s*Отправлено\s*:\s*/gi, '\nОтправлено: ')
    .replace(/\s*От\s*:\s*/g, '\nОт: ')
    .replace(/\s*-{10,}\s*/g, '\n----------\n')
    .replace(/\s+(<\s*[^>\s]+@[^>\s]+\s*>)/g, '\n$1');

  const markers = [
    /\n\s*-{2,}\s*(исходное|первоначальное)\s+сообщение\s*-{2,}/i,
    /\n\s*-{5,}/,                       // «----------------» разделитель цитаты
    /\n\s*_{5,}/,
    /\n\s*Кому:\s/i,
    /\n\s*От:\s.*\n\s*(Кому|Отправлено):/i,
    /\n\s*От кого:\s/i,
    /\n\s*Отправлено:\s/i,
    /\n\s*(Пересылаю|Пересланное сообщение|Перенаправлено)/i,
    /\n\s*From:\s.*\n\s*(Sent|To):/i,
    /\n\s*On .{0,80}wrote:/i,
    /\n\s*\d{1,2}\s+[а-яё.]+\s+\d{4}\s*(?:г\.)?\s*,?\s*в\s*\d{1,2}:\d{2}/i,
    /\n\s*[^\n]{0,120}<[^>\s]+@[^>]+>\s*(?:написал|пишет)/i
  ];
  let cut = s;
  for (const re of markers) {
    const parts = cut.split(re);
    if (parts.length > 1) cut = parts[0];
  }
  // Только «>»-цитата без текстового разделителя: если ВСЕ непустые строки
  // начинаются с «>», своего текста нет вовсе.
  const nonEmpty = cut.split('\n').filter((l) => l.trim());
  if (nonEmpty.length && nonEmpty.every((l) => /^\s*>/.test(l))) return '';
  return cut.trim();
}

/**
 * Это письмо — в основном цитата чужого текста?
 * @param {string} body
 * @returns {{quoted:boolean, reason?:string, ownLen:number, totalLen:number, ownShare:number}}
 */
function detectQuotedReply(body) {
  const total = String(body || '').trim();
  if (!total) return { quoted: false, ownLen: 0, totalLen: 0, ownShare: 0 };

  const own = stripQuoted(total);
  const ownLen = own.length;
  const totalLen = total.length;
  const ownShare = totalLen ? ownLen / totalLen : 0;

  // Доля строк-цитат.
  const lines = total.split('\n');
  const quotedLines = lines.filter((l) => {
    const t = l.trim();
    if (!t) return false;
    return /^>/.test(t)
      || /^(кому|от|отправлено|тема|дата|from|to|sent|subject|date)\s*:/i.test(t)
      || /^\d{1,2}[.\/]\d{1,2}[.\/]\d{2,4}/.test(t)
      || /<[^>\s]+@[^>\s]+>/.test(t)
      || /^_{3,}|^-{2,}\s*(исходное|первоначальное)/i.test(t);
  }).length;
  const quotedShare = lines.length ? quotedLines / lines.length : 0;

  // ГЛАВНЫЙ КРИТЕРИЙ: есть ли в СОБСТВЕННОМ тексте (до цитаты) реквизиты счёта?
  // Если человек сам написал сумму/ИНН/счёт — он передаёт данные, даже если
  // следом процитировал переписку. Тогда это не «пустая цитата».
  const hasOwnRequisite = /(\d{1,3}(?:[ \u00a0]\d{3})+(?:[.,]\d{2})?|\bИНН\b|\bБИК\b|\bКПП\b|р\/с|к\/с|к оплате|итого)/i.test(own);
  if (hasOwnRequisite && ownLen >= 40) {
    return { quoted: false, ownLen, totalLen, ownShare };
  }

  // Нет своих реквизитов. Тогда смотрим, не является ли текст по сути цитатой.
  // Порог 0.5 (а не 0.4): собственный текст из 1–2 предложений при большом
  // цитируемом хвосте — это ответ, а не счёт.
  if (quotedShare > 0.3) return { quoted: true, reason: 'many_quoted_lines', ownLen, totalLen, ownShare };
  if (totalLen > 100 && ownShare < 0.5) return { quoted: true, reason: 'own_text_too_short', ownLen, totalLen, ownShare };
  if (!hasOwnRequisite && totalLen > 60) return { quoted: true, reason: 'no_own_requisites', ownLen, totalLen, ownShare };
  return { quoted: false, ownLen, totalLen, ownShare };
}

module.exports = { detectQuotedReply, stripQuoted };
