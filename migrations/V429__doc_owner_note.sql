-- V429: под-ответственные («свой человек» внутри общего аккаунта) — D-306
-- ═══════════════════════════════════════════════════════════════════════════
-- ЗАПРОС ЗАКАЗЧИКА (20.10.2026), дословно:
--   «нужно добавить такую возможность как выбирать внутри одного аккаунта
--    например АГПЗ другого ответственного. например на аккаунте АГПЗ сидят
--    4 чел. и каждый из них должен видеть свои. они как в экселе в поле
--    ответственный рядом с АГПЗ нажали добавить и вписали туда своё фио.
--    потом в следующий документ зашли и выбрали либо прошлое фио, либо новое
--    написали и уже стало 2. Тумаева Вика хочет часть документов записать и
--    потом отфильтровать на другого человека, которого нет в СРМ».
--
-- ЧТО ДЕЛАЕМ: рядом с системным владельцем (doc_owner_id) заводим СВОБОДНУЮ
-- текстовую подпись `doc_owner_note`. Это НЕ второй ответственный и НЕ роль:
--   • doc_owner_id  — кто отвечает по матрице видимости (АГПЗ = 4698 и т.д.);
--   • doc_owner_note — «чьими руками» строка внесена (Пираев, Михайлушкин,
--     Сутубалдиева, любое ФИО, которого нет в CRM).
-- Видимость по роли НЕ меняется: офис-менеджер по-прежнему видит всё
-- (FULL_VISIBILITY), но может отфильтровать реестр по подписи и увидеть
-- только «свои» строки или только строки конкретного человека.
--
-- ПОЧЕМУ НЕ НОВАЯ ТАБЛИЦА: подпись живёт ровно на строке реестра, справочника
-- не требуется. Список подсказок собирается из уже введённых значений
-- (SELECT DISTINCT) — как в Excel, без администрирования.
--
-- Индекс: фильтр и подсказки идут по (doc_owner_id, doc_owner_note).

BEGIN;

ALTER TABLE doc_registry
  ADD COLUMN IF NOT EXISTS doc_owner_note TEXT;

COMMENT ON COLUMN doc_registry.doc_owner_note IS
  'Свободная подпись «чьими руками внесено» внутри общего аккаунта (ФИО без аккаунта в CRM). Видимость по роли не меняет.';

-- Подсказки «своих» ФИО в разрезе владельца (АГПЗ → Пираев / Михайлушкин / …)
CREATE INDEX IF NOT EXISTS idx_doc_registry_owner_note
  ON doc_registry (doc_owner_id, lower(doc_owner_note))
  WHERE deleted_at IS NULL AND doc_owner_note IS NOT NULL;

COMMIT;

