-- V441: размеры СИЗ приведены к размерному ряду из Excel «Размеры персонала 2»
-- ═══════════════════════════════════════════════════════════════════════════
-- Основание: файл «Размеры персонала 2.xlsx» (лист «Размеры персонала»,
-- 202 строки) и решение заказчика от 27.10.2026.
--
-- ЧТО НЕ СХОДИЛОСЬ
--   1. Одежда. В Excel размер задан ОБХВАТОМ ГРУДИ диапазоном в см —
--      «96-100», «104-108». В CRM clothing_size — номер размера «44»…«64».
--      Прямое сопоставление невозможно: 96-100 ≠ 48, это разные системы.
--      Решение: храним и показываем как в Excel — обхват груди диапазоном.
--   2. Обувь. В Excel встречается 36…50 (женские 36-38, крупные 50),
--      а справочник CRM был 39…48 — края не выбирались и не отображались.
--   3. Рост. В Excel диапазоны «170-176», а колонка была INTEGER, поэтому
--      диапазон не сохранялся в принципе. Одиночные значения (155, 173, 176.5)
--      приводим к стандартной шкале роста.
--
-- ПРАВИЛО ОКРУГЛЕНИЯ (одинаковое для одежды и роста)
--   Диапазон берётся по СЕРЕДИНЕ значения; границы — [нижняя, верхняя),
--   верхняя граница последнего диапазона включительна.
--   Примеры: 155 → 152-158, 173 → 170-176, 176 → 176-182, 176.5 → 176-182,
--             164-168 → 164-170, 180-182 → 176-182, 192-200 → 194-200.
--
-- ВАЖНО: ничего не удаляем. Прежние вольные значения (48/50, 46 (M), 54-3,
-- «стандарт») остаются как есть до ручной правки — их видно в UI с пометкой
-- «старое», автоподстановка их не переписывает.

BEGIN;

-- ─── 1. Рост: число → диапазон ─────────────────────────────────────────────
ALTER TABLE employees
  ALTER COLUMN height TYPE VARCHAR(20)
  USING (CASE
    WHEN height IS NULL THEN NULL
    WHEN height < 146 THEN '146-152'
    WHEN height < 152 THEN '146-152'
    WHEN height < 158 THEN '152-158'
    WHEN height < 164 THEN '158-164'
    WHEN height < 170 THEN '164-170'
    WHEN height < 176 THEN '170-176'
    WHEN height < 182 THEN '176-182'
    WHEN height < 188 THEN '182-188'
    WHEN height < 194 THEN '188-194'
    WHEN height < 200 THEN '194-200'
    ELSE '200-206'
  END);

COMMENT ON COLUMN employees.height IS
  'Рост по размерному ряду, см: 146-152 … 200-206. До V441 был INTEGER. См. src/lib/ppe-sizes.js';

-- ─── 2. Запас под диапазоны ────────────────────────────────────────────────
-- «104-108» = 7 символов, но с запасом на будущее и на вольные значения.
ALTER TABLE employees
  ALTER COLUMN clothing_size TYPE VARCHAR(30);

ALTER TABLE employees
  ALTER COLUMN shoe_size TYPE VARCHAR(20);

COMMENT ON COLUMN employees.clothing_size IS
  'Обхват груди, см, диапазоном: 84-88 … 124-128 (как в Excel «Размеры персонала»). До V441 — номер размера 44…64.';
COMMENT ON COLUMN employees.shoe_size IS
  'Размер обуви EU: 36…50. См. src/lib/ppe-sizes.js';
COMMENT ON COLUMN employees.headwear_size IS
  'Размер головного убора (каска / каскетка): 54…62 или «стандарт»';

COMMIT;

