-- V440: D-382 — полный доступ к реестру для Путкова Д.В. (d.putkov, PM).
--
-- ЗАДАЧА (заказчик 27.10.2026). Диме нужен обзор всего реестра: он ведёт
-- документооборот по ОБС и готовит письма. Сейчас роль PM даёт только
-- «свои» строки (111 из 1613): он не видит ни счета других инициаторов,
-- ни ОБС-счета, ни письма к ним, поэтому не может понять, где письмо
-- есть, а где его надо сформировать.
--
-- ПОЧЕМУ НЕ МЕНЯЕМ РОЛЬ. Роль PM завязана на десятки проверок в коде и на
-- отчёты по ответственности (в «моих» документах он должен остаться PM).
-- Смена роли на OFFICE_MANAGER дала бы доступ, но сломала бы разграничение
-- в других модулях и его собственные выборки.
--
-- РЕШЕНИЕ. Персональный флаг полного обзора: `users.doc_full_view`.
-- Он расширяет ТОЛЬКО видимость реестра документов — как у бухгалтерии и
-- директоров. Права на правку полей, смену способа оплаты и прочие действия
-- остаются ролевыми: флаг даёт смотреть и скачивать, но не менять чужие
-- документы.
--
-- Идемпотентна.

-- 1. Флаг полного обзора реестра.
ALTER TABLE users
  ADD COLUMN IF NOT EXISTS doc_full_view BOOLEAN NOT NULL DEFAULT FALSE;

COMMENT ON COLUMN users.doc_full_view IS
  'D-382: полный обзор реестра документов независимо от роли (без права менять чужие). '
  'Включено для документооборота ОБС (Путков). Не влияет на остальные модули.';

-- 2. Выдать Путкову.
UPDATE users
   SET doc_full_view = TRUE, updated_at = NOW()
 WHERE id = 3465
   AND login = 'd.putkov';
