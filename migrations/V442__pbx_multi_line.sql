-- V442: Несколько операторов на линии одновременно (multi-line).
--
-- Инцидент 27.10.2026: «сделай так, чтобы на линии можно было стоять не одному,
-- а несколько человек; звонок идёт всем, кто на линии, пока кто-то не возьмёт
-- первым».
--
-- Раньше это было запрещено физически: partial-unique индекс
-- uniq_pbx_operators_single_on_line (V376) допускал РОВНО одну строку с
-- on_line = true. Плюс claimLine снимал линию у предыдущего владельца, из-за
-- чего вставший вторым «выбивал» первого (и обрывал его разговор).
--
-- Теперь линия — это «я готов принимать входящие», а не эксклюзивный ресурс.
-- Входящий звонит ВСЕМ, кто on_line, и достаётся первому ответившему.

-- 1. Снять эксклюзивность линии.
DROP INDEX IF EXISTS uniq_pbx_operators_single_on_line;

-- 2. Учёт отданных звонков — для справедливости (кто меньше взял, тот раньше
--    в очереди) и для диагностики нагрузки. Значение инкрементируется при
--    ответе оператора.
ALTER TABLE pbx_operators ADD COLUMN IF NOT EXISTS calls_taken INTEGER NOT NULL DEFAULT 0;

COMMENT ON COLUMN pbx_operators.calls_taken IS 'Сколько входящих принял оператор (для round-robin и диагностики).';

-- 3. Индекс «кто сейчас на линии» — по нему строится параллельная раздача.
CREATE INDEX IF NOT EXISTS idx_pbx_operators_on_line_active
  ON pbx_operators (on_line, user_id)
  WHERE on_line = true;

-- 4. Поля слежения за «последним активным» каналом больше не нужны как
--    эксклюзив: on_line_by сохраняем (аудит, кто встал), on_line_since — время
--    последней постановки. Меняем только их смысл в комментариях.
COMMENT ON COLUMN pbx_operators.on_line_since IS 'Когда оператор последний раз встал на линию (аудит; line НЕ эксклюзивна с V442).';
COMMENT ON COLUMN pbx_operators.on_line_by IS 'Кто поставил on_line=true (обычно сам оператор).';
