-- ============================================================================
-- V399: факт-сумма выдачи наличных (касса).
-- ----------------------------------------------------------------------------
-- Требование заказчика (17.10.2026): «кнопка Выдано с подтверждением и сразу
-- изменением суммы в кассе». Бухгалтер может выдать сумму, ОТЛИЧНУЮ от заявленной
-- (нет размена), поэтому нужна колонка фактической выдачи, а баланс кассы
-- пересчитывается по фактической сумме.
-- Идемпотентно, аддитивно. Down — V399__..._down.sql.
-- ============================================================================

ALTER TABLE cash_requests ADD COLUMN IF NOT EXISTS issued_amount NUMERIC(12,2);

-- Backfill: там, где уже выдано, фактическая = заявленной.
UPDATE cash_requests
   SET issued_amount = amount
 WHERE status = 'money_issued' AND issued_amount IS NULL;

COMMENT ON COLUMN cash_requests.issued_amount IS
  'V399: фактически выданная сумма (может отличаться от заявленной — нет размена). '
  'Баланс кассы считается по ней, а не по amount.';
