-- ЖАЛОБА ТУМАЕВОЙ (заказчик 20.10.2026): «она видит документы Аделины
-- Сатубалдиевой, хотя её документы должны быть в АГПЗ на аккаунте АГПЗ.
-- Пираев, Михайлушкин тоже АГПЗ».
--
-- ДВЕ РАЗНЫЕ ПРИЧИНЫ, не путать:
--
-- 1) ВИДИМОСТЬ (не баг). Тумаева — OFFICE_MANAGER, а эта роль в
--    doc-visibility.js входит в FULL_VISIBILITY: «видит всё». Поэтому она
--    физически видит 1575 строк, включая АГПЗ. Это задумано для офис-менеджера
--    и меняется только настройкой роли, а не данными.
--
-- 2) ВЛАДЕЛЕЦ (вот это — мой дефект). При внесении 56 счетов я свёл «Пираев С.»
--    к Тумаевой (3471), хотя у него есть СВОЙ аккаунт: алиас
--    s.piraev@asgard-service.com → user 4698 «АГПЗ (офис)». Три счёта ЭТК
--    (ДС-00015800, БР-000010073, ДС-00015152) получили владельца 3471 вместо 4698.
--    Именно их Тумаева и увидела как «чужие» — они висели среди её 327 строк.
--
-- ЧТО ДЕЛАЕМ: переводим эти три счёта на 4698 (АГПЗ). Тумаевой остаются её
-- 324 документа (офис/склад/снабжение) — их не трогаем.
--
-- ВАЖНО: НЕ переводим всё «по объекту АГПЗ» — у 17 строк Тумаевой work_id
-- указывает на АГПЗ, но владелец у них может быть законный (офисные закупки
-- для АГПЗ ведёт офис). Правим ТОЛЬКО три счёта, где владелец в Excel —
-- «Пираев С.», а он в CRM = АГПЗ.

BEGIN;

-- 1. Три счёта ЭТК: владелец Пираев → АГПЗ (4698).
UPDATE doc_registry
   SET doc_owner_id = 4698,
       updated_by = 4698,
       updated_at = NOW()
 WHERE deleted_at IS NULL
   AND doc_owner_id = 3471
   AND invoice_number IN ('ДС-00015800', 'БР-000010073', 'ДС-00015152');

-- 2. Контроль: у АГПЗ-аккаунта должен быть корректный email и активность.
UPDATE users
   SET email = 'agpz@asgard-service.com',
       is_active = true,
       updated_at = NOW()
 WHERE id = 4698
   AND (email IS NULL OR trim(email) = '');

COMMIT;

