-- V426: починить битую сумму УПД у #616 (D-301)
-- ═══════════════════════════════════════════════════════════════════════════
-- В closing_json строки #616 (2609-406003-85682, ВсеИнструменты.ру) сумма
-- записана как 9136322245006 — это пять номеров УПД, слипшихся с суммами
-- из Excel-ячейки (9136, 322), а не деньги. Такое значение ломает любую
-- арифметику закрывающих и пугает бухгалтера.
--
-- В Excel та же ячейка содержит ПЯТЬ УПД, разбитых по строкам:
--   УПД №0410003353-НШК  04.10.2026   9 136
--   УПД №0410003363-НШК  04.10.2026     322
--   УПД №0410001871-НШК  04.10.2026 245 006
--   УПД №0710013187-НШК  07.10.2026  19 770
--   УПД №1810002023-НШК  18.10.2026   5 246
--   Итого 279 480 ₽ — это сумма ЗАКРЫВАЮЩИХ, а не сумма счёта.
--
-- САМ СЧЁТ (amount_gross = 270 022) НЕ ТРОГАЕМ: это сумма счёта на оплату,
-- она пришла отдельно и она верна. Расхождение 270 022 vs 274 234 в Excel
-- (тоже число из той же склеенной ячейки) — артефакт таблицы, а не ошибка CRM.

BEGIN;

UPDATE doc_registry
   SET closing_json = '[{"kind":"УПД","no":"0410003353-НШК","date":"2026-10-04","sum":9136,"source":"excel"},{"kind":"УПД","no":"0410003363-НШК","date":"2026-10-04","sum":322,"source":"excel"},{"kind":"УПД","no":"0410001871-НШК","date":"2026-10-04","sum":245006,"source":"excel"},{"kind":"УПД","no":"0710013187-НШК","date":"2026-10-07","sum":19770,"source":"excel"},{"kind":"УПД","no":"1810002023-НШК","date":"2026-10-18","sum":5246,"source":"excel"}]'::jsonb,
       updated_at = NOW()
 WHERE id = 616
   AND deleted_at IS NULL
   AND closing_json::text LIKE '%9136322245006%';

COMMIT;
