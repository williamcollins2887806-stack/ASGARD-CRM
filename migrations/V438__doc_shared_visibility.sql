-- V438: D-379 — Пираев видит счета АГПЗ, АГПЗ видит счета Пираева.
--
-- ЗАДАЧА (заказчик 25.10.2026): «сделать так, чтобы Пираев видел не только
-- свои счета в реестре, но и счета АГПЗ, а АГПЗ видел счета Пираева».
-- Раньше все счета Пираева сливались в единый аккаунт АГПЗ, и разделить их
-- было нечем: у строки реестра один `doc_owner_id`.
--
-- ПОЧЕМУ НЕ ОДИН doc_owner_id. Пираев и АГПЗ работают на одном объекте, но
-- это разные люди с разными зонами ответственности. Смена владельца
-- «перекинула» бы историю и сломала бы отчётность по АГПЗ. Нужны ДВЕ
-- полноценные зоны видимости, которые пересекаются.
--
-- РЕШЕНИЕ. Таблица связей «строка реестра → пользователь, который её видит».
-- Основной владелец остаётся в `doc_owner_id` (история не переписывается),
-- а связь добавляет ВТОРОЙ круг видимости. Это расширяемо: завтра так же
-- подключается любой другой共享-контур без новых колонок.
--
-- Правило: связь ДВУСТОРОННЯЯ. Если Пираев видит счета АГПЗ, то АГПЗ видит
-- счета Пираева. Поэтому записи создаются парами (по одной на каждую сторону),
-- а не «владелец + гость»: у обеих сторон одинаковые права на просмотр.
--
-- Идемпотентна.

-- 1. Таблица связей видимости.
CREATE TABLE IF NOT EXISTS doc_registry_shared_view (
  doc_id      INTEGER NOT NULL REFERENCES doc_registry(id) ON DELETE CASCADE,
  user_id     INTEGER NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  granted_by  INTEGER REFERENCES users(id) ON DELETE SET NULL,
  reason      TEXT,
  created_at  TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  PRIMARY KEY (doc_id, user_id)
);

COMMENT ON TABLE doc_registry_shared_view IS
  'D-379: дополнительные пользователи, которые видят строку реестра помимо doc_owner_id/pm_id. '
  'Нужно для пересекающихся зон (Пираев ↔ АГПЗ): владелец остаётся один, видимость — у обоих.';

CREATE INDEX IF NOT EXISTS idx_doc_shared_view_user
  ON doc_registry_shared_view (user_id);

-- 2. Настройка «кто с кем делится видимостью».
--    Хранится в settings, чтобы не хардкодить id пользователей в коде:
--    завтра добавят третьего — правится настройкой, а не миграцией.
--    Пара user_ids внутри группы видит документы друг друга.
INSERT INTO settings (key, value_json)
VALUES (
  'doc_visibility_shared_groups',
  '[{"name":"АГПЗ","user_ids":[4698,4701],"note":"Пираев и офис АГПЗ видят счета друг друга (D-379)"}]'
)
ON CONFLICT (key) DO NOTHING;

-- 3. Первичное наполнение связей по текущим данным.
--    Берём все живые строки реестра, где владелец — участник группы, и
--    выдаём видимость остальным участникам. Так исторические счета Пираева
--    (сейчас они на АГПЗ) сразу становятся видны ему, а счета, оформленные
--    на сотрудников (3465 и др.), — видны обеим сторонам, если относятся
--    к тем же заявкам.
--
--    Идемпотентно: ON CONFLICT DO NOTHING.
INSERT INTO doc_registry_shared_view (doc_id, user_id, granted_by, reason)
SELECT d.id, u.uid, 1, 'D-379: shared group АГПЗ (Пираев ↔ офис АГПЗ)'
  FROM doc_registry d
  CROSS JOIN (VALUES (4698), (4701)) AS u(uid)
 WHERE d.deleted_at IS NULL
   AND d.doc_owner_id IN (4698, 4701)
   AND d.doc_owner_id <> u.uid
ON CONFLICT (doc_id, user_id) DO NOTHING;
