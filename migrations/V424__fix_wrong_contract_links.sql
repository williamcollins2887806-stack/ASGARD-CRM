-- Обе правки идемпотентны и с проверками (не тронут, если состояние иное).

BEGIN;

-- 1. Отвязать счёт ЭТК от чужого договора ТМХ.
UPDATE doc_registry
   SET contract_id = NULL,
       contract_mode = 'once',
       updated_at = NOW()
 WHERE deleted_at IS NULL
   AND id = 1523
   AND contract_id = 26
   AND regexp_replace(COALESCE(counterparty_inn, ''), '\D', '', 'g') = '3015042714';

-- 2. Привязать А-2060 к договору УК «МАГИСТР».
--    Условие: счёт именно от «Учебный Комбинат Магистр» с тем же email-доменом.
UPDATE doc_registry
   SET contract_id = 21,
       contract_mode = 'linked',
       contract_label = '№25-16/2',
       updated_at = NOW()
 WHERE deleted_at IS NULL
   AND id = 1532
   AND contract_id IS NULL
   AND counterparty_name ILIKE '%Учебный Комбинат%';

