-- V412: производственный календарь 2026–2027 + различение праздников и переносов.
--
-- Проблема: таблица work_calendar (V394) содержит ТОЛЬКО перенесённые выходные и лишь
-- отчасти — сами нерабочие праздничные дни. Для отпусков этого мало: по ст. 120 ТК РФ
-- в число календарных дней отпуска НЕ входят нерабочие праздничные дни (ст. 112), и они
-- ПРОДЛЕВАЮТ отпуск. Перенесённый выходной — не праздник: он нерабочий, но отпуск НЕ продлевает.
-- Без различения двух видов система неверно посчитает отпуск (например, 1–14 января).
--
-- Источники (официальные):
--   нерабочие праздничные дни — ст. 112 ТК РФ (1–8 января, 23.02, 08.03, 01.05, 09.05, 12.06, 04.11);
--   2026 — Постановление Правительства РФ от 24.09.2025 N 1466 (норма 247 раб. дн.);
--   2027 — Постановление Правительства РФ от 17.09.2026 N 1187 (норма 247 раб. дн.).
--
-- Расчёт рабочих дней сверен по месяцам с официальной нормой (см. tools/_check_calendar.py):
--   2026: 15/19/21/22/19/21/23/21/22/22/20/22 = 247
--   2027: 15/19/22/22/19/21/22/22/22/21/20/22 = 247

-- ── 1. Различение вида дня ──────────────────────────────────────────────────
ALTER TABLE work_calendar ADD COLUMN IF NOT EXISTS kind  varchar(16) NOT NULL DEFAULT 'holiday';
ALTER TABLE work_calendar ADD COLUMN IF NOT EXISTS title varchar(200);
ALTER TABLE work_calendar ADD COLUMN IF NOT EXISTS source varchar(64);

COMMENT ON COLUMN work_calendar.is_working IS 'false — нерабочий день (праздник или перенесённый выходной)';
COMMENT ON COLUMN work_calendar.kind IS
  'holiday — нерабочий праздничный (ст.112 ТК, ПРОДЛЕВАЕТ отпуск, ст.120); '
  'shift — выходной по переносу (НЕ продлевает отпуск); working — выходной, ставший рабочим по переносу';
COMMENT ON COLUMN work_calendar.source IS 'Основание: ст.112 ТК РФ / постановление Правительства РФ';

-- Существующие строки V394 — это переносы (по содержанию note), помечаем как shift.
UPDATE work_calendar SET kind = 'shift'
 WHERE kind = 'holiday' AND note IS NOT NULL
   AND (note ILIKE '%перенос%' OR note ILIKE '%с 0%' OR note ILIKE '%с 1%' OR note ILIKE '%с 2%');

