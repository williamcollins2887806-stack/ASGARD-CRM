-- Основание: подтверждение заказчика 27.10.2026 — «23 млн это сумма без НДС».
--
-- СОСТОЯНИЕ ДО:
--   amount         = 23 111 014,72  ← это НЕТТО (без НДС)
--   amount_ex_vat  = 20 022 987,41  ← неверно (не совпадает с amount)
--   vat_amount     =  4 405 057,23  ← НДС посчитан от 20 022 987,41, тоже неверно
--   vat_rate       = 22.0
--   amount_ex_vat + vat_amount = 24 428 044,64 ≠ amount → расхождение 1 317 029,92 ₽
--
-- Корень: в форме расхода не спрашивали, сумма с НДС или без (см. V439).
-- Строку внесли как нетто, а форма всегда считала НДС от брутто.
--
-- ЧТО ДЕЛАЕМ:
--   amount остаётся 23 111 014,72 (это верное нетто);
--   vat_basis = 'net' — явно фиксируем трактовку;
--   vat_amount = 23 111 014,72 × 22% = 5 084 423,24;
--   amount_ex_vat = amount = 23 111 014,72.
--
-- ЭФФЕКТ на отчёт #406 (проверено пересчётом на клоне):
--   вычет НДС:    4 405 057,23 →  5 084 423,24  (+679 366,01 ₽)
--   расход нетто: 18 705 957,49 → 23 111 014,72  (+4 405 057,23 ₽)
--   расходы без НДС всего: 24 405 316,34 → 28 810 373,61
--   прибыль до налога: 56 068 941,49 → 51 663 884,22  (−4 405 057,27)
--   чистая прибыль:    42 051 706,12 → 38 747 913,16  (−3 303 792,96)
--   маржа: 51,4% → 47,3%
--
-- Про копейки: цифры выше — фактический результат ПОСТРОЧНОГО расчёта
-- (каждая строка округляется до копеек, потом суммируется). Если считать
-- «от общего итога», выходит 51 663 884,26 — разница 0,04 ₽ возникает
-- только из порядка округления. Значимая цифра — 51 663 884,22.
--
-- Цифра 4 405 057,23 — это НЕТТО-прирост себестоимости, а не «−VAT»:
-- раньше строка считалась как брутто 23 111 014,72 минус НДС 4 405 057,23,
-- то есть себестоимость была занижена ровно на сумму НДС.
--
-- ВАЖНО: правим ОДНУ строку по конкретному подтверждению. Массово
-- переоценивать другие строки этим скриптом нельзя.

BEGIN;

UPDATE work_expenses
   SET vat_basis    = 'net',
       vat_rate     = 22,
       vat_amount   = ROUND(amount * 22 / 100, 2),
       amount_ex_vat = amount,
       notes        = COALESCE(notes, '') ||
                      CASE WHEN COALESCE(notes,'') = '' THEN '' ELSE ' | ' END ||
                      'V444 27.10.2026: сумма 23 111 014,72 подтверждена как без НДС; НДС пересчитан 22% от нетто',
       updated_at   = NOW()
 WHERE id = 5257
   AND work_id = 406
   -- защита от повторного применения
   AND (vat_basis IS DISTINCT FROM 'net'
        OR vat_amount IS DISTINCT FROM ROUND(amount * 22 / 100, 2));

COMMIT;

