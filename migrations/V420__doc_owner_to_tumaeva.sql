-- V420: ответственный за документы — с администратора на Тумаеву
-- ═══════════════════════════════════════════════════════════════════════════
-- Заказчик 20.10.2026: «Все документы которые есть в реестре счетов за
-- администратором нужно перевести на Тумаеву Викторию ответственный за
-- документы».
--
-- Уточнено у заказчика: переводим и строки без ответственного (чтобы ни одна
-- карточка не висела «ничьей»). Итого 40 строк: 37 с doc_owner_id = 1
-- (Администратор системы) + 3 с NULL.
--
-- ВАЖНО: 1512 строк созданы под учёткой админа (created_by = 1), но у 1475 из
-- них есть ЖИВЫЕ ответственные — Баринов (649), Тумаева (265), АГПЗ (126),
-- Вилявисенсио (113) и другие. Их НЕ ТРОГАЕМ: это рабочие документы реальных
-- сотрудников, а не «бесхозные».

BEGIN;

-- Страховка: если сотрудник уволен/удалён — не переводим на него.
DO $$
DECLARE
  v_tumaeva int;
BEGIN
  SELECT id INTO v_tumaeva
    FROM users
   WHERE email = 'office@asgard-service.com'
     AND is_active = true
   LIMIT 1;

  IF v_tumaeva IS NULL THEN
    RAISE EXCEPTION 'V420: не найден активный пользователь office@asgard-service.com (Тумаева)';
  END IF;

  UPDATE doc_registry
     SET doc_owner_id = v_tumaeva,
         updated_by   = v_tumaeva,
         updated_at   = NOW()
   WHERE deleted_at IS NULL
     AND (doc_owner_id = 1 OR doc_owner_id IS NULL);

  RAISE NOTICE 'V420: документы переведены на пользователя %', v_tumaeva;
END $$;

COMMIT;
