/**
 * hiddenRoutes.js — единый список разделов, скрытых на мобильном.
 *
 * Источник (десктоп-«истина»): public/assets/js/app.js
 *   • ADMIN_ONLY_HIDDEN — 17 разделов, скрыты у всех, кроме ADMIN (app.js:2190–2208)
 *   • MAINTENANCE_PAGES — 11 недоделанных разделов (app.js:2167–2179)
 *   • пункты NAV с navHide: true — «внутренние» экраны без своего пункта в меню
 *
 * Решение заказчика (20.10.2026): на мобильном скрываем У ВСЕХ, включая ADMIN.
 * Скрытие применяется дважды: пункт не попадает в меню «Ещё» и маршрут не
 * регистрируется в App.jsx (прямой заход уводит на главную).
 *
 * Чтобы ВЕРНУТЬ раздел — убрать строку отсюда. Больше нигде править не нужно.
 */

/** Разделы, скрытые на десктопе у всех, кроме ADMIN. */
export const HIDDEN_ADMIN_ONLY = [
  '/tasks-admin',        // Управление задачами
  '/hr-requests',        // Заявки персонала
  '/workers-schedule',   // График: Рабочие
  '/training-board',     // Обучение и допуски
  '/pm-balance',         // Баланс подотчётников
  '/alerts',             // Уведомления
  '/training',           // Обучение
  '/all-estimates',      // Свод Расчётов / Свод Контрактов
];

/** Недоделанные разделы («Страница на ремонте» на десктопе). */
export const HIDDEN_MAINTENANCE = [
  '/tenders/tenderguru-settings', // Настройки TenderGuru
];

/**
 * ВАЖНО про `/estimate-report/:id`: на десктопе он в MAINTENANCE_PAGES, но на
 * мобильном это НЕ раздел меню, а экран-деталь отчёта просчёта. В него ведут
 * живые кнопки «Открыть просчёт» из чата Мимира и из закреплённой карточки
 * просчёта. Скрывать его нельзя: пользователь нажимал бы кнопку и молча
 * выбрасывался на главную. Поэтому здесь он намеренно НЕ скрыт.
 */

/** «Внутренние» экраны без собственного пункта меню на десктопе (navHide). */
export const HIDDEN_NAVHIDE = [
  '/pm-calcs',            // Просчёты (inbox)
  '/to-calcs',            // Мои просчёты (ТО)
  '/head-to-approvals',   // Согласование (ТО)
  '/approvals',           // Согласование просчётов
  '/invoices',            // Счета и оплаты (другая сущность, не заявки на оплату)
  '/acts',                // Акты
];

/** Всё вместе — для фильтрации меню и маршрутов. */
export const HIDDEN_ROUTES = [
  ...HIDDEN_ADMIN_ONLY,
  ...HIDDEN_MAINTENANCE,
  ...HIDDEN_NAVHIDE,
];

/**
 * Скрыт ли путь. Учитывает вложенные маршруты:
 * `/estimate-report/123` считается скрытым, если скрыт `/estimate-report`.
 */
export function isHiddenRoute(path) {
  if (!path) return false;
  const clean = String(path).split('?')[0];
  return HIDDEN_ROUTES.some((h) => clean === h || clean.startsWith(h + '/'));
}
