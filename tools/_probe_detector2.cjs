const det = require('../src/services/approval-detector');
const cases = [
  'НЕ ОДОБРЯЮ',
  'не одобряю',
  'Не одобряю оплату',
  'Не буду одобрять',
  'одобрять не буду',
  'не могу одобрить',
  'не согласовываю',
  'не подписываю',
  'Добро пожаловать в проект',
  'Добро пожаловать!',
  'доброго дня',
  'добротный отчёт',
  'Добро?',
  'Добро ??',
  'оплачивайте',
  'Оплачивайте. Пока не надо',
  'согласовано, но не сейчас',
  'Согласовано\n\n-- \nС уважением',
  '> Добро',
  '>> Добро',
  'Добро\n> цитата',
];
for (const body of cases) {
  const r = det.detectApproval(body);
  console.log(`${r.approve ? 'APPROVE' : 'no     '} ${(r.word || r.negative ? 'NEG' : r.question ? 'Q' : '').padEnd(4)} | <<${body.replace(/\n/g, '\\n')}>>`);
}
