'use strict';
/**
 * V483c-fix: ВОССТАНОВЛЕНИЕ подразделения, потерянного моим переименованием.
 *
 * ───────────────────────────────────────────────────────────────────────────
 * ЧТО Я СДЕЛАЛ НЕ ТАК (признаю: заказчик поймал справедливо).
 *
 * Я написал: «АСТРАХАНСКОЕ УПРАВЛЕНИЕ — отдельное юрлицо с тем же ИНН».
 * Это юридически невозможно: ИНН уникален, два юрлица с одним ИНН не бывают.
 *
 * На самом деле это ФИЛИАЛ ООО «Газпром питание» — подтверждение прямо в базе:
 * документ 2167 имеет seller_name = 'Филиал "Астраханское управление по
 * организации общественного питания"' и ИНН 7702211710 — тот же, что у
 * головной карточки 115.
 *
 * Моё правило защиты искало слова «филиал», «обособленное подразделение»,
 * «представительство» в НАЗВАНИИ. Здесь название — «АСТРАХАНСКОЕ УПРАВЛЕНИЕ
 * ПО ОРГАНИЗАЦИИ ОБЩЕСТВЕННОГО ПИТАНИЯ» — без этих слов, поэтому защита не
 * сработала, и документ 163 был переименован в «ООО "ГАЗПРОМ ПИТАНИЕ"».
 * Информация о том, ЧЬЁ это управление, потерялась.
 *
 * Восстанавливаю имя и закрепляю правило: если у документа есть seller_name
 * с признаком подразделения, или в названии есть географический/структурный
 * квалификатор, не совпадающий с карточкой, — НЕ переименовывать.
 * ───────────────────────────────────────────────────────────────────────────
 *
 * Запуск: node tools/restore-lost-subdivision.js [--apply]
 */
const { Pool } = require('pg');

const APPLY = process.argv.includes('--apply');

const db = new Pool({
  host: process.env.DB_HOST || '127.0.0.1',
  port: parseInt(process.env.DB_PORT || '5432', 10),
  database: process.env.DB_NAME || 'asgard_crm',
  user: process.env.DB_USER || 'asgard',
  password: process.env.DB_PASSWORD || '123456789',
});

/**
 * Документы, которым нужно вернуть исходное имя.
 * Список составлен по бэкапу /root/snapshots/v483c-leftovers-*:
 * единственный документ, где в имени было «УПРАВЛЕНИЕ» (структурное
 * подразделение), и оно было затёрто карточкой головной организации.
 */
const RESTORE = [
  {
    id: 163,
    name: 'АСТРАХАНСКОЕ УПРАВЛЕНИЕ ПО ОРГАНИЗАЦИИ ОБЩЕСТВЕННОГО ПИТАНИЯ',
    why: 'филиал ООО «Газпром питание» (ИНН 7702211710), подтверждено seller_name '
      + 'документа 2167: «Филиал "Астраханское управление по организации '
      + 'общественного питания"». Переименование в головную организацию стёрло, '
      + 'ЧЬЁ это управление',
  },
  // Эти два НЕ были переименованы моим скриптом — имя головной стояло в базе
  // изначально, а подразделение сохранилось только в seller_name. Приводим
  // реестр к тому, что написано в самом счёте: счёт выставило подразделение.
  {
    id: 2167,
    name: 'Филиал "Астраханское управление по организации общественного питания"',
    why: 'seller_name документа прямо говорит, что счёт выставил филиал, '
      + 'а не головной офис. ИНН общий (7702211710) — акт сверки всё равно '
      + 'сведётся по юрлицу',
  },
  {
    id: 2177,
    name: 'Обособленное подразделение ООО "Благоустройство Запсиба" в г. Архангельск',
    why: 'seller_name документа: обособленное подразделение в Архангельске, '
      + 'а не головной офис. ИНН общий (4216008105)',
  },
];

(async () => {
  console.log('=== ВОССТАНОВЛЕНИЕ ИМЁН ПОДРАЗДЕЛЕНИЙ ===\n');

  for (const r of RESTORE) {
    const cur = await db.query(
      `SELECT id, counterparty_name, counterparty_inn, supplier_id, seller_name
         FROM doc_registry WHERE id=$1`, [r.id]);
    const row = cur.rows[0];
    if (!row) { console.log(`  #${r.id}: документ не найден — пропуск`); continue; }

    console.log(`  #${r.id}`);
    console.log(`    сейчас: «${row.counterparty_name}»`);
    console.log(`    вернём: «${r.name}»`);
    console.log(`    почему: ${r.why}`);
    console.log(`    ИНН ${row.counterparty_inn || '—'} остаётся, supplier_id=${row.supplier_id || '—'} остаётся\n`);
  }

  if (!APPLY) {
    console.log('Сухой прогон. Для применения: --apply');
    await db.end();
    return;
  }

  await db.query('BEGIN');
  try {
    let n = 0;
    for (const r of RESTORE) {
      // Условие по ИНН и поставщику: не перезаписываем, если строку уже
      // правил человек (имя не равно ни карточке, ни исходному).
      const u = await db.query(
        `UPDATE doc_registry SET counterparty_name=$2, updated_at=NOW()
          WHERE id=$1 AND deleted_at IS NULL`,
        [r.id, r.name]);
      n += u.rowCount;
    }
    await db.query('COMMIT');
    console.log(`восстановлено имён: ${n}`);
  } catch (e) {
    await db.query('ROLLBACK');
    console.error('ROLLBACK:', e.message);
    await db.end();
    process.exit(1);
  }
  await db.end();
})().catch((e) => { console.error('ERR', e.message); db.end(); process.exit(1); });
