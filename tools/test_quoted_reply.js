'use strict';
/**
 * D-345: тесты определения «письмо-ответ, всё в цитате».
 * Реальные кейсы прода: #4999 (Сторожев) — цитата; #4992 (АГПЗ, с PDF) — не цитата.
 */
const assert = require('assert');
const { detectQuotedReply } = require('../src/services/quoted-reply');

let pass = 0, fail = 0;
function t(name, fn) {
  try { fn(); console.log(`PASS  ${name}`); pass++; }
  catch (e) { console.log(`FAIL  ${name}\n      ${e.message}`); fail++; }
}

// Реальное тело письма #4999 (ответ Сторожева без вложений).
const REAL_4999 = `+ d.putkov@ Коллеги, приветствую! Счёт подтверждаю. Прошу произвести оплату через ОБС. P.S. Вижу в счёте Алкотестеры. Роман Владимирович, усиливаем контроль и ведём борьбу с пьянством среди персонала? ---------------- Кому: Олег Викторович Гажилиев (go@asgard-service.com), Андрей Александрович Сторожев (a.storozhev@asgard-service.com), Бухгалтер АСГАРД-Сервис (buh@asgard-service.com); Копия: crm@asgard-service.com, Роман Владимирович Рощупкин (r.rochshupkin@asgard-service.com), Юрий Николаевич Иванейкин (iu.ivaneikin@asgard-service.com); Тема: АГПЗ: Счет на оплату ООО "Комус" №0VT/1873865/66597749 от 22.10.2026 г. Счет на оплату № 0VT/1873865/66597749 от 22.10.2026 Итого: 34 313,65 Всего к оплате: 34 313,65`;

// Реальный текст счёта (не цитата) — так выглядит настоящее вложение после OCR.
const REAL_INVOICE_TEXT = `Счет на оплату № 276 от 22 октября 2026 г. Поставщик: ООО "УТИЛИЗАЦИЯ ОТХОДОВ", ИНН 6101006049, КПП 610101001 Банк получателя ЮГО-ЗАПАДНЫЙ БАНК ПАО СБЕРБАНК БИК 046015602 Сч. № 40702810952740002717 Итого: 62 850,00 Без налога (НДС) Всего к оплате: 62 850,00`;

console.log('=== 1. Реальные кейсы прода ===');
t('#4999 (ответ по цитате) → определён как цитата', () => {
  const r = detectQuotedReply(REAL_4999);
  assert.strictEqual(r.quoted, true, 'должен считаться цитатой');
});
t('настоящий текст счёта → НЕ цитата', () => {
  const r = detectQuotedReply(REAL_INVOICE_TEXT);
  assert.strictEqual(r.quoted, false, 'счёт не должен считаться цитатой');
});

console.log('\n=== 2. Короткое деловое письмо с суммой — не цитата ===');
t('«Прошу оплатить счёт 276 на 62 850 руб» → не цитата', () => {
  const r = detectQuotedReply('Прошу оплатить счёт 276 на 62 850 руб. Срок до 27.10.2026. ИНН 6101006049.');
  assert.strictEqual(r.quoted, false);
});

console.log('\n=== 3. Ответ с собственным текстом и цитатой ===');
t('свой текст длиннее цитаты → не цитата', () => {
  const own = 'Коллеги, проверил счёт 276 от Утилизации отходов. Сумма 62 850 рублей без НДС. ИНН 6101006049 подтверждён, договор 1302АСГ-УО/У-ХВ есть в системе. Прошу оплатить в срок до 27 октября. '.repeat(2);
  const body = own + '\n---------------\nКому: go@asgard-service.com\nТема: Счет на оплату\nИтого: 62 850';
  const r = detectQuotedReply(body);
  assert.strictEqual(r.quoted, false, 'свой текст преобладает — не цитата');
});

console.log('\n=== 4. Краевые случаи ===');
t('пустое тело → не цитата (нет данных)', () => {
  assert.strictEqual(detectQuotedReply('').quoted, false);
});
t('только цитата с ">" → цитата', () => {
  const body = '> Счет на оплату № 276\n> Итого: 62 850\n> Всего к оплате: 62 850\n> ИНН 6101006049\n> БИК 046015602';
  assert.strictEqual(detectQuotedReply(body).quoted, true);
});
t('одно слово «Ок» → цитата? нет, но и счёта нет', () => {
  // Короткое «Ок» не должно блокироваться как цитата — его отсеет классификатор,
  // потому что в нём нет признаков счёта. Здесь только проверяем, что не падаем.
  const r = detectQuotedReply('Ок');
  assert.strictEqual(typeof r.quoted, 'boolean');
});

console.log(`\n═══ ИТОГ: ${pass} PASS / ${fail} FAIL ═══`);
if (fail) process.exitCode = 1;
