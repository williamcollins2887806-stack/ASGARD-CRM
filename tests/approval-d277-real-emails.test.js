'use strict';
/**
 * D-277 (прод 19.10.2026): «Добро» директора терялось.
 * ═══════════════════════════════════════════════════════════════════════════
 * ЖИВОЙ ИНЦИДЕНТ. Директор Гажилиев (go@asgard-service.com) согласовал два
 * счёта ответом «Добро» с iPhone. В БД: 0 согласований, dir_approved_at=NULL.
 * Письма #4889 (ПРЕСС БЮРО 47 800 ₽) и #4890 (АэроОтель 8 400 + 4 000 ₽)
 * остались awaiting_dir, бухгалтерия ничего не получила.
 *
 * ДВЕ ОТДЕЛЬНЫЕ ПРИЧИНЫ (обе в approval-detector.js):
 *   1) FALSE_APPROVE без границ слова: /добро\s+пожаловать/ и /доброе\s+утро/
 *      проверялись по ВСЕМУ телу, включая ЦИТАТУ. В цитате было «Коллеги,
 *      доброе утро!» → falsePositive → согласие выброшено.
 *   2) Подпись iPhone приходит СКЛЕЕННОЙ с текстом: «ДоброОтправлено с iPhone»,
 *      потому что перенос строки в body_text не сохраняется. Токен
 *      «доброотправлено» не в whitelist → unknown_tokens.
 *
 * Тест воспроизводит РЕАЛЬНЫЕ тела из БД, а не синтетику.
 */

const { detectApproval } = require('../src/services/approval-detector');

let pass = 0, fail = 0;
const fails = [];
function check(name, got, want) {
  const ok = got === want;
  if (ok) { pass++; console.log(`  PASS ${name}`); }
  else { fail++; fails.push(name); console.log(`  FAIL ${name}: got=${got} want=${want}`); }
}

// ── Реальные тела писем из прода (письма #4889 / #4890) ────────────────────
const REAL_4889 = 'ДоброОтправлено с iPhone\n\n'
  + '19 окт. 2026 г., в 11:10, Виктория Тумаева <office@asgard-service.com> написал(а):\n\n'
  + 'Коллеги, доброе утро!\n'
  + 'Прошу согласовать производство брендированных ручек, как мы делали ранее.\n'
  + 'Сумма к оплате 47 800 руб. вкл. НДС.';

const REAL_4890 = 'ДоброОтправлено с iPhone\n\n'
  + '19 окт. 2026 г., в 13:42, Виктория Тумаева <office@asgard-service.com> написал(а):\n\n'
  + 'Коллеги,\nПрошу согласовать и оплатить счета за проживание.\n'
  + 'Сумма к оплате 8400 руб. вкл. НДС и 4000 руб. без НДС.';

console.log('── D-277: реальные письма с «Добро» ──');
check('письмо #4889 (ПРЕСС БЮРО) — согласие распознано', detectApproval(REAL_4889).approve, true);
check('письмо #4890 (АэроОтель) — согласие распознано', detectApproval(REAL_4890).approve, true);

// ── Служебные подписи мобильных клиентов ────────────────────────────────────
console.log('── подписи мобильных клиентов не глушат согласие ──');
const sigCases = [
  ['iPhone (склейка)', 'ДоброОтправлено с iPhone'],
  ['iPhone (перенос)', 'Добро\nОтправлено с iPhone'],
  ['Android (пересылка)', 'Добро\nПереслано с Android'],
  ['Apple EN', 'ok\nSent from my iPhone'],
  ['Яндекс.Почта', 'Согласовано\nОтправлено из Почты Mail.ru'],
  ['Samsung', 'Да\nОтправлено с Samsung Galaxy']
];
for (const [name, body] of sigCases) check(name, detectApproval(body).approve, true);

// ── Цитата с приветствием не убивает согласие ───────────────────────────────
console.log('── приветствие в ЦИТАТЕ не считается ложным согласием ──');
check('цитата «доброе утро!» + Добро сверху', detectApproval(
  'Добро\n\n19 окт. 2026 г., в 11:10, X <x@y.ru> написал(а):\nКоллеги, доброе утро!\nСчёт во вложении.'
).approve, true);
check('цитата «Добро пожаловать» + Да сверху', detectApproval(
  'Да\n\n> Добро пожаловать в клуб'
).approve, true);

// ── Сами ловушки обязаны остаться ловушками ─────────────────────────────────
console.log('── ловушки по-прежнему блокируются ──');
const traps = [
  ['добро пожаловать', 'Добро пожаловать в клуб'],
  ['доброе утро (само по себе)', 'Доброе утро'],
  ['добрый день', 'Добрый день'],
  ['доброжелательный', 'доброжелательный отзыв'],
  ['вопрос Оплачиваем?', 'Оплачиваем?'],
  ['вопрос Согласовать?', 'Согласовать?'],
  ['длинный текст с условием', 'Добро, но оплату придержать до получения документов'],
  ['не оплачивайте', 'Не оплачивайте'],
  ['гомоглиф (лат. p)', 'добpо'],
  ['пусто', ''],
  ['только подпись', 'Отправлено с iPhone']
];
for (const [name, body] of traps) check(name, detectApproval(body).approve, false);

// ── Скрытая инструкция после разделителя ────────────────────────────────────
console.log('── скрытая инструкция после подписи ──');
check('Добро + --- + Не оплачивайте', detectApproval('Добро\n---\nНе оплачивайте до звонка').approve, false);

console.log('\n────────────────────────────────────────');
console.log(`ИТОГ D-277: PASS ${pass} / FAIL ${fail}`);
if (fail) { console.log('FAIL:', fails.join(' | ')); process.exit(1); }
