'use strict';
/**
 * D-302 (заказчик 20.10.2026): в письме должно быть сказано, ЧТО и ГДЕ сделать.
 * ═══════════════════════════════════════════════════════════════════════════
 * Дословно: «в письме по каждому нужно указывать что и где нужно сделать.
 * оплатить или отметить оплату, поставить что СФ получена, запросить СФ или акт.
 * а то не понятно что нужно сделать пользователю».
 *
 * Было: «💳 срок оплаты: Счёт УТ-2194» — констатация типа, а не инструкция.
 * Стало: у каждой задачи два поля:
 *   action — ЧТО сделать (глагол в повелительном наклонении);
 *   where  — ГДЕ именно в карточке CRM.
 *
 * Три типа задач, и для каждого свой текст:
 *   pay_due     → оплатить + отметить оплату
 *   sf_due      → запросить СФ или акт
 *   correction  → заменить СФ/акт и снять флаг
 * Плюс просрочка меняет формулировку на «сегодня».
 */

const fs = require('fs');
const path = require('path');

let pass = 0, fail = 0;
const fails = [];
function check(name, ok, detail) {
  if (ok) { pass++; console.log(`  PASS ${name}`); }
  else { fail++; fails.push(name); console.log(`  FAIL ${name}${detail ? ' — ' + detail : ''}`); }
}

const SRC = fs.readFileSync(path.join(__dirname, '../src/services/reminder-cron.js'), 'utf8');

// ─────────────────────────────────────────────────────────────────────────
console.log('── 1. Для каждого типа задачи есть «что» и «где» ──');
{
  check('pay_due: действие «Оплатить/Подготовить оплату»', /action = 'Оплатить сегодня и отметить оплату'/.test(SRC) && /action = 'Подготовить оплату и отметить оплату'/.test(SRC));
  check('pay_due: место «В очередь оплаты» → «Отметить оплачено»', /«В очередь оплаты» → после платежа «Отметить оплачено»/.test(SRC));
  check('sf_due: действие «Запросить СФ или акт»', /action = 'Запросить СФ или акт у поставщика'/.test(SRC));
  check('sf_due: место «Закрывающие» → «СФ получена»', /«Закрывающие» → добавить номер и дату, либо «СФ получена»/.test(SRC));
  check('correction: действие «Заменить СФ/акт и снять флаг»', /action = 'Заменить СФ\/акт и снять флаг'/.test(SRC));
  check('correction: место «Снять» в баннере', /«Снять» в красном баннере/.test(SRC));
}

// ─────────────────────────────────────────────────────────────────────────
console.log('── 2. Просрочка меняет формулировку ──');
{
  check('есть отдельная ветка для просроченного pay_due', /if \(overdue\)[\s\S]{0,200}Оплатить сегодня/.test(SRC));
  check('для непросроченного — «Подготовить оплату»', /else[\s\S]{0,120}Подготовить оплату/.test(SRC));
}

// ─────────────────────────────────────────────────────────────────────────
console.log('── 3. Письмо действительно содержит эти поля ──');
{
  check('HTML выводит action', /\$\{escHtml\(l\.action\)\}/.test(SRC));
  check('HTML выводит where', /\$\{whereShort\}/.test(SRC) || /\$\{escHtml\(l\.where\)\}/.test(SRC));
  // D-303: пояснительную строку «По каждой задаче указано...» УБРАЛИ по просьбе
  // заказчика («такое не пиши»). Вместо неё — бейдж над каждым заголовком,
  // поэтому проверяем, что её действительно нет.
  check('нет канцелярской строки-пояснения в шапке', !/По каждой задаче указано/.test(SRC));
  check('бейдж статуса стоит в одной ячейке с текстом (мобильный вид)', /border-radius:999px[\s\S]{0,200}<\/div>\s*<div style="margin-top:7px/.test(SRC));
  check('текстовая версия содержит «ЧТО СДЕЛАТЬ»', /ЧТО СДЕЛАТЬ: \$\{l\.action\}/.test(SRC));
  check('текстовая версия содержит «ГДЕ»', /ГДЕ: \$\{l\.where\}/.test(SRC));
}

// ─────────────────────────────────────────────────────────────────────────
console.log('── 4. Регресс: прежние фиксы D-300 на месте ──');
{
  check('абсолютная ссылка через publicBaseUrl', /publicBaseUrl/.test(SRC));
  check('премиальный HTML через wrapEmail', /wrapEmail\(/.test(SRC));
  check('склонения через plural', /plural\(fresh\.length/.test(SRC));
  check('даты через fmtDateRu', /fmtDateRu/.test(SRC));
  check('просрочка красным', /#b91c1c/.test(SRC));
}

console.log('\n────────────────────────────────────────');
console.log(`ИТОГ D-302: PASS ${pass} / FAIL ${fail}`);
if (fail) { console.log('FAIL:', fails.join(' | ')); process.exit(1); }
