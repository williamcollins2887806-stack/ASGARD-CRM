check('объём из геометрии: метры не пересчитываются дважды', () => {
  // «Суммарная длина трубок, м» — это ДЛИНА ВСЕХ ТРУБОК, а не длина одной.
  // Поэтому 60 м и есть объём: умножать на 10 трубок нельзя (считали бы её
  // дважды). Проверено на реальном тендере 2138 (12.11.2026): в «Форме»
  // стоят 899 трубок и суммарная длина 5475 м при длине трубки 6090 мм =
  // 6,09 м; 899 × 6,09 = 5474,91 — то есть 5475 это уже итог.
  const { XLSX, wb } = fakeWorkbook([['Л', [
    ['Наименование', 'Количество труб, шт', 'Суммарная длина трубок, м', 'Период'],
    ['Аппарат А', '10', '60', 'май']
  ]]]);
  const r = es.parseWorkbook(XLSX, wb);
  eq(r.positions[0].volume, 60, 'суммарная длина — уже итог, не умножаем на трубки');
  eq(r.positions[0].unit, 'п.м');
});

check('объём из геометрии: «мм» в слове «Суммарная» не делает из метров миллиметры', () => {
  // Подстрока «мм» есть внутри слова «суММарная». Проверка /мм/i пересчитывала
  // 5475 м как 5,475 м, а потом умножала на 899 трубок — объём завышался в
  // 899 раз. Два дефекта взаимно маскировались и давали «правдоподобные» 4922.
  const { XLSX, wb } = fakeWorkbook([['Л', [
    ['Наименование', 'Количество труб, шт', 'Суммарная длина трубок, м', 'Период'],
    ['Аппарат А', '899', '5474.91', 'апрель']
  ]]]);
  const r = es.parseWorkbook(XLSX, wb);
  eq(r.positions[0].volume, 5474.91, 'метры не пересчитываются в миллиметры');
});

