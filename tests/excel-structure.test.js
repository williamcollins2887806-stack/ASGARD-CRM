// ── Числовые поля: кратность и геометрия ────────────────────────────────────
check('clean_count: колонка метода (текст) не крадёт числовое поле', () => {
  // Реальная дефектная ведомость 2138: две колонки со словом «чистк».
  // «Метод_очистки» — текст и заполнен в 100 %, «Кол_во_чисток» — число.
  // По весам заголовка выигрывал текст, и clean_count был null у ВСЕХ позиций.
  const { XLSX, wb } = fakeWorkbook([['Л', [
    ['Наименование', 'Объём', 'Метод_очистки', 'Кол_во_чисток'],
    ['Аппарат А', '100', 'Гидродинамическая чистка внутренней поверхности', '1'],
    ['Аппарат Б', '200', 'Гидромеханическая чистка трубок', '2'],
    ['Аппарат В', '300', 'Химическая промывка', '3'],
    ['Аппарат Г', '400', 'Гидродинамическая чистка', '1']
  ]]]);
  const r = es.parseWorkbook(XLSX, wb);
  eq(r.positions.length, 4);
  eq(r.positions[0].clean_count, 1, 'кратность первой позиции');
  eq(r.positions[1].clean_count, 2, 'кратность второй позиции');
  eq(r.positions[2].clean_count, 3, 'кратность третьей позиции');
  // Ни у одной позиции кратность не должна быть null при наличии колонки.
  eq(r.positions.filter((p) => p.clean_count == null).length, 0, 'есть позиции без кратности');
  eq(r.positions[0].clean_count_source, 'document', 'источник кратности');
});

