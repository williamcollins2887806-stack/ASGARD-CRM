'use strict';

/**
 * tests/intake-markdown.test.js
 *
 * D-398 (инцидент 08.11.2026): vision-OCR возвращает текст в Markdown, и
 * классификатор перестаёт узнавать настоящий счёт.
 *
 * Реальный случай: счёт ИП Гомзяковой (письмо #5352, скан без текстового слоя).
 * OCR прочитал всё — номер 115559, дата 05.11.2026, БИК, р/с, суммы (1129
 * символов). Но ответ пришёл размеченным (`**БИК:** 044525593`), регулярка
 * классификатора `БИК[\s:№]*\d{9}` двоеточие после `**` не пропустила →
 * `kind=other, reason=no_bank` → файл отклонён как «не счёт», строка в реестр
 * не попала.
 *
 * Тест держит три вещи:
 *   1. stripMarkdown реально снимает разметку и не портит обычный текст;
 *   2. классификатор узнаёт счёт и БЕЗ стрипа (второй барьер в BANK_RE);
 *   3. на реальном фрагменте счёта Гомзяковой результат — invoice.
 */

process.env.DB_PASSWORD = process.env.DB_PASSWORD || 'test-not-used';

const test = require('node:test');
const assert = require('node:assert');

const { stripMarkdown } = require('../src/services/doc-email-intake');
const { classifyDocument } = require('../src/services/doc-classifier');

// Реальный фрагмент того, что вернул vision-OCR по скану Гомзяковой.
const GOMZYAKOVA_OCR = `**Тип документа:** Счёт
**Номер:** 115559
**Дата:** 05.11.2026

**Поставщик:** ООО "Асгард-Сервис"
**ИНН:** 7736244785
**КПП:** 770101001
**Банк:** АО "Альфа-Банк" г. Москва
**Расчётный счёт:** 40702810502260000343
**Корреспондентский счёт:** 30101810200000000593
**БИК:** 044525593

**Покупатель:** Индивидуальный предприниматель Гомзякова Анна Михайловна

**Таблица:**
| Наименование | Кол-во | Сумма |
| Услуга по обращению с отходами | 1 | 500,00 |

**Итого:** 500,00`;

// ─── 1. Стрип разметки ────────────────────────────────────────────────────
test('stripMarkdown снимает жирный, заголовки и таблицы', () => {
  const out = stripMarkdown(GOMZYAKOVA_OCR);
  assert.ok(!/\*\*/.test(out), 'жирного `**` не осталось');
  assert.ok(/БИК: 044525593/.test(out), 'БИК читается как обычная строка');
  assert.ok(/Расчётный счёт: 40702810502260000343/.test(out), 'р/с читается');
  assert.ok(/Номер: 115559/.test(out), 'номер счёта на месте');
  assert.ok(/Дата: 05\.11\.2026/.test(out), 'дата на месте');
  assert.ok(/Гомзякова/.test(out), 'контрагент на месте');
  assert.ok(!/\|/.test(out), 'разделители таблицы убраны');
});

test('stripMarkdown не портит обычный текст счёта', () => {
  // Текстовый слой нормального PDF: никакой разметки — функция обязана
  // вернуть строку БЕЗ изменений (иначе сломаем тысячи рабочих счетов).
  const plain = [
    'Счёт на оплату № 45 от 13.10.2026',
    'Поставщик: ООО «Ромашка», ИНН 7701234567',
    'Банк: АО «Альфа-Банк»',
    'Р/с 40702810502260000343, БИК 044525593',
    'Итого к оплате: 1 200,00 руб.',
  ].join('\n');
  assert.strictEqual(stripMarkdown(plain), plain, 'текст без разметки не меняется');
});

test('stripMarkdown не срезает дефис-разделитель сумм в середине строки', () => {
  // «ДС-26027738» и «КР-433п26» — номера с дефисом, они должны остаться.
  const s = 'Счёт № ДС-26027738 от 19.10.2026\nДоговор КР-433п26';
  assert.ok(/ДС-26027738/.test(stripMarkdown(s)), 'номер с дефисом цел');
  assert.ok(/КР-433п26/.test(stripMarkdown(s)), 'договор с дефисом цел');
});

test('stripMarkdown убирает маркеры списков и нумерацию заголовков', () => {
  const s = '## Работы\n- Вывоз отходов\n* Аренда\n• Доставка\n';
  const out = stripMarkdown(s);
  assert.ok(!/^#/m.test(out), 'решётки убраны');
  assert.ok(!/^[-*•]\s/m.test(out), 'маркеры списков убраны');
  assert.ok(/Вывоз отходов/.test(out), 'содержимое списка сохранено');
});

test('stripMarkdown на пустом входе возвращает пустую строку', () => {
  assert.strictEqual(stripMarkdown(''), '');
  assert.strictEqual(stripMarkdown(null), '');
  assert.strictEqual(stripMarkdown(undefined), '');
});

// ─── 2. Классификатор: счёт Гомзяковой ────────────────────────────────────
test('D-398: счёт Гомзяковой после стрипа — invoice', () => {
  const clean = stripMarkdown(GOMZYAKOVA_OCR);
  const cls = classifyDocument(clean, { ownInn: '7736244785' });
  assert.strictEqual(cls.is_invoice, true, 'счёт признан счётом');
  assert.strictEqual(cls.kind, 'invoice');
});

test('D-398: второй барьер — классификатор узнаёт счёт даже с разметкой', () => {
  // Если стрип когда-то перестанет вызываться (новый путь intake, другой
  // воркер), счёт всё равно обязан распознаваться: BANK_RE допускает `**`
  // вокруг двоеточия. Проверяем СЫРОЙ текст без стрипа.
  const cls = classifyDocument(GOMZYAKOVA_OCR, { ownInn: '7736244785' });
  assert.strictEqual(cls.is_invoice, true,
    'разметка не должна отменять признак счёта (reason=' + cls.reason + ')');
});

// ─── 3. Регресс: не-счета не превратились в счета ─────────────────────────
test('D-398: договор и УПД после стрипа остаются НЕ счетами', () => {
  const contract = '**Договор поставки № 12-03/1339**\n**Дата:** 12.03.2025\n**Стороны:** ООО «Асгард-Сервис» и ООО «Ромашка»\n**Предмет:** поставка оборудования';
  const c1 = classifyDocument(stripMarkdown(contract), { ownInn: '7736244785' });
  assert.strictEqual(c1.is_invoice, false, 'договор не должен стать счётом');

  const waybill = '**Универсальный передаточный документ**\n**Номер:** УПД-123\n**Дата:** 31.10.2026\n**БИК:** 044525593';
  const c2 = classifyDocument(stripMarkdown(waybill), { ownInn: '7736244785' });
  assert.strictEqual(c2.is_invoice, false, 'УПД не должен стать счётом');
});

test('D-398: наш ИНН как продавец по-прежнему отсекается', () => {
  // Собственное исходящее письмо: внутри цитируется чужой счёт, но «Исх. №»
  // и наш ИНН выдают, что документ наш. Не должно стать входящим счётом.
  const own = 'Исх. №261023-07\nООО «Асгард-Сервис», ИНН 7736244785\nБИК 044525593\nР/с 40702810502260000343\nПрилагаем счёт на оплату № УТ-2372';
  const cls = classifyDocument(stripMarkdown(own), { ownInn: '7736244785' });
  assert.strictEqual(cls.is_invoice, false, 'своё письмо не становится счётом к оплате');
});

// ─── 4. Путаница ролей продавец/покупатель в OCR ──────────────────────────
// D-398, вторая часть. Даже после стрипа разметки OCR ставил НАШИ реквизиты
// в «Поставщик», а настоящего поставщика — в «Покупатель». Входной счёт при
// этом не создавался: intake считал документ своим исходящим.
//
// Признак, по которому ловится путаница (реализован в doc-email-intake.js):
// документ — «Счёт на оплату» с просьбой оплатить, продавцом указаны МЫ, и
// при этом НЕТ нашего исходящего номера «Исх. №». Счёт, который выставляем мы,
// всегда имеет исходящий номер.

test('D-398: счёт с нашим ИНН в роли поставщика и просьбой оплатить — не «наш документ»', () => {
  // Ровно тот текст, что вернул OCR по скану Гомзяковой после стрипа.
  const text = stripMarkdown(GOMZYAKOVA_OCR) + '\nПросим оплатить счёт № 115559 от 05.11.2026 на сумму 500,00 руб.';
  const outgoingNo = /^\s*Исх\.?\s*№/im.test(text);
  const asksToPay = /(просим\s+оплатить|оплата\s+данного\s+сч[её]та|оплатить\s+сч[её]т)/i.test(text);
  const invoiceLike = /(сч[её]т\s+на\s+оплату|сч[её]т\s*(?:№|N|No)\.?\s*[\w\-/]+)/i.test(text);

  assert.strictEqual(outgoingNo, false, 'исходящего номера «Исх. №» нет');
  assert.strictEqual(asksToPay, true, 'в документе есть просьба оплатить');
  assert.strictEqual(invoiceLike, true, 'документ оформлен как счёт');
  // Комбинация «просит оплатить + нет исходящего номера» = роли перепутаны,
  // значит документ ВХОДЯЩИЙ и должен попасть в реестр.
  assert.ok(!outgoingNo && asksToPay && invoiceLike,
    'условие «роли перепутаны» выполняется — счёт не должен отбрасываться');
});

test('D-398: настоящий свой исходящий счёт всё равно отсекается', () => {
  // У нашего исходящего счёта ЕСТЬ «Исх. №» — путаницы нет, отбрасываем.
  const ownInvoice = [
    'Исх. №261023-11 от 23.10.2026',
    'Счёт на оплату № А-2127 от 23.10.2026',
    'Поставщик: ООО «Асгард-Сервис», ИНН 7736244785, БИК 044525593',
    'Р/с 40702810502260000343',
    'Просим оплатить счёт на сумму 103 150,00 руб.',
  ].join('\n');
  const outgoingNo = /^\s*Исх\.?\s*№/im.test(ownInvoice);
  assert.strictEqual(outgoingNo, true, 'у своего письма есть «Исх. №» → остаётся «нашим документом»');
});
