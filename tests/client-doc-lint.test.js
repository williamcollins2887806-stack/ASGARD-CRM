/* ═════════ 3. Негативный контроль: машинные артефакты ═════════ */

const ARTIFACTS = [
  'Срок выполнения: {{deadline}}.',
  'Важно: **срок 20 дней**.',
  '### Условия выполнения работ',
  '- очистка аппаратов\n- промывка линий',
  '```json\n{"a":1}\n```',
  '<b>Стоимость</b> фиксированная.',
  'Срок уточняется, TBD по объёму.',
  'Текст по шаблону TODO дописать.',
  'Поле customer_name: не заполнено.',
  'Условие: null.',
  'Показатель: undefined.',
  'Готовность True.',
  'Перенос строки \\n в тексте.',
  'Битый символ \uFFFD в тексте.'
];

check('пойманы ВСЕ артефакты (' + ARTIFACTS.length + ' шт.)', () => {
  const missed = [];
  for (const c of ARTIFACTS) {
    const k = kinds(c);
    if (k.indexOf('artifact') === -1) missed.push(JSON.stringify(c));
  }
  assert.deepStrictEqual(missed, [], 'не поймано: ' + missed.join(' | '));
});

check('пойманы словоформы вне перечисления (найдено верификатором)', () => {
  // Раньше словарь перечислял падежи руками, и эти формы проскакивали.
  const missed = ['Маржи по сделке 22%', 'наценке 15%', 'Прибыль по сделке 480 000 руб.',
    'Налог на прибыль 20%', 'Страховые взносы 30% учтены', 'Проезд персонала оплачивает подрядчик']
    .filter((s) => kinds(s).indexOf('internal') === -1);
  assert.deepStrictEqual(missed, [], 'проскочило: ' + missed.join(' | '));
});

check('НЕГАТИВ: штамп, разорванный переносом строки из PDF, ловится', () => {
  // pdf-parse вставляет \n в точках переноса вёрстки. Раньше гейт был слеп,
  // и «Таким \nобразом» доезжало до готового PDF для заказчика.
  const broken = [
    'Таким\nобразом, выполняем работы.',
    'В\nрамках договора.',
    'фонд\nоплаты труда',
    'транспортные\nрасходы',
    'себестоимость\nработ'
  ];
  const missed = broken.filter((s) => kinds(s, { skipNumbers: true }).length === 0);
  assert.deepStrictEqual(missed, [], 'перенос строки спрятал: ' + JSON.stringify(missed));
});

check('НДС и обычная «оплата» не считаются внутренней кухней', () => {
  const clean = [
    'Стоимость работ 1 250 000,00 руб., включая НДС 20%.',
    'НДС 22%: 275 000,00 руб.',
    'Стоимость включает налог на добавленную стоимость по ставке 22%.',
    'Оплата: аванс 30% в течение 5 банковских дней.',
    'Прокладки для фланцевых соединений.',
    'Данные о режиме предоставит заказчик.',
    'Доставка реагентов на объект.'
  ];
  const bad = clean.filter((s) => lint.lintText(s).hits.length > 0);
  assert.deepStrictEqual(bad, [], 'ложные срабатывания: ' + bad.join(' | '));
});

check('«прибыла на объект» — не «прибыль» (омонимия глагола)', () => {
  // Найдено верификатором: основа `прибыл*` резала нормальный клиентский текст,
  // а API отвечал 400 lint_failed на «Бригада прибыла на объект».
  const ok = [
    'Бригада прибыла на объект за два дня до начала работ.',
    'Специалисты прибыли на площадку согласно графику.'
  ];
  const bad = ok.filter((s) => lint.lintText(s).hits.length > 0);
  assert.deepStrictEqual(bad, [], 'глагол «прибыть» принят за прибыль: ' + bad.join(' | '));
});

check('«проезд представителя заказчика» — законный текст', () => {
  const ok = ['Проезд представителя заказчика на объект обеспечивает заказчик.'];
  const bad = ok.filter((s) => lint.lintText(s).hits.length > 0);
  assert.deepStrictEqual(bad, [], 'проезд заказчика принят за наши издержки: ' + bad.join(' | '));
});

check('«проезд персонала» — наша издержка, ловится', () => {
  assert.notStrictEqual(kinds('Проезд персонала оплачивает подрядчик.').indexOf('internal'), -1);
  assert.notStrictEqual(kinds('Проезд рабочих до объекта включён в цену.').indexOf('internal'), -1);
});

check('буллет «•» из документа заказчика — не markdown-артефакт', () => {
  // Найдено на реальном OCR: «• Срок действия предложения: 30 дней» считалось
  // markdown-списком и выпадало из контекста промпта, хотя это типографика ТКП.
  const ok = ['•  Срок действия предложения: 30 дней', '• Очистка аппарата АВД'];
  const bad = ok.filter((s) => lint.lintText(s, { skipNumbers: true }).hits.length > 0);
  assert.deepStrictEqual(bad, [], 'буллет принят за markdown: ' + bad.join(' | '));
});

/* ═════════ 4. Позитивный контроль: чистый текст без ложных срабатываний ═════════ */

const CLEAN = [
  'Очистка кожухотрубного теплообменника аппарата высокого давления.',
  'Поставка и доставка реагентов на объект заказчика.',
  'Прокладки для фланцевых соединений включены в комплект.',
  'Данные о режиме работы аппарата предоставит заказчик.',
  'Общая стоимость работ составляет 1 250 000,00 руб., включая НДС.',
  'Срок выполнения работ — 20 рабочих дней с даты подписания договора.',
  'Гарантийный срок на выполненные работы — 12 месяцев.',
    'Оплата: аванс 30% в течение 5 банковских дней, остаток — по акту.',
  'Работы выполняем силами собственной бригады из 6 человек.',
  'Вывоз отходов выполняет заказчик.',
  'Объём работ согласован по техническому заданию.',
  'Оборудование предоставляем своё, без аренды.'
];

check('чистый текст НЕ даёт ложных срабатываний (' + CLEAN.length + ' шт.)', () => {
  const falsePositives = [];
  for (const c of CLEAN) {
    const r = lint.lintText(c);
    if (!r.ok) falsePositives.push(c + ' → ' + r.hits.map((h) => h.kind + ':' + h.phrase).join(','));
  }
  assert.deepStrictEqual(falsePositives, [], 'ложные срабатывания: ' + falsePositives.join(' | '));
});

/* ═════════ 5. Выдуманные суммы ═════════ */

check('сумма вне контекста ловится как alien_number', () => {
  const r = lint.lintText('Стоимость работ 1 250 000 руб.', { allowedNumbers: [1250000] });
  assert.strictEqual(r.hits.length, 0, 'своя сумма не должна считаться лишней');

  const bad = lint.lintText('Стоимость работ 1 250 000 руб., экономия 380 000 руб.', { allowedNumbers: [1250000] });
  const alien = bad.hits.filter((h) => h.kind === 'alien_number');
  assert.strictEqual(alien.length, 1, 'должна пойматься ровно одна выдуманная сумма');
  assert.ok(/380/.test(alien[0].phrase), 'должна пойматься именно 380 000');
});

check('короткие числа (дни, люди, проценты) не считаются суммами', () => {
  const r = lint.lintText('Бригада 6 человек, срок 20 дней, НДС 22%.', { allowedNumbers: [] });
  assert.strictEqual(r.hits.length, 0);
});

/* ═════════ 6. scrubText вырезает утечку целиком ═════════ */

check('scrubText вырезает предложение с себестоимостью, смысл остальных сохраняет', () => {
  const src = 'Выполняем очистку аппарата. Себестоимость работ 350 000 руб. Срок — 20 дней.';
  const out = lint.scrubText(src);
  assert.ok(!/себестоимост/i.test(out), 'себестоимость осталась: ' + out);
  assert.ok(/очистку аппарата/i.test(out), 'потерян полезный текст: ' + out);
  assert.ok(/20 дней/i.test(out), 'потерян срок: ' + out);
});

check('scrubText НЕ режет предложение из-за ИИ-штампа (лечится поле целиком)', () => {
  const src = 'Таким образом, очистку аппарата выполняем за 20 дней.';
  const out = lint.scrubText(src);
  assert.ok(out.length > 0, 'предложение не должно исчезать');
});

/* ═════════ 7. stripInternal — фильтр входа ═════════ */

check('stripInternal убирает строки с внутренними статьями', () => {
  const ctx = [
    'Объект: котельная, 2 аппарата.',
    'ФОТ: 420 000 руб.',
    'Накладные 10%: 38 000 руб.',
    'Маржа: 22%',
    'Срок работ: 14 смен.',
    'Заказчик: ООО «Ромашка».'
  ].join('\n');
  const out = lint.stripInternal(ctx);
  assert.ok(!/ФОТ/i.test(out), 'ФОТ остался: ' + out);
  assert.ok(!/накладные/i.test(out), 'накладные остались: ' + out);
  assert.ok(!/маржа/i.test(out), 'маржа осталась: ' + out);
  assert.ok(/котельная/i.test(out), 'потерян полезный контекст: ' + out);
  assert.ok(/Ромашка/i.test(out), 'потерян заказчик: ' + out);
});

/* ═════════ 8. lintDraftFields — указание поля ═════════ */

check('lintDraftFields указывает конкретное поле', () => {
  const r = lint.lintDraftFields({
    subject: 'Очистка теплообменника',
    work_description: 'Выполняем работы в рамках договора.',
    items: [{ name: 'Промывка' }, { name: 'Материально-техническое обеспечение' }]
  });
  assert.strictEqual(r.ok, false);
  const fields = r.hits.map((h) => h.field);
  assert.ok(fields.indexOf('work_description') !== -1, 'не указано поле work_description: ' + fields.join(','));
});

check('lintDraftFields не считает деньги в позициях выдуманными', () => {
  const r = lint.lintDraftFields({
    subject: 'Очистка',
    items: [{ name: 'Промывка 8 аппаратов' }]
  });
  const n = r.hits.filter((h) => h.kind === 'alien_number');
  assert.strictEqual(n.length, 0);
});

/* ═════════ 9. reconcileNumbers — гейт сумм PDF ═════════ */

check('reconcileNumbers находит все ожидаемые суммы', () => {
  const text = 'Итого без НДС: 1 250 000,00 руб. НДС 22%: 275 000,00 руб. Итого с НДС: 1 525 000,00 руб.';
  const r = lint.reconcileNumbers(text, [1250000, 1525000]);
  assert.strictEqual(r.ok, true, 'не найдено: ' + JSON.stringify(r.missing));
});

check('reconcileNumbers сообщает о пропавшей сумме', () => {
  const r = lint.reconcileNumbers('Итого: 999 000,00 руб.', [1250000]);
  assert.strictEqual(r.ok, false);
  assert.ok(r.missing.indexOf('1250000') !== -1, 'ожидали missing 1250000, получили ' + JSON.stringify(r.missing));
});

/* ═════════ 10. numKey единообразен для форматов ═════════ */

check('numKey одинаков для 1250000 / 1 250 000 / 1 250 000,00', () => {
  assert.strictEqual(lint.numKey(1250000), '1250000');
  assert.strictEqual(lint.numKey('1 250 000'), '1250000');
  assert.strictEqual(lint.numKey('1 250 000,00'), '1250000');
  assert.strictEqual(lint.numKey('1\u00a0250\u00a0000,00'), '1250000');
});

/* ═════════ итог ═════════ */

console.log('');
console.log('client-doc-lint: ' + passed + '/' + (passed + failed) + ' проверок пройдено');
if (failed) {
  console.log('');
  failures.forEach((f) => {
    console.log('FAIL: ' + f.name);
    console.log('      ' + f.error);
  });
  process.exit(1);
}
console.log('OK');
