#!/usr/bin/env node
'use strict';

/**
 * Линтер клиентских документов — негативный и позитивный контроль.
 *
 * Что доказываем:
 *  1. Каждый класс мусора реально ловится (негативный контроль): ИИ-штампы,
 *     внутренняя кухня, машинные артефакты, выдуманные суммы.
 *  2. Нормальный деловой текст не даёт ложных срабатываний (позитивный
 *     контроль): «доставка», «прокладки», «данные», «ставка» вне сметы.
 *  3. scrubText вырезает утечку, stripInternal не пускает её в промпт.
 *  4. reconcileNumbers сверяет суммы из PDF с просчётом.
 *
 * Запуск: node tests/client-doc-lint.test.js
 */

const assert = require('assert');
const lint = require('../src/services/client-doc-lint');

let passed = 0;
let failed = 0;
const failures = [];

function check(name, fn) {
  try {
    fn();
    passed += 1;
  } catch (e) {
    failed += 1;
    failures.push({ name, error: e.message });
  }
}

function kinds(text, opts) {
  return lint.lintText(text, opts).hits.map((h) => h.kind);
}

function phrases(text) {
  return lint.lintText(text).hits.map((h) => h.phrase);
}

