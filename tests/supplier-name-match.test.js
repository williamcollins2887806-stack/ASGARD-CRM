'use strict';

/**
 * V483b: контрагент из почты берётся из карточки CRM.
 *
 * Жалоба заказчика 11.11.2026: «когда создаём через почту счёт, он берёт
 * контрагента не из CRM. Например, Интернет Решения: у нас в CRM их несколько
 * с одним ИНН, но название "ооо интернет решения" и "интернет решения ооо"».
 *
 * Два дефекта:
 *   1. Поиск по имени сравнивал regexp, снимавшей только ПРЕФИКС «ООО ».
 *      Написание «Интернет Решения, ООО» (суффикс, форма 1С/ЭДО) не находилось.
 *   2. Имя из OCR писалось в реестр КАК ЕСТЬ, даже когда карточка найдена —
 *      отсюда три написания одного контрагента в одной таблице.
 *   3. Попутно: ИНН из карточки не копировался в заявку (70 заявок на проде).
 *
 * Запуск: node tests/supplier-name-match.test.js
 */

const assert = require('assert');
const { normOrgName } = require('../src/services/supplier-resolve');

let n = 0;
function t(name, fn) {
  try {
    fn();
    n += 1;
    console.log('  \u2713', name);
  } catch (e) {
    console.error('  \u2717', name);
    throw e;
  }
}

console.log('supplier-name-match (V483b)');

// ─── 1. Организационная форма в любом месте ───────────────────────────────
t('префикс: «ООО "ИНТЕРНЕТ РЕШЕНИЯ"»', () => {
  assert.strictEqual(normOrgName('ООО "ИНТЕРНЕТ РЕШЕНИЯ"'), 'интернет решения');
});

t('суффикс: «Интернет Решения, ООО» — ЭТО был дефект', () => {
  // Старая regexp снимала только «^ооо » и кавычки → результат «интернет
  // решения, ооо» ≠ «интернет решения» → карточка не находилась.
  assert.strictEqual(normOrgName('Интернет Решения, ООО'), 'интернет решения');
});

t('суффикс без запятой: «Интернет Решения ООО»', () => {
  assert.strictEqual(normOrgName('Интернет Решения ООО'), 'интернет решения');
});

t('полная форма: «Общество с ограниченной ответственностью "ИНТЕРНЕТ РЕШЕНИЯ"»', () => {
  assert.strictEqual(
    normOrgName('Общество с ограниченной ответственностью "ИНТЕРНЕТ РЕШЕНИЯ"'),
    'интернет решения');
});

// ─── 2. Три написания = один ключ (случай с прода) ────────────────────────
t('три написания с прода дают ОДИН ключ', () => {
  const keys = [
    'ООО "ИНТЕРНЕТ РЕШЕНИЯ"',
    'Интернет Решения, ООО',
    'ООО "Интернет Решения"'
  ].map(normOrgName);
  assert.deepStrictEqual(new Set(keys).size, 1, JSON.stringify(keys));
});

t('карточка CRM и имя из счёта совпадают по ключу', () => {
  // В suppliers: ООО "ИНТЕРНЕТ РЕШЕНИЯ". В счёте: Интернет Решения, ООО.
  assert.strictEqual(
    normOrgName('ООО "ИНТЕРНЕТ РЕШЕНИЯ"'),
    normOrgName('Интернет Решения, ООО'));
});

// ─── 3. Разные юрлица НЕ склеиваются ──────────────────────────────────────
t('разные контрагенты остаются разными', () => {
  assert.notStrictEqual(normOrgName('ООО "Ромашка"'), normOrgName('ООО "Лютик"'));
});

t('АО / ПАО / ИП тоже снимаются', () => {
  assert.strictEqual(normOrgName('ПАО "Ростелеком"'), 'ростелеком');
  assert.strictEqual(normOrgName('ИП Иванов Иван'), 'иванов иван');
  assert.strictEqual(normOrgName('АО "Сбербанк"'), 'сбербанк');
});

t('пустое и мусорное имя не ломают функцию', () => {
  assert.strictEqual(normOrgName(''), '');
  assert.strictEqual(normOrgName(null), '');
  assert.strictEqual(normOrgName('ООО'), '');
});

// ─── 4. Название С «ООО» внутри не режется ────────────────────────────────
t('ООО в середине названия сохраняется', () => {
  // «ООО "Завод ООО Тест"» — внутреннее ООО частью названия быть не должно
  // срезаться: снимаем только одну форму (префикс ИЛИ суффикс).
  const k = normOrgName('ООО "Завод Тест"');
  assert.strictEqual(k, 'завод тест');
});

// ─── 5. Кавычки-ёлочки и типографские ──────────────────────────────────────
t('ёлочки и типографские кавычки нормализуются', () => {
  assert.strictEqual(normOrgName('ООО «Интернет Решения»'), 'интернет решения');
  assert.strictEqual(normOrgName('ООО “Интернет Решения”'), 'интернет решения');
});

console.log(`\nOK: ${n} проверок`);
