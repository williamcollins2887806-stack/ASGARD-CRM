/**
 * Очистка наименований номенклатуры (заказчик 19.10.2026).
 * Дефект: OCR склеивает наименование с размерами/ГОСТ/фасовкой —
 * «Мат из минеральной ваты ... - 2000.1200.60 ГОСТ 21880-2022 36 руп. (5,184 м3)».
 * Мешает поиску по номенклатуре.
 *
 * Главное требование заказчика: «сделай так, чтобы такого больше не получалось,
 * но так чтобы это не ломало систему».
 */
const { splitItemName, tidyOrgName } = require('../src/lib/item-name-clean');
let pass = 0; let fail = 0;
const ok = (c, m) => { if (c) { pass++; console.log('  PASS ' + m); } else { fail++; console.log('  FAIL ' + m); } };

console.log('=== Реальный кейс БАШПРОМ: размеры/ГОСТ → артикул ===');
const r1 = splitItemName('Мат из минеральной ваты прошивной теплоизоляционный МП (СТ)-100 - 2000.1200.60 ГОСТ 21880-2022 36 руп. (5,184 м3)');
ok(r1.name === 'Мат из минеральной ваты прошивной теплоизоляционный МП (СТ)-100', 'имя очищено: ' + JSON.stringify(r1.name));
ok(/2000\.1200\.60/.test(r1.tail || ''), 'размеры в артикуле: ' + JSON.stringify(r1.tail));
ok(r1.changed === true, 'факт изменения отмечен');

console.log('\n=== НЕ ЛОМАЕМ: чистые названия остаются как есть ===');
const clean = [
  'Автоуслуги',
  'Ручка',
  'Нанесение, тиснение, гравировка, термотрансфер, брендирование',
  'Мат из минеральной ваты прошивной теплоизоляционный МП (СТ)-100'
];
for (const c of clean) {
  const r = splitItemName(c);
  ok(r.name === c && r.changed === false, 'не тронуто: ' + JSON.stringify(c.slice(0, 40)));
}

console.log('\n=== НЕ ЛОМАЕМ: размер в начале названия — часть товара ===');
for (const c of ['Кабель ВВГ 3х2,5', 'Труба Ду50', 'Болт М8х40 ГОСТ 7798-70']) {
  const r = splitItemName(c);
  ok(r.changed === false, 'не режем: ' + JSON.stringify(c));
}

console.log('\n=== ДАТЫ в услугах сохраняются (без них позиция нечитаема) ===');
const svc = splitItemName('Проживание ТРУХИН А. С. 12.10.2026 13.10.2026');
ok(svc.name.includes('Проживание') && svc.name.includes('12.10.2026'), 'дата осталась в имени: ' + JSON.stringify(svc.name));

console.log('\n=== Фасовка в скобках → артикул ===');
const pk = splitItemName('Кислота азотная 46% (27кг)');
ok(pk.name === 'Кислота азотная 46%', 'имя без фасовки: ' + JSON.stringify(pk.name));
ok(pk.tail === '(27кг)', 'фасовка в артикуле: ' + JSON.stringify(pk.tail));

console.log('\n=== Контрагент: двойные кавычки из OCR ===');
const o1 = tidyOrgName('ООО "ТД "БАШПРОМТОРГ"');
ok(o1 === 'ООО "ТД БАШПРОМТОРГ"', 'кавычки исправлены: ' + JSON.stringify(o1));
ok(tidyOrgName('ООО "ПРЕСС БЮРО"') === 'ООО "ПРЕСС БЮРО"', 'корректное имя не тронуто');
ok(tidyOrgName('ООО РВБ') === 'ООО РВБ', 'имя без кавычек не тронуто');
ok(tidyOrgName('«ООО АэроОтель»') === 'ООО АэроОтель' || tidyOrgName('«ООО АэроОтель»') === '"ООО АэроОтель"', 'ёлочки приведены к прямым: ' + JSON.stringify(tidyOrgName('«ООО АэроОтель»')));

console.log('\n────────────────────────────────────────');
console.log('ИТОГ очистки номенклатуры: PASS ' + pass + ' / FAIL ' + fail);
process.exit(fail ? 1 : 0);
