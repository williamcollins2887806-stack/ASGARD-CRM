/** Проверка отрендеренного HTML на ключевые подписи и числа. */
const fs = require('fs');
const html = fs.readFileSync(process.argv[2], 'utf8');

const must = [
  'Итого расходов без НДС',
  'С НДС (как в счетах)',
  '− НДС внутри расходов',
  'Налоговая нагрузка 55% (от 2 481 304',
  'Итого расходы + налоги',
  'НДС — расчёт с бюджетом',
  'НДС не уменьшает прибыль',
  'Округления в первичке',
  'Править не обязательно',
  'платежей ещё не зарегистрировано',
  'Выручка без НДС',
  '− Расходы без НДС',
  '− Налоговая нагрузка',
  'от выручки без НДС',
  'АО НПК «ПАНХ»',
  '23 111 015',
  '2 470 073',
  'Сумма без НДС'
];

// Чего быть НЕ должно (старые подписи, которые путали директора)
const mustNot = [
  '+ НДС к вычету',
  'На ФОТ, наличные, суточные, субподряд',
  'С учётом налогов (55%)',
  '>НДС к выч.<',
  "' + m(d.vat.deductible)",
  'Есть строки под сверку'
];

let fail = 0;
console.log('=== ДОЛЖНО БЫТЬ ===');
for (const s of must) {
  const ok = html.includes(s);
  if (!ok) fail++;
  console.log((ok ? '  OK   ' : '  FAIL ') + s);
}
console.log('');
console.log('=== НЕ ДОЛЖНО БЫТЬ ===');
for (const s of mustNot) {
  const ok = !html.includes(s);
  if (!ok) fail++;
  console.log((ok ? '  OK   ' : '  FAIL ') + s);
}
console.log('');
console.log(fail === 0 ? 'ВСЁ ПРОШЛО' : 'ПРОВАЛОВ: ' + fail);
process.exit(fail ? 1 : 0);
